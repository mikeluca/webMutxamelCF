-- ============================================================================
-- Importador semanal de clasificaciones desde el Excel de la intranet de la FFCV
--
-- El coordinador descarga a mano "ListadoClasificaciones.xlsx" y lo sube en el
-- panel (/admin/ffcv/clasificaciones). El servidor no accede a ninguna web de
-- la FFCV: solo procesa el archivo subido.
--
-- Este script crea CLASIFICACIONES: la tabla COMPLETA del grupo de cada equipo
-- del club, tal y como la da la FFCV (POSICION sin recalcular; puede haber
-- empates). EQUIPO_ID es NUESTRO equipo, el dueño de la tabla; ES_NUESTRO = 1
-- marca la fila del Mutxamel dentro de ella. Cada importación borra las filas
-- del EQUIPO_ID y las vuelve a insertar.
--
-- Reutiliza EQUIPOS_FFCV (2026-10-16_importador_partidos_ffcv.sql) para saber
-- qué grupo corresponde a cada equipo.
--
-- IMPORTANTE: este script NO se ejecuta automáticamente (el proyecto no usa
-- Flyway/Liquibase). Debe ejecutarse a mano en dev y en producción ANTES de
-- desplegar el commit que añade el importador, y con el usuario PROPIETARIO del
-- esquema (no con USER_WEB, que solo usa la aplicación).
--
-- El sinónimo necesita el nombre del esquema propietario: el script lo pide
-- (variable PROPIETARIO); también se puede definir antes con
-- DEFINE PROPIETARIO = nombre_del_esquema
-- ============================================================================

CREATE TABLE CLASIFICACIONES (
    ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EQUIPO_ID           NUMBER NOT NULL,
    COMPETICION         VARCHAR2(200) NOT NULL,
    JORNADA             NUMBER NULL,
    POSICION            NUMBER NOT NULL,
    NOMBRE_EQUIPO       VARCHAR2(150) NOT NULL,
    LETRA               VARCHAR2(2) NULL,
    ES_NUESTRO          NUMBER(1) DEFAULT 0 NOT NULL,
    PUNTOS              NUMBER NOT NULL,
    PJ                  NUMBER NOT NULL,
    PG                  NUMBER NOT NULL,
    PE                  NUMBER NOT NULL,
    PP                  NUMBER NOT NULL,
    GF                  NUMBER NOT NULL,
    GC                  NUMBER NOT NULL,
    FECHA_ULT_PARTIDO   DATE NULL,
    FECHA_IMPORTACION   TIMESTAMP NOT NULL,
    CONSTRAINT FK_CLASIFICACIONES_EQUIPO FOREIGN KEY (EQUIPO_ID) REFERENCES EQUIPO(ID),
    CONSTRAINT CK_CLASIFICACIONES_NUESTRO CHECK (ES_NUESTRO IN (0, 1))
);

CREATE INDEX IDX_CLASIFICACIONES_EQUIPO_POS ON CLASIFICACIONES (EQUIPO_ID, POSICION);

-- La aplicación se conecta como USER_WEB y accede a las tablas por sinónimo.
-- Sin estas dos líneas la pantalla falla con ORA-00942 (500 en producción).
GRANT SELECT, INSERT, UPDATE, DELETE ON CLASIFICACIONES TO USER_WEB;

CREATE SYNONYM USER_WEB.CLASIFICACIONES FOR &&PROPIETARIO..CLASIFICACIONES;

-- Comprobación 1: debe devolver 4 privilegios (DELETE, INSERT, SELECT, UPDATE)
-- y el sinónimo debe aparecer apuntando a la tabla.
SELECT PRIVILEGE
FROM USER_TAB_PRIVS_MADE
WHERE TABLE_NAME = 'CLASIFICACIONES' AND GRANTEE = 'USER_WEB'
ORDER BY PRIVILEGE;

SELECT OWNER, SYNONYM_NAME, TABLE_OWNER, TABLE_NAME
FROM ALL_SYNONYMS
WHERE OWNER = 'USER_WEB' AND SYNONYM_NAME = 'CLASIFICACIONES';

-- Comprobación 2: la tabla existe y está vacía hasta la primera importación
-- (0 filas es lo correcto ahora).
SELECT COUNT(*) AS FILAS FROM CLASIFICACIONES;
