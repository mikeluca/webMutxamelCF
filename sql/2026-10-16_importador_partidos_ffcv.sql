-- ============================================================================
-- Importador semanal de partidos desde el CSV de la intranet de la FFCV
--
-- El coordinador descarga a mano "LstPartidos.csv" los miércoles y lo sube en
-- el panel (calendario-resultados -> "Importar partidos FFCV"). El servidor no
-- accede a ninguna web de la FFCV: solo procesa el archivo subido.
--
-- Este script:
--   1. Añade a PARTIDOS el ORIGEN del partido (MANUAL | FFCV) y la JORNADA.
--      Las filas existentes quedan con ORIGEN = 'MANUAL' (nunca las toca el
--      importador).
--   2. Crea EQUIPOS_FFCV: relación (competición normalizada + letra) -> EQUIPO.
--   3. Crea DESCANSOS_EQUIPO: equipos con relación que no juegan ese fin de
--      semana.
--
-- La COMPETICION se guarda ya normalizada con la misma función que usa el
-- parser (FfcvCsvParser.normalizarCompeticion): trim, espacios colapsados,
-- "Grup - 7" -> "Grup 7" y sin espacios antes de las comas.
--
-- IMPORTANTE: este script NO se ejecuta automáticamente (el proyecto no usa
-- Flyway/Liquibase). Debe ejecutarse a mano en dev y en producción ANTES de
-- desplegar el commit que añade el importador.
-- ============================================================================

ALTER TABLE PARTIDOS ADD (ORIGEN VARCHAR2(10) DEFAULT 'MANUAL' NOT NULL);
ALTER TABLE PARTIDOS ADD (JORNADA NUMBER NULL);
ALTER TABLE PARTIDOS ADD CONSTRAINT CK_PARTIDOS_ORIGEN CHECK (ORIGEN IN ('MANUAL', 'FFCV'));

CREATE TABLE EQUIPOS_FFCV (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EQUIPO_ID    NUMBER NOT NULL,
    COMPETICION  VARCHAR2(200) NOT NULL,
    LETRA        VARCHAR2(2) NULL,
    CONSTRAINT FK_EQUIPOS_FFCV_EQUIPO FOREIGN KEY (EQUIPO_ID) REFERENCES EQUIPO(ID),
    CONSTRAINT UQ_EQUIPOS_FFCV UNIQUE (COMPETICION, LETRA)
);

CREATE INDEX IDX_EQUIPOS_FFCV_EQUIPO ON EQUIPOS_FFCV (EQUIPO_ID);

CREATE TABLE DESCANSOS_EQUIPO (
    ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EQUIPO_ID  NUMBER NOT NULL,
    FECHA      DATE NOT NULL,
    JORNADA    NUMBER NULL,
    CONSTRAINT FK_DESCANSOS_EQUIPO FOREIGN KEY (EQUIPO_ID) REFERENCES EQUIPO(ID),
    CONSTRAINT UQ_DESCANSOS_EQUIPO UNIQUE (EQUIPO_ID, FECHA)
);

-- Relación inicial, buscando EQUIPO por NOMBRE (único desde
-- 2026-09-29_equipo_nombre_unico.sql). Si algún nombre no existe en la base
-- de datos, esa fila no se inserta: la consulta de comprobación del final lo
-- lista.
INSERT INTO EQUIPOS_FFCV (EQUIPO_ID, COMPETICION, LETRA)
SELECT E.ID, R.COMPETICION, R.LETRA
FROM EQUIPO E
JOIN (
    SELECT 'Primer Equipo' NOMBRE, 'Primera FFCV, Grup 4' COMPETICION, CAST(NULL AS VARCHAR2(2)) LETRA FROM DUAL
    UNION ALL SELECT 'Filial',          'Segona FFCV, Grup 7', 'B' FROM DUAL
    UNION ALL SELECT 'Juvenil A',       'Segona FFCV Juvenil, Grup 7', 'A' FROM DUAL
    UNION ALL SELECT 'Juvenil B',       'Tercera FFCV Juvenil, Grup 19', 'B' FROM DUAL
    UNION ALL SELECT 'Cadete A',        'Primera Cadet, Grup 10', 'A' FROM DUAL
    UNION ALL SELECT 'Cadete B',        'Segona Cadet Alacant, Grup 3', 'B' FROM DUAL
    UNION ALL SELECT 'Infantil A',      'Primera Infantil, Grup 10', 'A' FROM DUAL
    UNION ALL SELECT 'Infantil B',      'Segona Infantil Alacant, Grup 3', 'B' FROM DUAL
    UNION ALL SELECT 'Alevín A',        'Primera FFCV Aleví 2n. any Alacant, Grup 1', 'A' FROM DUAL
    UNION ALL SELECT 'Alevín B',        'Segona FFCV Aleví 1r. any Alacant, F.C. - Grup 5', 'B' FROM DUAL
    UNION ALL SELECT 'Alevín C',        'Segona FFCV Aleví 2n. any Alacant, F.C. - Grup 6', 'C' FROM DUAL
    UNION ALL SELECT 'Benjamín A',      'Primera FFCV Benjamí 2n. any Alacant, Grup 1', 'A' FROM DUAL
    UNION ALL SELECT 'Benjamín B',      'Segona FFCV Benjamí 1r. any Alacant, F.C. - Grup 6', 'B' FROM DUAL
    UNION ALL SELECT 'Prebenjamín A',   'Segona FFCV Prebenjamí 2n. any Alacant, F.C. - Grup 2', 'A' FROM DUAL
    UNION ALL SELECT 'Prebenjamín B',   'Segona FFCV Prebenjamí 1r. any Alacant, F.C. - Grup 2', 'B' FROM DUAL
) R ON R.NOMBRE = E.NOMBRE;

COMMIT;

-- Comprobación: debe devolver 15 filas. Si faltan, el NOMBRE del equipo no
-- coincide con el de la tabla EQUIPO; se puede añadir la relación a mano
-- desde el panel (Equipos FFCV).
SELECT E.NOMBRE, F.COMPETICION, F.LETRA
FROM EQUIPOS_FFCV F
JOIN EQUIPO E ON E.ID = F.EQUIPO_ID
ORDER BY E.NOMBRE;
