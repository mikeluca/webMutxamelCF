-- ---------------------------------------------------------------- PARTE 0
ALTER TABLE CUERPO_TECNICO DROP CONSTRAINT FK_CUERPO_TECNICO_EQUIPO;
DROP INDEX IDX_CUERPO_TECNICO_EQUIPO_ID;
ALTER TABLE CUERPO_TECNICO DROP COLUMN EQUIPO_ID;

-- Comprobación 0 (debe devolver 0 filas)
SELECT COLUMN_NAME FROM DBA_TAB_COLUMNS
WHERE OWNER = 'SYSTEM' AND TABLE_NAME = 'CUERPO_TECNICO' AND COLUMN_NAME = 'EQUIPO_ID';

-- ------------------------------------------------------------- COMPROBACIONES
-- 1) Debe devolver 0 filas: técnicos cuyo EQUIPO no coincide con ningún equipo
SELECT CT.ID, CT.EQUIPO FROM CUERPO_TECNICO CT
WHERE CT.EQUIPO IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM EQUIPO E WHERE UPPER(TRIM(E.NOMBRE)) = UPPER(TRIM(CT.EQUIPO)));

-- 2) Informativa: personas dadas de alta más de una vez (una ficha por equipo).
--    Después del despliegue se unen con "Fusionar fichas" en el panel.
SELECT UPPER(TRIM(NOMBRE)) AS NOMBRE, UPPER(TRIM(APELLIDOS)) AS APELLIDOS, COUNT(*) AS FICHAS,
       LISTAGG(EQUIPO, ', ') WITHIN GROUP (ORDER BY EQUIPO) AS EQUIPOS
FROM CUERPO_TECNICO
GROUP BY UPPER(TRIM(NOMBRE)), UPPER(TRIM(APELLIDOS))
HAVING COUNT(*) > 1;

-- ---------------------------------------------------------------- PARTE A
CREATE TABLE CUERPO_TECNICO_EQUIPO (
    ID                 NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUERPO_TECNICO_ID  NUMBER             NOT NULL,
    EQUIPO_ID          NUMBER             NOT NULL,
    PUESTO             VARCHAR2(100 CHAR) NULL,      -- NULL = el puesto general de la ficha; solo si en ese equipo es otro
    FECHA_CREACION     TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_CT_EQUIPO_CT     FOREIGN KEY (CUERPO_TECNICO_ID) REFERENCES CUERPO_TECNICO(ID),
    CONSTRAINT FK_CT_EQUIPO_EQUIPO FOREIGN KEY (EQUIPO_ID)         REFERENCES EQUIPO(ID),
    CONSTRAINT UQ_CT_EQUIPO UNIQUE (CUERPO_TECNICO_ID, EQUIPO_ID)
);
CREATE INDEX IDX_CT_EQUIPO_EQUIPO ON CUERPO_TECNICO_EQUIPO (EQUIPO_ID);

GRANT SELECT, INSERT, UPDATE, DELETE ON SYSTEM.CUERPO_TECNICO_EQUIPO TO USER_WEB;
CREATE OR REPLACE SYNONYM USER_WEB.CUERPO_TECNICO_EQUIPO FOR SYSTEM.CUERPO_TECNICO_EQUIPO;

-- Comprobaciones A
SELECT OWNER, SYNONYM_NAME, TABLE_OWNER FROM DBA_SYNONYMS WHERE SYNONYM_NAME = 'CUERPO_TECNICO_EQUIPO';
SELECT PRIVILEGE FROM DBA_TAB_PRIVS WHERE TABLE_NAME = 'CUERPO_TECNICO_EQUIPO' AND GRANTEE = 'USER_WEB';

-- ---------------------------------------------------------------- PARTE B
-- PUESTO se deja NULL: cada relación usa el puesto general de su ficha.
INSERT INTO CUERPO_TECNICO_EQUIPO (CUERPO_TECNICO_ID, EQUIPO_ID)
SELECT CT.ID, E.ID
FROM CUERPO_TECNICO CT
JOIN EQUIPO E ON UPPER(TRIM(E.NOMBRE)) = UPPER(TRIM(CT.EQUIPO))
WHERE NOT EXISTS (SELECT 1 FROM CUERPO_TECNICO_EQUIPO X
                  WHERE X.CUERPO_TECNICO_ID = CT.ID AND X.EQUIPO_ID = E.ID);
COMMIT;

-- Comprobación B: los dos números deben coincidir
SELECT (SELECT COUNT(*) FROM CUERPO_TECNICO WHERE EQUIPO IS NOT NULL) AS TECNICOS_CON_EQUIPO,
       (SELECT COUNT(*) FROM CUERPO_TECNICO_EQUIPO) AS RELACIONES
FROM DUAL;
