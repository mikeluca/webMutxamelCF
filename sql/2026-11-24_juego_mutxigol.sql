-- ============================================================================
-- Juego de Mutxigol (app 1.0.16): perfil de jugador (alias y equipación) y puntuaciones
--
-- Qué hace:
--   * JUEGO_PERFILES: una fila por cuenta de la app con su alias para el ranking, la equipación
--     elegida (AZUL / ROSA) y si un moderador lo ha ocultado del ranking.
--     ALIAS_NORMALIZADO lo rellena el backend (mayúsculas, sin acentos ni espacios de más) y es el
--     que garantiza que no haya dos alias iguales sin distinguir mayúsculas ni acentos.
--   * JUEGO_PUNTUACIONES: cada partida guardada (juego, puntos, duración y fecha).
--   * Al borrar la cuenta (fila de USUARIOS_APP) se borran también su perfil y sus puntuaciones.
--
-- Ejecutar con el usuario propietario del esquema (SYSTEM), primero en DEV y luego en PRO.
-- ============================================================================

-- 1) Perfil del juego
CREATE TABLE JUEGO_PERFILES (
    USUARIO_APP_ID       NUMBER PRIMARY KEY,
    ALIAS                VARCHAR2(20 CHAR) NULL,
    ALIAS_NORMALIZADO    VARCHAR2(20 CHAR) NULL,
    EQUIPACION           VARCHAR2(10) DEFAULT 'AZUL' NOT NULL,
    OCULTO               NUMBER(1) DEFAULT 0 NOT NULL,
    FECHA_ALTA           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_MODIFICACION   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_JUEGO_PERFIL_USUARIO FOREIGN KEY (USUARIO_APP_ID) REFERENCES USUARIOS_APP(ID) ON DELETE CASCADE,
    CONSTRAINT UQ_JUEGO_PERFIL_ALIAS UNIQUE (ALIAS_NORMALIZADO),
    CONSTRAINT CK_JUEGO_PERFIL_EQUIP CHECK (EQUIPACION IN ('AZUL', 'ROSA')),
    CONSTRAINT CK_JUEGO_PERFIL_OCULTO CHECK (OCULTO IN (0, 1))
);
GRANT SELECT, INSERT, UPDATE, DELETE ON JUEGO_PERFILES TO USER_WEB;
CREATE SYNONYM USER_WEB.JUEGO_PERFILES FOR SYSTEM.JUEGO_PERFILES;

-- 2) Puntuaciones
CREATE TABLE JUEGO_PUNTUACIONES (
    ID                   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USUARIO_APP_ID       NUMBER NOT NULL,
    JUEGO                VARCHAR2(20) NOT NULL,
    PUNTOS               NUMBER(5) NOT NULL,
    DURACION_MS          NUMBER(10) NOT NULL,
    FECHA                TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_JUEGO_PUNT_USUARIO FOREIGN KEY (USUARIO_APP_ID) REFERENCES USUARIOS_APP(ID) ON DELETE CASCADE,
    CONSTRAINT CK_JUEGO_PUNT_JUEGO CHECK (JUEGO IN ('PENALTIS', 'TOQUES', 'ATRAPA')),
    CONSTRAINT CK_JUEGO_PUNT_PUNTOS CHECK (PUNTOS BETWEEN 0 AND 999),
    CONSTRAINT CK_JUEGO_PUNT_DURACION CHECK (DURACION_MS > 0)
);
CREATE INDEX IX_JUEGO_PUNT_JUEGO_FECHA ON JUEGO_PUNTUACIONES (JUEGO, FECHA);
CREATE INDEX IX_JUEGO_PUNT_USUARIO ON JUEGO_PUNTUACIONES (USUARIO_APP_ID, JUEGO);
GRANT SELECT, INSERT, UPDATE, DELETE ON JUEGO_PUNTUACIONES TO USER_WEB;
CREATE SYNONYM USER_WEB.JUEGO_PUNTUACIONES FOR SYSTEM.JUEGO_PUNTUACIONES;

-- 3) Comprobación: las dos tablas existen y están vacías
SELECT 'JUEGO_PERFILES' AS TABLA, COUNT(*) AS FILAS FROM JUEGO_PERFILES
UNION ALL
SELECT 'JUEGO_PUNTUACIONES', COUNT(*) FROM JUEGO_PUNTUACIONES;

