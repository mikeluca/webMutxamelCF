-- ============================================================================
-- Imágenes para redes sociales (previa y resultados del fin de semana)
--
-- Qué añade:
--   * IMAGENES_REDES: los PNG (1080x1350) que el backend genera de cada fin de semana.
--       TIPO            PREVIA (viernes 12:00) o RESULTADOS (lunes 09:00).
--       MODALIDAD       F11, F8 o F5 (una imagen, o varias páginas, por modalidad).
--       PAGINA / TOTAL_PAGINAS  1/1, 1/2, 2/2...
--       FECHA_DESDE / FECHA_HASTA  el viernes y el domingo del fin de semana.
--       VERSION         sube cada vez que se regeneran (la app renueva su caché).
--     Al regenerar, el backend borra las imágenes de ese tipo y fin de semana y las vuelve a insertar.
--
-- Solo añade una tabla: el código anterior sigue funcionando.
-- Ejecutar ANTES de desplegar, con el usuario PROPIETARIO del esquema (SYSTEM), no con USER_WEB.
-- ============================================================================

-- 1) Tabla
CREATE TABLE IMAGENES_REDES (
    ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TIPO              VARCHAR2(10) NOT NULL,
    MODALIDAD         VARCHAR2(3) NOT NULL,
    PAGINA            NUMBER(2) NOT NULL,
    TOTAL_PAGINAS     NUMBER(2) NOT NULL,
    FECHA_DESDE       DATE NOT NULL,
    FECHA_HASTA       DATE NOT NULL,
    PNG               BLOB NOT NULL,
    FECHA_GENERACION  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    VERSION           NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT CK_IMAGENES_REDES_TIPO CHECK (TIPO IN ('PREVIA', 'RESULTADOS')),
    CONSTRAINT CK_IMAGENES_REDES_MODALIDAD CHECK (MODALIDAD IN ('F11', 'F8', 'F5')),
    CONSTRAINT UQ_IMAGENES_REDES UNIQUE (TIPO, MODALIDAD, PAGINA, FECHA_DESDE)
);

CREATE INDEX IDX_IMAGENES_REDES_FECHA ON IMAGENES_REDES (FECHA_DESDE);

-- 2) Permisos y sinónimo para USER_WEB
GRANT SELECT, INSERT, UPDATE, DELETE ON IMAGENES_REDES TO USER_WEB;

CREATE SYNONYM USER_WEB.IMAGENES_REDES FOR SYSTEM.IMAGENES_REDES;

-- 3) Comprobaciones
SELECT TABLE_NAME FROM USER_TABLES WHERE TABLE_NAME = 'IMAGENES_REDES';                       -- 1 fila

SELECT TABLE_NAME, PRIVILEGE FROM USER_TAB_PRIVS
WHERE TABLE_NAME = 'IMAGENES_REDES' AND GRANTEE = 'USER_WEB';                                  -- 4 filas

