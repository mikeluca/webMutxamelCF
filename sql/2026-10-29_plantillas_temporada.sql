-- 3) Plantilla de cada jugador en cada temporada (historial y borrador de la siguiente)
CREATE TABLE JUGADOR_TEMPORADA (
    ID                   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    JUGADOR_ID           NUMBER             NOT NULL,
    TEMPORADA_ID         NUMBER             NOT NULL,
    EQUIPO_ID            NUMBER             NULL,      -- NULL = sin equipo / baja
    EQUIPO_NOMBRE        VARCHAR2(100)      NULL,      -- copia: se conserva aunque se renombre el equipo
    CATEGORIA            VARCHAR2(100)      NULL,      -- copia
    DORSAL               NUMBER(3)          NULL,
    BAJA                 NUMBER(1)          DEFAULT 0 NOT NULL,
    PENDIENTE_REVISION   NUMBER(1)          DEFAULT 0 NOT NULL,
    NOTA                 VARCHAR2(200 CHAR) NULL,      -- motivo de la revisión
    FECHA_CREACION       TIMESTAMP          NOT NULL,
    FECHA_ACTUALIZACION  TIMESTAMP          NULL,
    CONSTRAINT FK_JUG_TEMP_JUGADOR   FOREIGN KEY (JUGADOR_ID)   REFERENCES JUGADORES(ID),
    CONSTRAINT FK_JUG_TEMP_TEMPORADA FOREIGN KEY (TEMPORADA_ID) REFERENCES TEMPORADAS(ID),
    CONSTRAINT FK_JUG_TEMP_EQUIPO    FOREIGN KEY (EQUIPO_ID)    REFERENCES EQUIPO(ID),
    CONSTRAINT UQ_JUG_TEMP UNIQUE (JUGADOR_ID, TEMPORADA_ID),
    CONSTRAINT CK_JUG_TEMP_FLAGS CHECK (BAJA IN (0, 1) AND PENDIENTE_REVISION IN (0, 1))
);
CREATE INDEX IDX_JUG_TEMP_TEMP_EQUIPO ON JUGADOR_TEMPORADA (TEMPORADA_ID, EQUIPO_ID);

