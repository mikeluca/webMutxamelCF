-- 1) Rellenar EQUIPO_ID a partir del nombre
UPDATE JUGADORES J
SET J.EQUIPO_ID = (SELECT E.ID FROM EQUIPO E
                   WHERE UPPER(TRIM(E.NOMBRE)) = UPPER(TRIM(J.EQUIPO)))
WHERE J.EQUIPO IS NOT NULL;

-- 2) Plantilla de la temporada activa = situación actual
INSERT INTO JUGADOR_TEMPORADA
    (JUGADOR_ID, TEMPORADA_ID, EQUIPO_ID, EQUIPO_NOMBRE, CATEGORIA, DORSAL, FECHA_CREACION)
SELECT J.ID, T.ID, J.EQUIPO_ID, E.NOMBRE, E.CATEGORIA, J.DORSAL, SYSTIMESTAMP
FROM JUGADORES J
CROSS JOIN TEMPORADAS T
LEFT JOIN EQUIPO E ON E.ID = J.EQUIPO_ID
WHERE T.ACTIVA = 1
  AND NOT EXISTS (SELECT 1 FROM JUGADOR_TEMPORADA JT
                  WHERE JT.JUGADOR_ID = J.ID AND JT.TEMPORADA_ID = T.ID);

COMMIT;

