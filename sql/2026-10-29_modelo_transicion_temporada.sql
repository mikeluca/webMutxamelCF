-- ============================================================================
-- Modelo de datos de la transición de temporada (docs/transicion-temporada.md, §3 y §4)
--
-- Qué añade:
--   * JUGADOR_TEMPORADA: ESTADO (CONFIRMADO / PRUEBA / BAJA), CONTINUIDAD (PENDIENTE / SIGUE / NO_SIGUE / DUDA)
--     con su fecha y su usuario, y EQUIPO_DEFINITIVO (0 / 1).
--   * EQUIPO_TEMPORADA: qué equipos juegan cada temporada (y cuáles son de pretemporada).
--   * CUERPO_TECNICO_TEMPORADA: foto del cuerpo técnico de cada temporada. Se crea VACÍA: la rellena el cierre de
--     temporada (borra e inserta la temporada que se cierra, con COALESCE(CTE.PUESTO, CT.PUESTO)).
--   * TEMPORADA_ID en CLASIFICACIONES, EQUIPOS_FFCV y HORARIOS_ENTRENAMIENTO.
--   * CUOTAS_JUGADOR: el estado INCOBRABLE (morosidad).
--
-- Se ejecuta en DOS PARTES, con el usuario PROPIETARIO del esquema (no con USER_WEB), a mano en dev y en
-- producción (el proyecto no usa Flyway/Liquibase):
--
--   PARTE A (estructura): ANTES de desplegar. Solo añade columnas con valor por defecto o NULL y tablas nuevas:
--   el código anterior sigue funcionando.
--
--   PARTE B (datos y restricciones): JUSTO ANTES de desplegar el código nuevo. Rellena los datos y pone
--   TEMPORADA_ID obligatorio, así que el código anterior fallaría al insertar en esas tablas. Las sentencias de
--   datos se pueden repetir; las de restricciones (ADD/DROP CONSTRAINT, MODIFY) no: si la parte B se interrumpe,
--   hay que continuar desde la sentencia que falló.
--
-- Los datos se rellenan con la temporada activa (SELECT ID FROM TEMPORADAS WHERE ACTIVA = 1). Tiene que haber
-- exactamente una.
--
-- El sinónimo necesita el nombre del esquema propietario: el script lo pide (variable PROPIETARIO); también se
-- puede definir antes con DEFINE PROPIETARIO = nombre_del_esquema
-- ============================================================================


-- ============================================================================
-- PARTE A: estructura
-- ============================================================================

-- 1) JUGADOR_TEMPORADA. CONTINUIDAD solo tiene sentido en las filas de una temporada en borrador: no se migra nada.
ALTER TABLE JUGADOR_TEMPORADA ADD (
    ESTADO                      VARCHAR2(12) DEFAULT 'CONFIRMADO' NOT NULL,
    CONTINUIDAD                 VARCHAR2(10) DEFAULT 'PENDIENTE' NOT NULL,
    FECHA_CONTINUIDAD           TIMESTAMP NULL,
    USUARIO_APP_CONTINUIDAD_ID  NUMBER NULL,
    EQUIPO_DEFINITIVO           NUMBER(1) DEFAULT 1 NOT NULL
);

ALTER TABLE JUGADOR_TEMPORADA ADD CONSTRAINT CK_JT_ESTADO
    CHECK (ESTADO IN ('CONFIRMADO', 'PRUEBA', 'BAJA'));
ALTER TABLE JUGADOR_TEMPORADA ADD CONSTRAINT CK_JT_CONTINUIDAD
    CHECK (CONTINUIDAD IN ('PENDIENTE', 'SIGUE', 'NO_SIGUE', 'DUDA'));
ALTER TABLE JUGADOR_TEMPORADA ADD CONSTRAINT CK_JT_EQUIPO_DEFINITIVO
    CHECK (EQUIPO_DEFINITIVO IN (0, 1));
ALTER TABLE JUGADOR_TEMPORADA ADD CONSTRAINT FK_JT_USUARIO_CONTINUIDAD
    FOREIGN KEY (USUARIO_APP_CONTINUIDAD_ID) REFERENCES USUARIOS_APP(ID);

-- 2) EQUIPO_TEMPORADA
CREATE TABLE EQUIPO_TEMPORADA (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EQUIPO_ID    NUMBER NOT NULL,
    TEMPORADA_ID NUMBER NOT NULL,
    ACTIVO       NUMBER(1) DEFAULT 1 NOT NULL,
    MODALIDAD    VARCHAR2(3) NULL,
    TIPO         VARCHAR2(12) DEFAULT 'NORMAL' NOT NULL,
    CONSTRAINT FK_EQUIPO_TEMPORADA_EQUIPO FOREIGN KEY (EQUIPO_ID) REFERENCES EQUIPO(ID),
    CONSTRAINT FK_EQUIPO_TEMPORADA_TEMP FOREIGN KEY (TEMPORADA_ID) REFERENCES TEMPORADAS(ID),
    CONSTRAINT CK_EQUIPO_TEMPORADA_ACTIVO CHECK (ACTIVO IN (0, 1)),
    CONSTRAINT CK_EQUIPO_TEMPORADA_MODALIDAD CHECK (MODALIDAD IN ('F11', 'F8', 'F5')),
    CONSTRAINT CK_EQUIPO_TEMPORADA_TIPO CHECK (TIPO IN ('NORMAL', 'PRETEMPORADA')),
    CONSTRAINT UQ_EQUIPO_TEMPORADA UNIQUE (EQUIPO_ID, TEMPORADA_ID)
);

CREATE INDEX IDX_EQUIPO_TEMPORADA_TEMP ON EQUIPO_TEMPORADA (TEMPORADA_ID);

-- 3) CUERPO_TECNICO_TEMPORADA (vacía: la rellena el cierre de temporada)
CREATE TABLE CUERPO_TECNICO_TEMPORADA (
    ID                 NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUERPO_TECNICO_ID  NUMBER NOT NULL,
    TEMPORADA_ID       NUMBER NOT NULL,
    EQUIPO_ID          NUMBER NOT NULL,
    PUESTO             VARCHAR2(100 CHAR) NULL,
    CONSTRAINT FK_CTT_CUERPO_TECNICO FOREIGN KEY (CUERPO_TECNICO_ID) REFERENCES CUERPO_TECNICO(ID),
    CONSTRAINT FK_CTT_TEMPORADA FOREIGN KEY (TEMPORADA_ID) REFERENCES TEMPORADAS(ID),
    CONSTRAINT FK_CTT_EQUIPO FOREIGN KEY (EQUIPO_ID) REFERENCES EQUIPO(ID),
    CONSTRAINT UQ_CTT_FICHA_TEMPORADA_EQUIPO UNIQUE (CUERPO_TECNICO_ID, TEMPORADA_ID, EQUIPO_ID)
);

CREATE INDEX IDX_CTT_TEMPORADA_EQUIPO ON CUERPO_TECNICO_TEMPORADA (TEMPORADA_ID, EQUIPO_ID);

-- La aplicación se conecta como USER_WEB y accede a las tablas por sinónimo.
-- Sin estas líneas la pantalla falla con ORA-00942 (500 en producción).
GRANT SELECT, INSERT, UPDATE, DELETE ON EQUIPO_TEMPORADA TO USER_WEB;
GRANT SELECT, INSERT, UPDATE, DELETE ON CUERPO_TECNICO_TEMPORADA TO USER_WEB;

CREATE SYNONYM USER_WEB.EQUIPO_TEMPORADA FOR &&PROPIETARIO..EQUIPO_TEMPORADA;
CREATE SYNONYM USER_WEB.CUERPO_TECNICO_TEMPORADA FOR &&PROPIETARIO..CUERPO_TECNICO_TEMPORADA;

-- 4) TEMPORADA_ID (todavía opcional) en CLASIFICACIONES, EQUIPOS_FFCV y HORARIOS_ENTRENAMIENTO
ALTER TABLE CLASIFICACIONES ADD (TEMPORADA_ID NUMBER NULL);
ALTER TABLE CLASIFICACIONES ADD CONSTRAINT FK_CLASIFICACIONES_TEMPORADA
    FOREIGN KEY (TEMPORADA_ID) REFERENCES TEMPORADAS(ID);
CREATE INDEX IDX_CLASIFICACIONES_EQ_TEMP ON CLASIFICACIONES (EQUIPO_ID, TEMPORADA_ID);

ALTER TABLE EQUIPOS_FFCV ADD (TEMPORADA_ID NUMBER NULL);
ALTER TABLE EQUIPOS_FFCV ADD CONSTRAINT FK_EQUIPOS_FFCV_TEMPORADA
    FOREIGN KEY (TEMPORADA_ID) REFERENCES TEMPORADAS(ID);
CREATE INDEX IDX_EQUIPOS_FFCV_TEMPORADA ON EQUIPOS_FFCV (TEMPORADA_ID);

ALTER TABLE HORARIOS_ENTRENAMIENTO ADD (TEMPORADA_ID NUMBER NULL);
ALTER TABLE HORARIOS_ENTRENAMIENTO ADD CONSTRAINT FK_HORARIOS_ENTRENO_TEMPORADA
    FOREIGN KEY (TEMPORADA_ID) REFERENCES TEMPORADAS(ID);
CREATE INDEX IDX_HORARIOS_ENTRENO_TEMPORADA ON HORARIOS_ENTRENAMIENTO (TEMPORADA_ID);

-- Comprobación de la parte A: 2 tablas nuevas (vacías), 5 columnas nuevas en JUGADOR_TEMPORADA y TEMPORADA_ID en las
-- tres tablas (todavía nulable: NULLABLE = 'Y').
SELECT TABLE_NAME, COLUMN_NAME, NULLABLE
FROM USER_TAB_COLUMNS
WHERE (TABLE_NAME = 'JUGADOR_TEMPORADA' AND COLUMN_NAME IN
          ('ESTADO', 'CONTINUIDAD', 'FECHA_CONTINUIDAD', 'USUARIO_APP_CONTINUIDAD_ID', 'EQUIPO_DEFINITIVO'))
   OR (TABLE_NAME IN ('CLASIFICACIONES', 'EQUIPOS_FFCV', 'HORARIOS_ENTRENAMIENTO') AND COLUMN_NAME = 'TEMPORADA_ID')
ORDER BY TABLE_NAME, COLUMN_NAME;

SELECT (SELECT COUNT(*) FROM EQUIPO_TEMPORADA) AS EQUIPO_TEMPORADA,
       (SELECT COUNT(*) FROM CUERPO_TECNICO_TEMPORADA) AS CUERPO_TECNICO_TEMPORADA
FROM DUAL;


-- ============================================================================
-- PARTE B: datos y restricciones (justo antes de desplegar el código nuevo)
-- ============================================================================

-- Debe haber UNA temporada activa (devuelve 1 fila).
SELECT ID, NOMBRE, FECHA_INICIO, FECHA_FIN FROM TEMPORADAS WHERE ACTIVA = 1;

-- 1) Estados de las cuotas que hay ahora. El CHECK nuevo solo admite PENDIENTE, PARCIAL, PAGADO e INCOBRABLE: si
-- sale otro valor, el ADD CONSTRAINT del final falla. En producción la tabla está vacía (0 filas).
SELECT ESTADO, COUNT(*) AS CUOTAS FROM CUOTAS_JUGADOR GROUP BY ESTADO ORDER BY ESTADO;

-- 2) JUGADOR_TEMPORADA: las bajas pasan a ESTADO = 'BAJA' y BAJA/ESTADO quedan coherentes. BAJA se mantiene de
-- momento; el código nuevo escribe las dos columnas a la vez.
UPDATE JUGADOR_TEMPORADA SET ESTADO = 'BAJA' WHERE BAJA = 1 AND ESTADO <> 'BAJA';

ALTER TABLE JUGADOR_TEMPORADA ADD CONSTRAINT CK_JT_BAJA_ESTADO
    CHECK ((BAJA = 1 AND ESTADO = 'BAJA') OR (BAJA = 0 AND ESTADO <> 'BAJA'));

-- 3) EQUIPO_TEMPORADA de la temporada activa: todos los equipos actuales, activos, NORMAL y con su modalidad.
INSERT INTO EQUIPO_TEMPORADA (EQUIPO_ID, TEMPORADA_ID, ACTIVO, MODALIDAD, TIPO)
SELECT E.ID, T.ID, 1, E.MODALIDAD, 'NORMAL'
FROM EQUIPO E
CROSS JOIN (SELECT ID FROM TEMPORADAS WHERE ACTIVA = 1) T
WHERE NOT EXISTS (SELECT 1 FROM EQUIPO_TEMPORADA ET WHERE ET.EQUIPO_ID = E.ID AND ET.TEMPORADA_ID = T.ID);

-- 4) TEMPORADA_ID = la temporada activa donde falte, y después obligatorio.
UPDATE CLASIFICACIONES SET TEMPORADA_ID = (SELECT ID FROM TEMPORADAS WHERE ACTIVA = 1) WHERE TEMPORADA_ID IS NULL;
UPDATE EQUIPOS_FFCV SET TEMPORADA_ID = (SELECT ID FROM TEMPORADAS WHERE ACTIVA = 1) WHERE TEMPORADA_ID IS NULL;
UPDATE HORARIOS_ENTRENAMIENTO SET TEMPORADA_ID = (SELECT ID FROM TEMPORADAS WHERE ACTIVA = 1) WHERE TEMPORADA_ID IS NULL;

ALTER TABLE CLASIFICACIONES MODIFY (TEMPORADA_ID NOT NULL);
ALTER TABLE EQUIPOS_FFCV MODIFY (TEMPORADA_ID NOT NULL);
ALTER TABLE HORARIOS_ENTRENAMIENTO MODIFY (TEMPORADA_ID NOT NULL);

-- 5) EQUIPOS_FFCV: el mismo (COMPETICION, LETRA) puede repetirse en temporadas distintas, no dentro de la misma.
-- CLASIFICACIONES y HORARIOS_ENTRENAMIENTO no tienen ninguna UNIQUE que cambiar.
ALTER TABLE EQUIPOS_FFCV DROP CONSTRAINT UQ_EQUIPOS_FFCV;
ALTER TABLE EQUIPOS_FFCV ADD CONSTRAINT UQ_EQUIPOS_FFCV UNIQUE (TEMPORADA_ID, COMPETICION, LETRA);

-- 6) CUOTAS_JUGADOR: nuevo estado INCOBRABLE.
ALTER TABLE CUOTAS_JUGADOR DROP CONSTRAINT CK_CUOTA_ESTADO;
ALTER TABLE CUOTAS_JUGADOR ADD CONSTRAINT CK_CUOTA_ESTADO
    CHECK (ESTADO IN ('PENDIENTE', 'PARCIAL', 'PAGADO', 'INCOBRABLE'));

COMMIT;

-- Comprobación 1: EQUIPOS debe ser igual a EN_LA_ACTIVA.
SELECT (SELECT COUNT(*) FROM EQUIPO) AS EQUIPOS,
       (SELECT COUNT(*) FROM EQUIPO_TEMPORADA ET JOIN TEMPORADAS T ON T.ID = ET.TEMPORADA_ID WHERE T.ACTIVA = 1)
           AS EN_LA_ACTIVA
FROM DUAL;

-- Comprobación 2: las tres columnas deben dar 0.
SELECT (SELECT COUNT(*) FROM CLASIFICACIONES WHERE TEMPORADA_ID IS NULL) AS CLASIFICACIONES_SIN_TEMPORADA,
       (SELECT COUNT(*) FROM EQUIPOS_FFCV WHERE TEMPORADA_ID IS NULL) AS EQUIPOS_FFCV_SIN_TEMPORADA,
       (SELECT COUNT(*) FROM HORARIOS_ENTRENAMIENTO WHERE TEMPORADA_ID IS NULL) AS HORARIOS_SIN_TEMPORADA
FROM DUAL;

-- Comprobación 3: debe dar 0.
SELECT COUNT(*) AS BAJAS_INCOHERENTES FROM JUGADOR_TEMPORADA WHERE BAJA = 1 AND ESTADO <> 'BAJA';

-- Comprobación 4: UQ_EQUIPOS_FFCV con las columnas TEMPORADA_ID, COMPETICION, LETRA (en ese orden).
SELECT COLUMN_NAME, POSITION FROM USER_CONS_COLUMNS WHERE CONSTRAINT_NAME = 'UQ_EQUIPOS_FFCV' ORDER BY POSITION;

-- Comprobación 5: CK_CUOTA_ESTADO con los cuatro estados.
SELECT CONSTRAINT_NAME, SEARCH_CONDITION FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME = 'CK_CUOTA_ESTADO';

-- Comprobación 6: 4 privilegios (DELETE, INSERT, SELECT, UPDATE) por cada tabla nueva, y los dos sinónimos
-- apuntando a ellas.
SELECT TABLE_NAME, PRIVILEGE
FROM USER_TAB_PRIVS_MADE
WHERE TABLE_NAME IN ('EQUIPO_TEMPORADA', 'CUERPO_TECNICO_TEMPORADA') AND GRANTEE = 'USER_WEB'
ORDER BY TABLE_NAME, PRIVILEGE;

SELECT OWNER, SYNONYM_NAME, TABLE_OWNER, TABLE_NAME
FROM ALL_SYNONYMS
WHERE OWNER = 'USER_WEB' AND SYNONYM_NAME IN ('EQUIPO_TEMPORADA', 'CUERPO_TECNICO_TEMPORADA');
