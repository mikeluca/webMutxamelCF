-- ============================================================================
-- Escudos de los clubes rivales (todas las categorías)
--
-- Qué añade:
--   * CLUBES_RIVALES: un registro por CLUB rival (no por equipo: el Alicante A, el Alicante B y el Alicante
--     infantil son el mismo club y comparten escudo). CODIGO_FFCV es el código de club de la FFCV (columna
--     "Club" del Excel de clasificaciones): es lo que une el mismo club en ligas distintas.
--     ESCUDO es un PNG ya reducido a 256 px por el backend. ESCUDO_VERSION sube cada vez que cambia el escudo:
--     va en la URL pública para que la app renueve su caché.
--   * CLUBES_RIVALES_ALIAS: los nombres (normalizados) con los que aparece ese club en clasificaciones y
--     partidos. Un nombre normalizado solo puede ser de un club.
--   * PARTIDOS.CLUB_RIVAL_ID: el club rival de cada partido (todos los equipos).
--   * CLASIFICACIONES.CODIGO_CLUB: el código de club de la FFCV de cada fila (se rellena al importar el Excel).
--
-- Solo añade tablas y columnas nulas: el código anterior sigue funcionando.
-- Los clubes se crean desde el backend (al importar clasificaciones y con el botón "Generar clubes" del panel),
-- no desde este script.
--
-- SI YA EJECUTASTE LA VERSIÓN ANTERIOR DE ESTE SCRIPT (la que no tenía CODIGO_FFCV ni CODIGO_CLUB):
-- ejecuta solo el bloque 5 ("Ampliación") y las comprobaciones.
--
-- Ejecutar ANTES de desplegar, con el usuario PROPIETARIO del esquema (SYSTEM), no con USER_WEB.
-- No se puede repetir entero: si se interrumpe, continuar desde la sentencia que falló.
-- ============================================================================

-- 1) Clubes rivales
CREATE TABLE CLUBES_RIVALES (
    ID                   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE               VARCHAR2(150 CHAR) NOT NULL,
    ESCUDO               BLOB NULL,
    ESCUDO_VERSION       NUMBER DEFAULT 0 NOT NULL,
    FECHA_ACTUALIZACION  TIMESTAMP NULL,
    FECHA_CREACION       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_CLUBES_RIVALES_NOMBRE UNIQUE (NOMBRE)
);

-- 2) Nombres con los que aparece cada club
CREATE TABLE CLUBES_RIVALES_ALIAS (
    ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CLUB_RIVAL_ID       NUMBER NOT NULL,
    NOMBRE_NORMALIZADO  VARCHAR2(150 CHAR) NOT NULL,
    CONSTRAINT FK_ALIAS_CLUB_RIVAL FOREIGN KEY (CLUB_RIVAL_ID) REFERENCES CLUBES_RIVALES(ID),
    CONSTRAINT UQ_ALIAS_NOMBRE UNIQUE (NOMBRE_NORMALIZADO)
);

CREATE INDEX IDX_ALIAS_CLUB_RIVAL ON CLUBES_RIVALES_ALIAS (CLUB_RIVAL_ID);

-- 3) Club rival del partido
ALTER TABLE PARTIDOS ADD (
    CLUB_RIVAL_ID  NUMBER NULL
);

ALTER TABLE PARTIDOS ADD CONSTRAINT FK_PARTIDOS_CLUB_RIVAL
    FOREIGN KEY (CLUB_RIVAL_ID) REFERENCES CLUBES_RIVALES(ID);

CREATE INDEX IDX_PARTIDOS_CLUB_RIVAL ON PARTIDOS (CLUB_RIVAL_ID);

-- 4) Permisos y sinónimos para USER_WEB
GRANT SELECT, INSERT, UPDATE, DELETE ON CLUBES_RIVALES TO USER_WEB;
GRANT SELECT, INSERT, UPDATE, DELETE ON CLUBES_RIVALES_ALIAS TO USER_WEB;

CREATE SYNONYM USER_WEB.CLUBES_RIVALES FOR SYSTEM.CLUBES_RIVALES;
CREATE SYNONYM USER_WEB.CLUBES_RIVALES_ALIAS FOR SYSTEM.CLUBES_RIVALES_ALIAS;

-- 5) Ampliación: código de club de la FFCV (si ya ejecutaste la versión anterior, empieza aquí)
ALTER TABLE CLUBES_RIVALES ADD (
    CODIGO_FFCV  NUMBER NULL
);

ALTER TABLE CLUBES_RIVALES ADD CONSTRAINT UQ_CLUBES_RIVALES_CODIGO UNIQUE (CODIGO_FFCV);

ALTER TABLE CLASIFICACIONES ADD (
    CODIGO_CLUB  NUMBER NULL
);

