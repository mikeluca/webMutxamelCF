-- 1)
CREATE TABLE SYSTEM.EQUIPACIONES (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE      VARCHAR2(50 CHAR) NOT NULL,
    CAMISETA    VARCHAR2(50 CHAR) NULL,
    PANTALON    VARCHAR2(50 CHAR) NULL,
    MEDIAS      VARCHAR2(50 CHAR) NULL,
    COLOR_HEX   VARCHAR2(7) NULL,
    ORDEN       NUMBER DEFAULT 0 NOT NULL,
    ACTIVA      NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT UQ_EQUIPACIONES_NOMBRE UNIQUE (NOMBRE),
    CONSTRAINT CK_EQUIPACIONES_COLOR_HEX CHECK (REGEXP_LIKE(COLOR_HEX, '^#[0-9A-Fa-f]{6}$')),
    CONSTRAINT CK_EQUIPACIONES_ACTIVA CHECK (ACTIVA IN (0, 1))
);

-- 2) La aplicación se conecta como USER_WEB y accede a las tablas por sinónimo.
GRANT SELECT, INSERT, UPDATE, DELETE ON SYSTEM.EQUIPACIONES TO USER_WEB;

CREATE OR REPLACE SYNONYM USER_WEB.EQUIPACIONES FOR SYSTEM.EQUIPACIONES;

-- 3)
ALTER TABLE SYSTEM.CONVOCATORIAS ADD (
    EQUIPACION_ID          NUMBER NULL,
    EQUIPACION_MOCHILA_ID  NUMBER NULL
);

ALTER TABLE SYSTEM.CONVOCATORIAS ADD CONSTRAINT FK_CONVOCATORIAS_EQUIPACION
    FOREIGN KEY (EQUIPACION_ID) REFERENCES SYSTEM.EQUIPACIONES(ID);

ALTER TABLE SYSTEM.CONVOCATORIAS ADD CONSTRAINT FK_CONVOCATORIAS_EQUIP_MOCHILA
    FOREIGN KEY (EQUIPACION_MOCHILA_ID) REFERENCES SYSTEM.EQUIPACIONES(ID);

-- Mochila: ninguna, o con equipaje principal y distinto de ella.
ALTER TABLE SYSTEM.CONVOCATORIAS ADD CONSTRAINT CK_CONVOCATORIAS_EQUIPAJE CHECK (
    EQUIPACION_MOCHILA_ID IS NULL
    OR (EQUIPACION_ID IS NOT NULL AND EQUIPACION_ID <> EQUIPACION_MOCHILA_ID));

-- Las claves ajenas se usan al borrar un equipaje y al comprobar si está en uso.
CREATE INDEX IDX_CONVOCATORIAS_EQUIPACION ON SYSTEM.CONVOCATORIAS (EQUIPACION_ID);
CREATE INDEX IDX_CONVOCATORIAS_EQUIP_MOCHILA ON SYSTEM.CONVOCATORIAS (EQUIPACION_MOCHILA_ID);

-- 4) Comprobaciones
-- La tabla nueva (8 filas: ID, NOMBRE, CAMISETA, PANTALON, MEDIAS, COLOR_HEX, ORDEN, ACTIVA):
SELECT COLUMN_NAME, DATA_TYPE, NULLABLE, DATA_DEFAULT FROM DBA_TAB_COLUMNS
WHERE OWNER = 'SYSTEM' AND TABLE_NAME = 'EQUIPACIONES' ORDER BY COLUMN_ID;

-- Las dos columnas nuevas de CONVOCATORIAS (2 filas, NULLABLE = 'Y'):
SELECT COLUMN_NAME, NULLABLE FROM DBA_TAB_COLUMNS
WHERE OWNER = 'SYSTEM' AND TABLE_NAME = 'CONVOCATORIAS'
  AND COLUMN_NAME IN ('EQUIPACION_ID', 'EQUIPACION_MOCHILA_ID');

-- Restricciones (UQ_EQUIPACIONES_NOMBRE, CK_EQUIPACIONES_COLOR_HEX, CK_EQUIPACIONES_ACTIVA, la clave primaria,
-- FK_CONVOCATORIAS_EQUIPACION, FK_CONVOCATORIAS_EQUIP_MOCHILA y CK_CONVOCATORIAS_EQUIPAJE):
SELECT TABLE_NAME, CONSTRAINT_NAME, CONSTRAINT_TYPE FROM DBA_CONSTRAINTS
WHERE OWNER = 'SYSTEM'
  AND (TABLE_NAME = 'EQUIPACIONES' OR CONSTRAINT_NAME LIKE 'FK_CONVOCATORIAS_EQUIP%'
       OR CONSTRAINT_NAME = 'CK_CONVOCATORIAS_EQUIPAJE')
  AND CONSTRAINT_NAME NOT LIKE 'SYS\_%' ESCAPE '\'
ORDER BY TABLE_NAME, CONSTRAINT_NAME;

-- Los índices nuevos (IDX_CONVOCATORIAS_EQUIPACION e IDX_CONVOCATORIAS_EQUIP_MOCHILA):
SELECT INDEX_NAME FROM DBA_INDEXES
WHERE OWNER = 'SYSTEM' AND INDEX_NAME LIKE 'IDX_CONVOCATORIAS_EQUIP%' ORDER BY INDEX_NAME;

-- GRANT y sinónimo para USER_WEB (4 privilegios y 1 sinónimo):
SELECT TABLE_NAME, PRIVILEGE FROM DBA_TAB_PRIVS
WHERE GRANTEE = 'USER_WEB' AND TABLE_NAME = 'EQUIPACIONES' ORDER BY PRIVILEGE;

SELECT OWNER, SYNONYM_NAME, TABLE_OWNER FROM DBA_SYNONYMS
WHERE OWNER = 'USER_WEB' AND SYNONYM_NAME = 'EQUIPACIONES';

-- Ninguna convocatoria existente tiene equipaje (debe dar CON_EQUIPAJE = 0):
SELECT COUNT(*) AS TOTAL, COUNT(EQUIPACION_ID) AS CON_EQUIPAJE FROM SYSTEM.CONVOCATORIAS;

-- Línea "🚿 Ducha recomendable después del partido" de los avisos de convocatoria: lleva un emoji (4 bytes en UTF-8).
-- Para que COMUNICACIONES.CONTENIDO lo guarde y lo devuelva bien hacen falta las dos cosas siguientes. Ejecutar ANTES
-- de desplegar (son consultas, no cambian nada):
--   a) El juego de caracteres de la base de datos tiene que ser AL32UTF8 (con WE8MSWIN1252 u otro, el emoji se
--      guarda como '¿'). Si NLS_CHARACTERSET no es AL32UTF8, quitar la línea (LINEA_DUCHA en TextosConvocatoria).
SELECT PARAMETER, VALUE FROM NLS_DATABASE_PARAMETERS WHERE PARAMETER IN ('NLS_CHARACTERSET', 'NLS_NCHAR_CHARACTERSET');
--   b) CONTENIDO tiene que ser VARCHAR2 / NVARCHAR2 / CLOB con espacio de sobra (los avisos de convocatoria llegan a
--      unos 450 caracteres con el equipaje; si es VARCHAR2(n BYTE) con n pequeño, ampliarlo o quitar la línea).
SELECT COLUMN_NAME, DATA_TYPE, DATA_LENGTH, CHAR_LENGTH, CHAR_USED FROM DBA_TAB_COLUMNS
WHERE OWNER = 'SYSTEM' AND TABLE_NAME = 'COMUNICACIONES' AND COLUMN_NAME IN ('TITULO', 'CONTENIDO');
--   c) Prueba del carácter (debe devolver CODIGO = 128703, que es U+1F6BF; con otro valor, p. ej. 49855, el emoji se estropea).
--      Si el cliente SQL no usa UTF-8, el emoji de este fichero puede llegar ya estropeado: la prueba usa UNISTR.
SELECT ASCII(UNISTR('\D83D\DEBF')) AS CODIGO FROM DUAL;

