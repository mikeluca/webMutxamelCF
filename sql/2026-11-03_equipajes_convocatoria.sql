--     panel web (Administración deportiva > Equipajes). Se crea VACÍA: no hay datos iniciales.
--       - NOMBRE (único), y CAMISETA, PANTALON y MEDIAS como texto con el color ("Blanca"), todos opcionales.
--       - COLOR_HEX '#RRGGBB' opcional: la muestra de color de la app y del panel.
--       - ORDEN (por defecto 0) y ACTIVA (0 / 1, por defecto 1). Un equipaje usado en alguna convocatoria no se
--         borra, solo se desactiva (lo comprueba el panel; la clave ajena de CONVOCATORIAS lo impide además).
--   * CONVOCATORIAS: EQUIPACION_ID (con el que van vestidos al partido) y EQUIPACION_MOCHILA_ID (el de reserva,
--     en la mochila). Las dos opcionales. CHECK: sin mochila, o con mochila y con equipaje principal distinto.
--
-- Solo crea una tabla y añade columnas nulas: el código anterior sigue funcionando (no las lee ni las escribe).
-- Ejecutar con el usuario PROPIETARIO del esquema (SYSTEM, no USER_WEB), a mano, en DEV y luego en PRO. El proyecto
-- no usa Flyway/Liquibase y el script no se puede repetir (ORA-00955, ORA-01430): si se interrumpe, continuar desde
-- la sentencia que falló.
