-- Justificación de ausencia a partidos (sustituye a la respuesta "Va / No puede"
-- a la convocatoria).
--
-- Parte A: crea JUSTIFICACIONES_FALTA_PARTIDO.
-- Parte B: elimina de CONVOCATORIA_JUGADOR las columnas de la respuesta.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- Parte A
-- ---------------------------------------------------------------------------

CREATE TABLE JUSTIFICACIONES_FALTA_PARTIDO (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PARTIDO_ID       NUMBER              NOT NULL,
    JUGADOR_ID       NUMBER              NOT NULL,
    USUARIO_APP_ID   NUMBER              NOT NULL,
    MOTIVO           VARCHAR2(500 CHAR)  NOT NULL,
    FECHA_CREACION   TIMESTAMP           NOT NULL,
    CONSTRAINT FK_JUSTIF_PART_PARTIDO FOREIGN KEY (PARTIDO_ID) REFERENCES PARTIDOS(ID),
    CONSTRAINT FK_JUSTIF_PART_JUGADOR FOREIGN KEY (JUGADOR_ID) REFERENCES JUGADORES(ID),
    CONSTRAINT FK_JUSTIF_PART_USUARIO FOREIGN KEY (USUARIO_APP_ID) REFERENCES USUARIOS_APP(ID),
    CONSTRAINT UQ_JUSTIF_PART_PART_JUG UNIQUE (PARTIDO_ID, JUGADOR_ID)
);

CREATE INDEX IDX_JUSTIF_PART_JUGADOR ON JUSTIFICACIONES_FALTA_PARTIDO (JUGADOR_ID);

GRANT SELECT, INSERT, UPDATE, DELETE ON SYSTEM.JUSTIFICACIONES_FALTA_PARTIDO TO USER_WEB;

CREATE OR REPLACE SYNONYM USER_WEB.JUSTIFICACIONES_FALTA_PARTIDO
    FOR SYSTEM.JUSTIFICACIONES_FALTA_PARTIDO;

-- Comprobaciones
SELECT OWNER, SYNONYM_NAME, TABLE_OWNER, TABLE_NAME
FROM DBA_SYNONYMS WHERE SYNONYM_NAME = 'JUSTIFICACIONES_FALTA_PARTIDO';

SELECT GRANTEE, OWNER, PRIVILEGE
FROM DBA_TAB_PRIVS
WHERE TABLE_NAME = 'JUSTIFICACIONES_FALTA_PARTIDO' AND GRANTEE = 'USER_WEB';
-- Como USER_WEB: SELECT COUNT(*) FROM JUSTIFICACIONES_FALTA_PARTIDO;  -> 0

-- ---------------------------------------------------------------------------
-- Parte B
-- ---------------------------------------------------------------------------

ALTER TABLE CONVOCATORIA_JUGADOR DROP (
    RESPUESTA, MOTIVO, FECHA_RESPUESTA, USUARIO_APP_RESPUESTA_ID
) CASCADE CONSTRAINTS;

-- Comprobación: deben quedar solo ID, CONVOCATORIA_ID y JUGADOR_ID
SELECT COLUMN_NAME FROM DBA_TAB_COLUMNS
WHERE OWNER = 'SYSTEM' AND TABLE_NAME = 'CONVOCATORIA_JUGADOR'
ORDER BY COLUMN_ID;
