-- Retransmisión en directo por partido, con eventos que se pueden deshacer.
--
-- Hasta ahora el estado del directo vivía en una única fila (PARTIDO_LIVE) y
-- en PARTIDO_LIVE_GOLEADOR (el autor del gol era texto libre). Desde ahora cada
-- cosa que pasa en un partido es una fila de PARTIDO_LIVE_EVENTOS y el marcador,
-- la fase y los goleadores se CALCULAN a partir de los eventos no anulados.
-- Deshacer marca ANULADO = 1: nunca se borra nada.
--
-- PARTIDO_LIVE y PARTIDO_LIVE_GOLEADOR dejan de usarse, pero este script NO las
-- toca (no se borran).
--
-- TIPO: INICIO, GOL_FAVOR, GOL_CONTRA, DESCANSO, SEGUNDA_PARTE, FINAL.
-- JUGADOR_ID: autor de un GOL_FAVOR elegido en la lista de convocados.
-- AUTOR_TEXTO: solo para "Otro" (texto libre, máx. 60) y "p.p." (propia puerta
--              del rival); nunca junto a JUGADOR_ID.
--
-- Las columnas RESULTADO_ANTERIOR ... ESTADISTICAS_GUARDADAS solo las rellena
-- un evento FINAL: guardan lo que había en PARTIDOS antes de escribir el
-- resultado y si el FINAL creó las estadísticas por jugador, para poder
-- deshacer el FINAL sin pisar nada que el entrenador haya metido a mano.
--
-- IMPORTANTE: este script NO se ejecuta automáticamente (el proyecto no usa
-- Flyway/Liquibase). Debe ejecutarse a mano en dev y en producción ANTES de
-- desplegar el commit de la retransmisión por partido, con el usuario SYSTEM
-- (propietario de las tablas).
-- ============================================================================

CREATE TABLE PARTIDO_LIVE_EVENTOS (
    ID                        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PARTIDO_ID                NUMBER NOT NULL,
    TIPO                      VARCHAR2(20) NOT NULL,
    JUGADOR_ID                NUMBER NULL,
    AUTOR_TEXTO               VARCHAR2(60) NULL,
    USUARIO_APP_ID            NUMBER NOT NULL,
    FECHA                     TIMESTAMP NOT NULL,
    ANULADO                   NUMBER(1) DEFAULT 0 NOT NULL,
    FECHA_ANULACION           TIMESTAMP NULL,
    RESULTADO_ANTERIOR        VARCHAR2(20) NULL,
    GOLES_FAVOR_ANTERIOR      NUMBER NULL,
    GOLES_CONTRA_ANTERIOR     NUMBER NULL,
    AVISO_ANTERIOR            NUMBER(1) NULL,
    ESTADISTICAS_GUARDADAS    NUMBER(1) DEFAULT 0 NOT NULL,
    CONSTRAINT FK_LIVE_EVENTOS_PARTIDO FOREIGN KEY (PARTIDO_ID) REFERENCES PARTIDOS(ID),
    CONSTRAINT FK_LIVE_EVENTOS_JUGADOR FOREIGN KEY (JUGADOR_ID) REFERENCES JUGADORES(ID),
    CONSTRAINT FK_LIVE_EVENTOS_USUARIO FOREIGN KEY (USUARIO_APP_ID) REFERENCES USUARIOS_APP(ID),
    CONSTRAINT CK_LIVE_EVENTOS_TIPO CHECK (TIPO IN
        ('INICIO', 'GOL_FAVOR', 'GOL_CONTRA', 'DESCANSO', 'SEGUNDA_PARTE', 'FINAL')),
    CONSTRAINT CK_LIVE_EVENTOS_ANULADO CHECK (ANULADO IN (0, 1)),
    CONSTRAINT CK_LIVE_EVENTOS_ESTADISTICAS CHECK (ESTADISTICAS_GUARDADAS IN (0, 1)),
    CONSTRAINT CK_LIVE_EVENTOS_AUTOR CHECK (JUGADOR_ID IS NULL OR AUTOR_TEXTO IS NULL)
);

CREATE INDEX IDX_LIVE_EVENTOS_PARTIDO_FECHA ON PARTIDO_LIVE_EVENTOS (PARTIDO_ID, FECHA);

-- La aplicación se conecta como USER_WEB y accede a las tablas por sinónimo.
-- Sin estas dos líneas la retransmisión falla con ORA-00942 (500 en producción).
GRANT SELECT, INSERT, UPDATE, DELETE ON PARTIDO_LIVE_EVENTOS TO USER_WEB;

CREATE SYNONYM USER_WEB.PARTIDO_LIVE_EVENTOS FOR SYSTEM.PARTIDO_LIVE_EVENTOS;

-- Comprobación 1: debe devolver 4 privilegios (DELETE, INSERT, SELECT, UPDATE).
SELECT PRIVILEGE
FROM USER_TAB_PRIVS_MADE
WHERE TABLE_NAME = 'PARTIDO_LIVE_EVENTOS' AND GRANTEE = 'USER_WEB'
ORDER BY PRIVILEGE;

-- Comprobación 2: el sinónimo debe apuntar a SYSTEM.PARTIDO_LIVE_EVENTOS.
SELECT OWNER, SYNONYM_NAME, TABLE_OWNER, TABLE_NAME
FROM ALL_SYNONYMS
WHERE OWNER = 'USER_WEB' AND SYNONYM_NAME = 'PARTIDO_LIVE_EVENTOS';

-- Comprobación 3: la tabla existe y está vacía hasta el primer directo.
