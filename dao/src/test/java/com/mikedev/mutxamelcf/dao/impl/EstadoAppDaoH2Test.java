package com.mikedev.mutxamelcf.dao.impl;

import static org.assertj.core.api.Assertions.assertThat;

import java.sql.Timestamp;
import java.time.LocalDateTime;
import java.util.List;
import java.util.Map;
import java.util.UUID;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import com.mikedev.mutxamelcf.dao.EstadoAppDao;
import com.mikedev.mutxamelcf.dao.EstadoAppDao.DispositivosPorVersion;

/** Los agregados del estado de la app, sobre H2 en modo Oracle. */
class EstadoAppDaoH2Test {

    private static final LocalDateTime AHORA = LocalDateTime.of(2026, 10, 26, 12, 0);

    private JdbcTemplate jdbc;
    private EstadoAppDaoImpl dao;

    @BeforeEach
    void setUp() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(
                "jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=Oracle;DB_CLOSE_DELAY=-1", "sa", ""));

        jdbc.execute("""
                CREATE TABLE USUARIOS_APP (
                    ID NUMBER PRIMARY KEY, EMAIL VARCHAR2(100), ACTIVO NUMBER(1) DEFAULT 0 NOT NULL,
                    FECHA_ACTIVACION TIMESTAMP, FECHA_ULTIMO_ACCESO TIMESTAMP, FECHA_ELIMINACION TIMESTAMP)""");
        jdbc.execute("""
                CREATE TABLE USUARIOS_APP_DISPOSITIVOS (
                    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, USUARIO_APP_ID NUMBER NOT NULL,
                    PLATAFORMA VARCHAR2(10), VERSION_APP VARCHAR2(20), ACTIVO NUMBER(1) DEFAULT 1 NOT NULL)""");
        jdbc.execute("""
                CREATE TABLE PREFERENCIAS_NOTIFICACION (
                    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, USUARIO_APP_ID NUMBER NOT NULL,
                    NOTIFICACIONES_ACTIVADAS NUMBER(1) DEFAULT 1 NOT NULL)""");

        dao = new EstadoAppDaoImpl(jdbc);

        // 1: activa, con 2 dispositivos (Android 1.0.2 y iOS 1.0.10), entró hace 2 días.
        usuario(1, 1, true, AHORA.minusDays(2));
        dispositivo(1, "ANDROID", "1.0.2", 1);
        dispositivo(1, "IOS", "1.0.10", 1);
        // 2: activa, sin ningún dispositivo activo (uno dado de baja), entró hace 40 días.
        usuario(2, 1, true, AHORA.minusDays(40));
        dispositivo(2, "ANDROID", "1.0.1", 0);
        // 3: activa, con notificaciones apagadas y un Android sin versión; nunca entró (activada hace 50 días).
        usuario(3, 1, true, null);
        jdbc.update("UPDATE USUARIOS_APP SET FECHA_ACTIVACION = ? WHERE ID = 3", Timestamp.valueOf(AHORA.minusDays(50)));
        dispositivo(3, "ANDROID", null, 1);
        jdbc.update("INSERT INTO PREFERENCIAS_NOTIFICACION (USUARIO_APP_ID, NOTIFICACIONES_ACTIVADAS) VALUES (3, 0)");
        // 4: pendiente de activar (nunca activada).
        usuario(4, 0, false, null);
        // 5: desactivada por un administrador (se activó alguna vez).
        usuario(5, 0, true, AHORA.minusDays(100));
        // 6: eliminada por su titular: no cuenta en nada.
        usuario(6, 1, true, AHORA.minusDays(100));
        jdbc.update("UPDATE USUARIOS_APP SET FECHA_ELIMINACION = ? WHERE ID = 6", Timestamp.valueOf(AHORA));
        dispositivo(6, "ANDROID", "0.9", 1);
        // 7: activa con Android 1.0.1 (antigua) y notificaciones activadas.
        usuario(7, 1, true, AHORA.minusDays(1));
        dispositivo(7, "ANDROID", "1.0.1", 1);
        jdbc.update("INSERT INTO PREFERENCIAS_NOTIFICACION (USUARIO_APP_ID, NOTIFICACIONES_ACTIVADAS) VALUES (7, 1)");
    }

    private void usuario(long id, int activo, boolean activada, LocalDateTime ultimoAcceso) {
        jdbc.update(
                "INSERT INTO USUARIOS_APP (ID, EMAIL, ACTIVO, FECHA_ACTIVACION, FECHA_ULTIMO_ACCESO) VALUES (?, ?, ?, ?, ?)",
                id, "u" + id + "@b.es", activo,
                activada ? Timestamp.valueOf(AHORA.minusDays(200)) : null,
                ultimoAcceso == null ? null : Timestamp.valueOf(ultimoAcceso));
    }

    private void dispositivo(long usuario, String plataforma, String version, int activo) {
        jdbc.update("INSERT INTO USUARIOS_APP_DISPOSITIVOS (USUARIO_APP_ID, PLATAFORMA, VERSION_APP, ACTIVO) VALUES (?, ?, ?, ?)",
                usuario, plataforma, version, activo);
    }

    @Test
    void cuentaLasCuentasPorEstadoSinContarLasEliminadas() {
        EstadoAppDao.Totales totales = dao.contarCuentas();

        assertThat(totales.activas()).isEqualTo(4);
        assertThat(totales.pendientes()).isEqualTo(1);
        assertThat(totales.desactivadas()).isEqualTo(1);
    }

    @Test
    void activasSinDispositivoActivo() {
        assertThat(dao.contarActivasSinDispositivo()).isEqualTo(1);
        assertThat(dao.listarActivasSinDispositivo(200)).extracting(EstadoAppDao.Usuario::id).containsExactly(2L);
    }

    @Test
    void activasConLasNotificacionesApagadas() {
        assertThat(dao.contarActivasSinNotificaciones()).isEqualTo(1);
        assertThat(dao.listarActivasSinNotificaciones(200)).extracting(EstadoAppDao.Usuario::id).containsExactly(3L);
    }

    @Test
    void inactivasPorUltimoAccesoOPorSuActivacionSiNuncaEntraron() {
        LocalDateTime hace30 = AHORA.minusDays(30);

        assertThat(dao.contarInactivasDesde(hace30)).isEqualTo(2);
        assertThat(dao.listarInactivasDesde(hace30, 200)).extracting(EstadoAppDao.Usuario::id)
                .containsExactlyInAnyOrder(2L, 3L);
    }

    @Test
    void dispositivosActivosDeCuentasActivasPorPlataformaYVersion() {
        List<DispositivosPorVersion> versiones = dao.contarDispositivosPorVersion();

        assertThat(versiones).containsExactlyInAnyOrder(
                new DispositivosPorVersion("ANDROID", "1.0.2", 1),
                new DispositivosPorVersion("IOS", "1.0.10", 1),
                new DispositivosPorVersion("ANDROID", null, 1),
                new DispositivosPorVersion("ANDROID", "1.0.1", 1));
    }

    @Test
    void cuentasConAlgunDispositivoActivoDeUnaVersion() {
        assertThat(dao.listarActivasConVersiones("ANDROID", List.of("1.0.1"), 200))
                .extracting(EstadoAppDao.Usuario::id).containsExactly(7L);
        assertThat(dao.listarActivasConVersiones("IOS", List.of("1.0.1"), 200)).isEmpty();
        assertThat(dao.listarActivasConVersiones("ANDROID", List.of(), 200)).isEmpty();
    }

    @Test
    void lasListasTienenMaximo() {
        for (int i = 100; i < 110; i++) {
            usuario(i, 1, true, AHORA.minusDays(60));
        }

        assertThat(dao.listarInactivasDesde(AHORA.minusDays(30), 5)).hasSize(5);
    }

    @Test
    void versionesDeLosDispositivosActivosPorCuenta() {
        Map<Long, List<String>> versiones = dao.versionesDeDispositivosActivos(List.of(1L, 2L, 3L));

        assertThat(versiones.get(1L)).containsExactlyInAnyOrder("1.0.2", "1.0.10");
        assertThat(versiones).doesNotContainKey(2L);
        assertThat(versiones.get(3L)).containsExactly((String) null);
        assertThat(dao.versionesDeDispositivosActivos(List.of())).isEmpty();
    }
}
