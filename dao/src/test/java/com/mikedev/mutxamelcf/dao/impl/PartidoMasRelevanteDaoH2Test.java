package com.mikedev.mutxamelcf.dao.impl;

import static org.assertj.core.api.Assertions.assertThat;

import java.sql.Date;
import java.time.LocalDate;
import java.util.UUID;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import com.mikedev.mutxamelcf.model.Partido;

/**
 * El criterio de "partido más relevante" contra una base real (H2 en modo
 * Oracle): próximo sin resultado, o si no hay, el último ya jugado con o sin
 * resultado; los cancelados nunca.
 */
class PartidoMasRelevanteDaoH2Test {

    private static final long EQUIPO = 1L;

    private JdbcTemplate jdbc;
    private PartidoDaoImpl dao;

    @BeforeEach
    void setUp() {
        DriverManagerDataSource ds = new DriverManagerDataSource(
                "jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=Oracle;DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(ds);

        jdbc.execute("CREATE TABLE EQUIPO (ID NUMBER PRIMARY KEY, NOMBRE VARCHAR2(100), CATEGORIA VARCHAR2(100))");
        jdbc.execute("""
                CREATE TABLE PARTIDOS (
                    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    EQUIPO_ID NUMBER NOT NULL,
                    RIVAL VARCHAR2(150) NOT NULL,
                    DIA DATE NULL,
                    HORA VARCHAR2(10) NULL,
                    CAMPO VARCHAR2(150) NULL,
                    RESULTADO VARCHAR2(20) NULL,
                    TIPO VARCHAR2(20) NULL,
                    USUARIO_ACTUALIZO_ID NUMBER NULL,
                    FECHA_ACTUALIZACION TIMESTAMP NULL,
                    CANCELADO NUMBER(1) DEFAULT 0 NOT NULL,
                    GOLES_FAVOR NUMBER NULL,
                    GOLES_CONTRA NUMBER NULL,
                    AVISO_RESULTADO_ENVIADO NUMBER(1) DEFAULT 0 NOT NULL,
                    ORIGEN VARCHAR2(10) DEFAULT 'MANUAL' NOT NULL,
                    JORNADA NUMBER NULL,
                    ES_LOCAL NUMBER(1) DEFAULT 1 NOT NULL
                )""");
        jdbc.update("INSERT INTO EQUIPO (ID, NOMBRE, CATEGORIA) VALUES (?, 'Primer Equipo', 'Primer Equipo')", EQUIPO);

        dao = new PartidoDaoImpl(jdbc);
    }

    private void partido(String rival, int diasDesdeHoy, String resultado, int cancelado, Integer golesFavor) {
        jdbc.update("""
                INSERT INTO PARTIDOS (EQUIPO_ID, RIVAL, DIA, RESULTADO, CANCELADO, GOLES_FAVOR, GOLES_CONTRA)
                VALUES (?, ?, ?, ?, ?, ?, ?)""",
                EQUIPO, rival, Date.valueOf(LocalDate.now().plusDays(diasDesdeHoy)), resultado, cancelado,
                golesFavor, golesFavor == null ? null : 0);
    }

    private String rivalPorId() {
        Partido p = dao.obtenerMasRelevantePorEquipo(EQUIPO);
        return p == null ? null : p.getRival();
    }

    private String rivalPorNombre() {
        Partido p = dao.obtenerMasRelevantePorEquipoNombre("Primer Equipo", "Primer Equipo");
        return p == null ? null : p.getRival();
    }

    private void esperar(String rival) {
        assertThat(rivalPorId()).isEqualTo(rival);
        assertThat(rivalPorNombre()).isEqualTo(rival);
    }

    @Test
    void ultimoPartidoPasadoSinResultadoSeDevuelveSiNoHayFuturo() {
        partido("Antiguo", -20, "1-0", 0, null);
        partido("Pendiente", -4, null, 0, null);

        esperar("Pendiente");
    }

    @Test
    void ultimoPartidoPasadoConResultadoSeDevuelveSiNoHayFuturo() {
        partido("Antiguo", -11, "3-3", 0, null);
        partido("Reciente", -4, "2-1", 0, null);

        esperar("Reciente");
    }

    @Test
    void siHayFuturoGanaElFuturoAunqueElPasadoEsteSinResultado() {
        partido("Pendiente", -4, null, 0, null);
        partido("Futuro", 3, null, 0, null);

        esperar("Futuro");
    }

    @Test
    void elProximoEsElMasCercano() {
        partido("Lejano", 10, null, 0, null);
        partido("Cercano", 3, null, 0, null);

        esperar("Cercano");
    }

    @Test
    void unPartidoPasadoCanceladoNoSeDevuelveYSaleElAnteriorNoCancelado() {
        partido("Anterior", -11, "2-0", 0, null);
        partido("Cancelado", -4, null, 1, null);

        esperar("Anterior");
    }

    @Test
    void unProximoCanceladoSeIgnora() {
        partido("Jugado", -4, "2-0", 0, null);
        partido("FuturoCancelado", 3, null, 1, null);

        esperar("Jugado");
    }

    @Test
    void unPartidoConSoloGolesCuentaComoConResultado() {
        // De hoy, con goles pero sin texto de resultado: no es "próximo".
        partido("Anterior", -11, "2-0", 0, null);
        partido("HoyConGoles", 0, null, 0, 2);

        esperar("HoyConGoles");
    }

    @Test
    void sinPartidosDevuelveNull() {
        assertThat(rivalPorId()).isNull();
        assertThat(rivalPorNombre()).isNull();
    }

}
