package com.mikedev.mutxamelcf.dao.impl;

import static org.assertj.core.api.Assertions.assertThat;

import java.sql.Date;
import java.util.UUID;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import com.mikedev.mutxamelcf.dao.EsquemaH2;
import com.mikedev.mutxamelcf.model.Clasificacion;

/**
 * Los DAO que usan el reparto, el historial y la web pública en verano, con H2 en modo Oracle: activar/desactivar un
 * equipo en la temporada, contar jugadores con equipo definitivo, el cuerpo técnico de una temporada y la clasificación
 * de la temporada anterior mientras la activa no tiene partidos.
 */
class RepartoYVeranoDaoH2Test {

    private static final long ANTERIOR = 1;
    private static final long ACTIVA = 2;
    private static final long CADETE_A = 5;
    private static final long CADETE_B = 6;

    private JdbcTemplate jdbc;

    @BeforeEach
    void setUp() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(
                "jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=Oracle;DB_CLOSE_DELAY=-1", "sa", ""));

        jdbc.execute("""
                CREATE TABLE TEMPORADAS (ID NUMBER PRIMARY KEY, NOMBRE VARCHAR2(50), FECHA_INICIO DATE,
                    FECHA_FIN DATE, ACTIVA NUMBER(1))""");
        jdbc.execute("""
                CREATE TABLE EQUIPO (ID NUMBER PRIMARY KEY, NOMBRE VARCHAR2(100), CATEGORIA VARCHAR2(100),
                    DEPORTE VARCHAR2(10), GRUPO VARCHAR2(10), ORDEN VARCHAR2(5), MODALIDAD VARCHAR2(5))""");
        jdbc.execute("""
                CREATE TABLE CLASIFICACIONES (
                    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, EQUIPO_ID NUMBER NOT NULL,
                    COMPETICION VARCHAR2(200) NOT NULL, JORNADA NUMBER, POSICION NUMBER NOT NULL,
                    NOMBRE_EQUIPO VARCHAR2(150) NOT NULL, LETRA VARCHAR2(2), ES_NUESTRO NUMBER(1) DEFAULT 0 NOT NULL,
                    PUNTOS NUMBER NOT NULL, PJ NUMBER NOT NULL, PG NUMBER NOT NULL, PE NUMBER NOT NULL,
                    PP NUMBER NOT NULL, GF NUMBER NOT NULL, GC NUMBER NOT NULL, FECHA_ULT_PARTIDO DATE,
                    FECHA_IMPORTACION TIMESTAMP NOT NULL)""");
        jdbc.execute("""
                CREATE TABLE PARTIDOS (ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, DIA DATE,
                    CANCELADO NUMBER(1) DEFAULT 0)""");

        EsquemaH2.crearPersonal(jdbc);
        EsquemaH2.crearPlantillas(jdbc);
        EsquemaH2.crearTransicion(jdbc);

        jdbc.update("INSERT INTO TEMPORADAS VALUES (?, '2025/2026', ?, ?, 0)", ANTERIOR, Date.valueOf("2025-07-01"),
                Date.valueOf("2026-06-30"));
        jdbc.update("INSERT INTO TEMPORADAS VALUES (?, '2026/2027', ?, ?, 1)", ACTIVA, Date.valueOf("2026-07-01"),
                Date.valueOf("2027-06-30"));
        jdbc.update("INSERT INTO EQUIPO (ID, NOMBRE, ORDEN, MODALIDAD) VALUES (?, 'Cadete A', '3', 'F11')", CADETE_A);
        jdbc.update("INSERT INTO EQUIPO (ID, NOMBRE, ORDEN, MODALIDAD) VALUES (?, 'Cadete B', '3', 'F11')", CADETE_B);
    }

    private Integer activoEnLaTemporada(long equipo, long temporada) {
        return jdbc.query("SELECT ACTIVO FROM EQUIPO_TEMPORADA WHERE EQUIPO_ID = ? AND TEMPORADA_ID = ?",
                rs -> rs.next() ? rs.getInt(1) : null, equipo, temporada);
    }

    // ---- activar y desactivar un equipo -----------------------------------------------------------

    @Test
    void marcarActivoActualizaLaFilaDeLaTemporadaActivaYNoLaDeOtra() {
        jdbc.update("INSERT INTO EQUIPO_TEMPORADA (EQUIPO_ID, TEMPORADA_ID, ACTIVO, MODALIDAD, TIPO)"
                + " VALUES (?, ?, 0, 'F11', 'NORMAL')", CADETE_A, ACTIVA);
        jdbc.update("INSERT INTO EQUIPO_TEMPORADA (EQUIPO_ID, TEMPORADA_ID, ACTIVO, MODALIDAD, TIPO)"
                + " VALUES (?, ?, 0, 'F11', 'NORMAL')", CADETE_A, ANTERIOR);
        EquipoDaoImpl dao = new EquipoDaoImpl(jdbc);

        dao.marcarActivoEnTemporada(CADETE_A, true);

        assertThat(activoEnLaTemporada(CADETE_A, ACTIVA)).isEqualTo(1);
        assertThat(activoEnLaTemporada(CADETE_A, ANTERIOR)).isZero();

        dao.marcarActivoEnTemporada(CADETE_A, false);

        assertThat(activoEnLaTemporada(CADETE_A, ACTIVA)).isZero();
    }

    @Test
    void activarUnEquipoSinFilaEnLaTemporadaLaCreaComoNormalConLaModalidadDelEquipo() {
        new EquipoDaoImpl(jdbc).marcarActivoEnTemporada(CADETE_B, true);

        assertThat(activoEnLaTemporada(CADETE_B, ACTIVA)).isEqualTo(1);
        assertThat(jdbc.queryForObject("SELECT TIPO || '/' || MODALIDAD FROM EQUIPO_TEMPORADA WHERE EQUIPO_ID = ?",
                String.class, CADETE_B)).isEqualTo("NORMAL/F11");
    }

    @Test
    void desactivarUnEquipoSinFilaNoCreaNada() {
        new EquipoDaoImpl(jdbc).marcarActivoEnTemporada(CADETE_B, false);

        assertThat(activoEnLaTemporada(CADETE_B, ACTIVA)).isNull();
    }

    // ---- jugadores con equipo ----------------------------------------------------------------------

    private void jugadorEnLaTemporada(long id, long temporada, long equipo, int definitivo, String estado) {
        jdbc.update("INSERT INTO JUGADORES (ID, NOMBRE, APELLIDOS, CATEGORIA, DEPORTE, DORSAL, EQUIPO, EQUIPO_ID)"
                + " VALUES (?, 'J', 'J', 'Cadete', 'F', 1, 'Cadete A', ?)", id, equipo);
        jdbc.update("INSERT INTO JUGADOR_TEMPORADA (JUGADOR_ID, TEMPORADA_ID, EQUIPO_ID, ESTADO, EQUIPO_DEFINITIVO)"
                + " VALUES (?, ?, ?, ?, ?)", id, temporada, equipo, estado, definitivo);
    }

    @Test
    void sePuedeContarLosJugadoresDeUnEquipoSoloEnLaTemporadaActivaYSinBajas() {
        jugadorEnLaTemporada(1, ACTIVA, CADETE_A, 1, "CONFIRMADO");
        jugadorEnLaTemporada(2, ACTIVA, CADETE_A, 0, "CONFIRMADO");
        jugadorEnLaTemporada(3, ACTIVA, CADETE_A, 1, "BAJA");
        jugadorEnLaTemporada(4, ANTERIOR, CADETE_A, 1, "CONFIRMADO");
        jugadorEnLaTemporada(5, ACTIVA, CADETE_B, 0, "CONFIRMADO");
        JugadorTemporadaDaoImpl dao = new JugadorTemporadaDaoImpl(jdbc);

        assertThat(dao.contarDefinitivosEnLaTemporadaActiva(CADETE_A)).isEqualTo(1);
        assertThat(dao.contarEnEquipoEnLaTemporadaActiva(CADETE_A)).isEqualTo(2);
        assertThat(dao.contarDefinitivosEnLaTemporadaActiva(CADETE_B)).isZero();
        assertThat(dao.contarEnEquipoEnLaTemporadaActiva(CADETE_B)).isEqualTo(1);
    }

    // ---- cuerpo técnico de una temporada ----------------------------------------------------------

    @Test
    void elCuerpoTecnicoSeLeeDeLaTemporadaPedidaConElNombreDelEquipo() {
        jdbc.update("INSERT INTO CUERPO_TECNICO (ID, NOMBRE, APELLIDOS) VALUES (1, 'Luis', 'Mora')");
        jdbc.update("INSERT INTO CUERPO_TECNICO (ID, NOMBRE, APELLIDOS) VALUES (2, 'Eva', 'Gil')");
        jdbc.update("INSERT INTO CUERPO_TECNICO_TEMPORADA (CUERPO_TECNICO_ID, TEMPORADA_ID, EQUIPO_ID, PUESTO)"
                + " VALUES (1, ?, ?, 'Entrenador')", ANTERIOR, CADETE_A);
        jdbc.update("INSERT INTO CUERPO_TECNICO_TEMPORADA (CUERPO_TECNICO_ID, TEMPORADA_ID, EQUIPO_ID, PUESTO)"
                + " VALUES (2, ?, ?, 'Delegado')", ANTERIOR, CADETE_A);
        jdbc.update("INSERT INTO CUERPO_TECNICO_TEMPORADA (CUERPO_TECNICO_ID, TEMPORADA_ID, EQUIPO_ID, PUESTO)"
                + " VALUES (1, ?, ?, 'Entrenador')", ACTIVA, CADETE_B);
        CuerpoTecnicoTemporadaDaoImpl dao = new CuerpoTecnicoTemporadaDaoImpl(jdbc);

        assertThat(dao.listarPorTemporada(ANTERIOR)).extracting(f -> f.equipoNombre() + ":" + f.apellidos() + ":" + f.puesto())
                .containsExactly("Cadete A:Gil:Delegado", "Cadete A:Mora:Entrenador");
        assertThat(dao.listarPorTemporada(ACTIVA)).extracting(f -> f.equipoNombre()).containsExactly("Cadete B");
    }

    // ---- clasificaciones: por temporada y respaldo de verano ---------------------------------------

    private void clasificacion(long temporada, String competicion) {
        jdbc.update("INSERT INTO CLASIFICACIONES (EQUIPO_ID, COMPETICION, POSICION, NOMBRE_EQUIPO, PUNTOS, PJ, PG,"
                + " PE, PP, GF, GC, FECHA_IMPORTACION, TEMPORADA_ID) VALUES (?, ?, 1, 'Mutxamel', 60, 30, 20, 0, 10,"
                + " 50, 20, CURRENT_TIMESTAMP, ?)", CADETE_A, competicion, temporada);
    }

    @Test
    void laClasificacionSeLeePorTemporada() {
        clasificacion(ANTERIOR, "Liga 25/26");
        clasificacion(ACTIVA, "Liga 26/27");
        ClasificacionDaoImpl dao = new ClasificacionDaoImpl(jdbc);

        assertThat(dao.obtenerPorEquipoYTemporada(CADETE_A, ANTERIOR)).extracting(Clasificacion::getCompeticion)
                .containsExactly("Liga 25/26");
        assertThat(dao.listarPorTemporada(ACTIVA)).extracting(Clasificacion::getCompeticion)
                .containsExactly("Liga 26/27");
    }

    @Test
    void enVeranoSinClasificacionActivaSeMuestraLaDeLaTemporadaAnterior() {
        clasificacion(ANTERIOR, "Liga 25/26");
        ClasificacionDaoImpl dao = new ClasificacionDaoImpl(jdbc);

        assertThat(dao.obtenerPorEquipo(CADETE_A)).extracting(Clasificacion::getCompeticion)
                .containsExactly("Liga 25/26");
    }

    @Test
    void conPartidosEnLaTemporadaActivaNoSeMiraLaAnterior() {
        clasificacion(ANTERIOR, "Liga 25/26");
        jdbc.update("INSERT INTO PARTIDOS (DIA, CANCELADO) VALUES (DATE '2026-09-20', 0)");

        assertThat(new ClasificacionDaoImpl(jdbc).obtenerPorEquipo(CADETE_A)).isEmpty();
    }

    @Test
    void laClasificacionActivaTienePrioridadSobreLaAnterior() {
        clasificacion(ANTERIOR, "Liga 25/26");
        clasificacion(ACTIVA, "Liga 26/27");

        assertThat(new ClasificacionDaoImpl(jdbc).obtenerPorEquipo(CADETE_A)).extracting(Clasificacion::getCompeticion)
                .containsExactly("Liga 26/27");
    }
}
