package com.mikedev.mutxamelcf.dao.impl;

import static org.assertj.core.api.Assertions.assertThat;

import java.sql.Date;
import java.util.UUID;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import com.mikedev.mutxamelcf.dao.EsquemaH2;
import com.mikedev.mutxamelcf.model.CuotaMorosidad;

/** Las consultas de Morosidad con H2 en modo Oracle: cuotas sin pagar de una temporada, equipo de esa temporada e incobrables. */
class MorosidadDaoH2Test {

    private static final long ANTERIOR = 1;
    private static final long ACTIVA = 2;

    private JdbcTemplate jdbc;
    private CuotaJugadorDaoImpl dao;

    @BeforeEach
    void setUp() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(
                "jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=Oracle;DB_CLOSE_DELAY=-1", "sa", ""));

        jdbc.execute("""
                CREATE TABLE TEMPORADAS (ID NUMBER PRIMARY KEY, NOMBRE VARCHAR2(50), FECHA_INICIO DATE,
                    FECHA_FIN DATE, ACTIVA NUMBER(1))""");
        jdbc.execute("""
                CREATE TABLE EQUIPO (ID NUMBER PRIMARY KEY, NOMBRE VARCHAR2(100), CATEGORIA VARCHAR2(100),
                    DEPORTE VARCHAR2(10), GRUPO VARCHAR2(10), ORDEN VARCHAR2(5), MODALIDAD VARCHAR2(5))""");
        jdbc.execute("""
                CREATE TABLE CONCEPTOS_PAGO (ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, TEMPORADA_ID NUMBER,
                    NOMBRE VARCHAR2(100), DESCRIPCION VARCHAR2(200), IMPORTE NUMBER, ACTIVO NUMBER(1) DEFAULT 1)""");
        jdbc.execute("""
                CREATE TABLE CUOTAS_JUGADOR (ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, JUGADOR_ID NUMBER,
                    CONCEPTO_PAGO_ID NUMBER, PERIODO VARCHAR2(7), IMPORTE NUMBER, ESTADO VARCHAR2(20) NOT NULL,
                    FECHA_LIMITE DATE, OBSERVACIONES VARCHAR2(500),
                    CONSTRAINT CK_CUOTA_ESTADO CHECK (ESTADO IN ('PENDIENTE', 'PARCIAL', 'PAGADO', 'INCOBRABLE')))""");
        jdbc.execute("CREATE TABLE PAGOS (ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                + " CUOTA_JUGADOR_ID NUMBER, IMPORTE NUMBER)");

        EsquemaH2.crearPersonal(jdbc);
        EsquemaH2.crearPlantillas(jdbc);

        jdbc.update("INSERT INTO TEMPORADAS VALUES (?, '2025/2026', ?, ?, 0)", ANTERIOR, Date.valueOf("2025-07-01"),
                Date.valueOf("2026-06-30"));
        jdbc.update("INSERT INTO TEMPORADAS VALUES (?, '2026/2027', ?, ?, 1)", ACTIVA, Date.valueOf("2026-07-01"),
                Date.valueOf("2027-06-30"));
        jdbc.update("INSERT INTO CONCEPTOS_PAGO (ID, TEMPORADA_ID, NOMBRE, IMPORTE) VALUES (10, ?, 'Cuota mensual', 30)",
                ANTERIOR);
        jdbc.update("INSERT INTO CONCEPTOS_PAGO (ID, TEMPORADA_ID, NOMBRE, IMPORTE) VALUES (20, ?, 'Cuota mensual', 35)",
                ACTIVA);

        jugador(1, "Ana", "Pérez");
        jugador(2, "Biel", "Gil");
        // Ana jugaba en el Alevín A el año pasado y este año está en el Infantil A
        ficha(1, ANTERIOR, "Alevín A");
        ficha(1, ACTIVA, "Infantil A");

        dao = new CuotaJugadorDaoImpl(jdbc);
    }

    private void jugador(long id, String nombre, String apellidos) {
        jdbc.update("INSERT INTO JUGADORES (ID, NOMBRE, APELLIDOS, CATEGORIA, DEPORTE, DORSAL) VALUES (?, ?, ?, 'Cat', 'F', 1)",
                id, nombre, apellidos);
    }

    private void ficha(long jugador, long temporada, String equipo) {
        jdbc.update("INSERT INTO JUGADOR_TEMPORADA (JUGADOR_ID, TEMPORADA_ID, EQUIPO_NOMBRE) VALUES (?, ?, ?)", jugador,
                temporada, equipo);
    }

    private long cuota(long jugador, long concepto, String periodo, String estado, int importe) {
        jdbc.update("INSERT INTO CUOTAS_JUGADOR (JUGADOR_ID, CONCEPTO_PAGO_ID, PERIODO, IMPORTE, ESTADO) VALUES (?, ?, ?, ?, ?)",
                jugador, concepto, periodo, importe, estado);

        return jdbc.queryForObject("SELECT MAX(ID) FROM CUOTAS_JUGADOR", Long.class);
    }

    private void pago(long cuota, int importe) {
        jdbc.update("INSERT INTO PAGOS (CUOTA_JUGADOR_ID, IMPORTE) VALUES (?, ?)", cuota, importe);
    }

    private String estado(long cuota) {
        return jdbc.queryForObject("SELECT ESTADO FROM CUOTAS_JUGADOR WHERE ID = ?", String.class, cuota);
    }

    @Test
    void listaLasCuotasSinPagarDeLaTemporadaConSuEquipoDeEsaTemporadaYLoPagado() {
        long parcial = cuota(1, 10, "2025-10", "PARCIAL", 30);
        pago(parcial, 12);
        cuota(2, 10, "2025-11", "PENDIENTE", 30);
        cuota(1, 10, "2025-12", "PAGADO", 30);
        cuota(1, 20, "2026-10", "PENDIENTE", 35); // de la temporada activa: no sale

        var cuotas = dao.listarParaMorosidad(ANTERIOR, false);

        assertThat(cuotas).extracting(CuotaMorosidad::estado).containsExactly("PENDIENTE", "PARCIAL");
        CuotaMorosidad ana = cuotas.get(1);
        assertThat(ana.jugador()).isEqualTo("Ana Pérez");
        assertThat(ana.equipo()).isEqualTo("Alevín A");
        assertThat(ana.temporada()).isEqualTo("2025/2026");
        assertThat(ana.concepto()).isEqualTo("Cuota mensual");
        assertThat(ana.periodo()).isEqualTo("2025-10");
        assertThat(ana.importe()).isEqualByComparingTo("30");
        assertThat(ana.pagado()).isEqualByComparingTo("12");
        assertThat(ana.pendiente()).isEqualByComparingTo("18");
        // Biel no tenía ficha esa temporada: sin equipo
        assertThat(cuotas.get(0).equipo()).isNull();
    }

    @Test
    void conIncluirPagadasSalenTambienLasCobradas() {
        cuota(1, 10, "2025-10", "PENDIENTE", 30);
        cuota(1, 10, "2025-11", "PAGADO", 30);

        assertThat(dao.listarParaMorosidad(ANTERIOR, true)).extracting(CuotaMorosidad::estado)
                .containsExactly("PENDIENTE", "PAGADO");
    }

    @Test
    void lasIncobrablesSiguenSaliendoComoPendientes() {
        cuota(1, 10, "2025-10", "INCOBRABLE", 30);

        assertThat(dao.listarParaMorosidad(ANTERIOR, false)).singleElement()
                .satisfies(c -> assertThat(c.estado()).isEqualTo("INCOBRABLE"));
    }

    @Test
    void marcarIncobrableSoloValeParaPendientesYParciales() {
        long pendiente = cuota(1, 10, "2025-10", "PENDIENTE", 30);
        long parcial = cuota(1, 10, "2025-11", "PARCIAL", 30);
        long pagada = cuota(1, 10, "2025-12", "PAGADO", 30);
        long yaIncobrable = cuota(1, 10, "2026-01", "INCOBRABLE", 30);

        assertThat(dao.marcarIncobrable(pendiente)).isEqualTo(1);
        assertThat(dao.marcarIncobrable(parcial)).isEqualTo(1);
        assertThat(dao.marcarIncobrable(pagada)).isZero();
        assertThat(dao.marcarIncobrable(yaIncobrable)).isZero();
        assertThat(dao.marcarIncobrable(9999L)).isZero();

        assertThat(estado(pendiente)).isEqualTo("INCOBRABLE");
        assertThat(estado(parcial)).isEqualTo("INCOBRABLE");
        assertThat(estado(pagada)).isEqualTo("PAGADO");
    }

    @Test
    void deshacerIncobrableDejaElEstadoQueLeToca() {
        long sinPagos = cuota(1, 10, "2025-10", "INCOBRABLE", 30);
        long conPagos = cuota(1, 10, "2025-11", "INCOBRABLE", 30);
        pago(conPagos, 10);
        long enteraPagada = cuota(1, 10, "2025-12", "INCOBRABLE", 30);
        pago(enteraPagada, 30);
        long noIncobrable = cuota(1, 10, "2026-01", "PENDIENTE", 30);

        assertThat(dao.deshacerIncobrable(sinPagos)).isEqualTo(1);
        assertThat(dao.deshacerIncobrable(conPagos)).isEqualTo(1);
        assertThat(dao.deshacerIncobrable(enteraPagada)).isEqualTo(1);
        assertThat(dao.deshacerIncobrable(noIncobrable)).isZero();

        assertThat(estado(sinPagos)).isEqualTo("PENDIENTE");
        assertThat(estado(conPagos)).isEqualTo("PARCIAL");
        assertThat(estado(enteraPagada)).isEqualTo("PAGADO");
        assertThat(estado(noIncobrable)).isEqualTo("PENDIENTE");
    }

    @Test
    void unaIncobrableConPagoTotalPasaAPagadaAlActualizarElEstado() {
        long cuota = cuota(1, 10, "2025-10", "INCOBRABLE", 30);
        pago(cuota, 30);

        dao.actualizarEstado(cuota);

        assertThat(estado(cuota)).isEqualTo("PAGADO");
    }
}
