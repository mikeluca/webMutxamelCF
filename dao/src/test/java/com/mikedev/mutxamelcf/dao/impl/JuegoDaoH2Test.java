package com.mikedev.mutxamelcf.dao.impl;

import static org.assertj.core.api.Assertions.assertThat;

import java.time.LocalDateTime;
import java.util.List;
import java.util.UUID;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import com.mikedev.mutxamelcf.dao.JuegoDao.FilaRanking;
import com.mikedev.mutxamelcf.dao.JuegoDao.Marca;

/** El ranking, las posiciones y la moderación del juego de Mutxigol, sobre H2 en modo Oracle. */
class JuegoDaoH2Test {

    // Lunes 23/11/2026 00:00: el corte de la semana (hora de Madrid).
    private static final LocalDateTime LUNES = LocalDateTime.of(2026, 11, 23, 0, 0);
    private static final LocalDateTime SIGUIENTE_LUNES = LUNES.plusWeeks(1);
    private static final LocalDateTime AHORA = LocalDateTime.of(2026, 11, 25, 12, 0);

    private JdbcTemplate jdbc;
    private JuegoDaoImpl dao;

    @BeforeEach
    void setUp() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(
                "jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=Oracle;DB_CLOSE_DELAY=-1", "sa", ""));

        jdbc.execute("""
                CREATE TABLE USUARIOS_APP (
                    ID NUMBER PRIMARY KEY, EMAIL VARCHAR2(100), NOMBRE VARCHAR2(100), APELLIDOS VARCHAR2(100),
                    ACTIVO NUMBER(1) DEFAULT 1 NOT NULL, FECHA_ELIMINACION TIMESTAMP)""");
        jdbc.execute("""
                CREATE TABLE JUEGO_PERFILES (
                    USUARIO_APP_ID NUMBER PRIMARY KEY, ALIAS VARCHAR2(20), ALIAS_NORMALIZADO VARCHAR2(20) UNIQUE,
                    EQUIPACION VARCHAR2(10) DEFAULT 'AZUL' NOT NULL, OCULTO NUMBER(1) DEFAULT 0 NOT NULL,
                    FECHA_ALTA TIMESTAMP NOT NULL, FECHA_MODIFICACION TIMESTAMP NOT NULL)""");
        jdbc.execute("""
                CREATE TABLE JUEGO_PUNTUACIONES (
                    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, USUARIO_APP_ID NUMBER NOT NULL,
                    JUEGO VARCHAR2(20) NOT NULL, PUNTOS NUMBER NOT NULL, DURACION_MS NUMBER NOT NULL,
                    FECHA TIMESTAMP NOT NULL)""");

        dao = new JuegoDaoImpl(jdbc);
    }

    private void cuenta(long id, String alias) {
        jdbc.update("INSERT INTO USUARIOS_APP (ID, EMAIL, NOMBRE, APELLIDOS) VALUES (?, ?, ?, ?)", id,
                "u" + id + "@b.es", "Nombre" + id, "Apellido" + id);
        dao.crearPerfil(id, alias, alias == null ? null : alias.toUpperCase(), "AZUL", AHORA);
    }

    private void puntos(long id, String juego, int puntos, LocalDateTime fecha) {
        dao.insertarPuntuacion(id, juego, puntos, 30_000, fecha);
    }

    private List<String> aliasDelRanking(String juego, LocalDateTime desde, LocalDateTime hasta) {
        return dao.ranking(juego, desde, hasta, 50).stream().map(FilaRanking::alias).toList();
    }

    @Test
    void elRankingTieneUnaFilaPorCuentaConSuMejorMarcaYSeOrdenaDeMejorAPeor() {
        cuenta(1, "Ana");
        cuenta(2, "Beto");
        cuenta(3, "Cris");

        puntos(1, "PENALTIS", 5, LUNES.plusDays(1));
        puntos(1, "PENALTIS", 9, LUNES.plusDays(2));
        puntos(1, "PENALTIS", 7, LUNES.plusDays(3));
        puntos(2, "PENALTIS", 9, LUNES.plusDays(1)); // empata con Ana pero antes
        puntos(3, "PENALTIS", 3, LUNES.plusDays(1));
        puntos(3, "TOQUES", 99, LUNES.plusDays(1)); // otro juego: no cuenta

        List<FilaRanking> filas = dao.ranking("PENALTIS", null, null, 50);

        assertThat(filas).extracting(FilaRanking::alias).containsExactly("Beto", "Ana", "Cris");
        assertThat(filas).extracting(FilaRanking::puntos).containsExactly(9, 9, 3);
        // La fecha de la fila es la de la mejor marca de Ana (la del día 2), no la última.
        assertThat(filas.get(1).fecha()).isEqualTo(LUNES.plusDays(2));
    }

    @Test
    void elRankingLimitaAlosMejores() {
        for (int i = 1; i <= 5; i++) {
            cuenta(i, "Jugador" + i);
            puntos(i, "TOQUES", i, LUNES.plusDays(1));
        }

        assertThat(dao.ranking("TOQUES", null, null, 3)).extracting(FilaRanking::alias)
                .containsExactly("Jugador5", "Jugador4", "Jugador3");
    }

    @Test
    void lasSemanasCortanElLunesALasCeroHorasYElHistoricoNo() {
        cuenta(1, "Ana");
        cuenta(2, "Beto");
        cuenta(3, "Cris");

        // Ana: domingo 22:59:59 (semana anterior). Beto: lunes 00:00:00 (esta semana). Cris: el lunes siguiente
        // 00:00:00 (la siguiente).
        puntos(1, "ATRAPA", 50, LUNES.minusSeconds(1));
        puntos(2, "ATRAPA", 20, LUNES);
        puntos(3, "ATRAPA", 10, SIGUIENTE_LUNES);

        assertThat(aliasDelRanking("ATRAPA", LUNES, SIGUIENTE_LUNES)).containsExactly("Beto");
        assertThat(aliasDelRanking("ATRAPA", LUNES.minusWeeks(1), LUNES)).containsExactly("Ana");
        assertThat(aliasDelRanking("ATRAPA", null, null)).containsExactly("Ana", "Beto", "Cris");
    }

    @Test
    void laMejorMarcaSemanalIgnoraLasDeOtrasSemanas() {
        cuenta(1, "Ana");

        puntos(1, "PENALTIS", 30, LUNES.minusDays(2));
        puntos(1, "PENALTIS", 8, LUNES.plusDays(1));

        assertThat(dao.ranking("PENALTIS", LUNES, SIGUIENTE_LUNES, 50)).extracting(FilaRanking::puntos).containsExactly(8);
        assertThat(dao.ranking("PENALTIS", null, null, 50)).extracting(FilaRanking::puntos).containsExactly(30);
        assertThat(dao.mejorMarca(1, "PENALTIS", LUNES, SIGUIENTE_LUNES)).contains(new Marca(8, LUNES.plusDays(1)));
        assertThat(dao.mejorMarca(1, "PENALTIS", null, null)).contains(new Marca(30, LUNES.minusDays(2)));
        assertThat(dao.mejorMarca(1, "TOQUES", null, null)).isEmpty();
    }

    @Test
    void fueraDelRankingOcultosSinAliasYCuentasDesactivadasOEliminadas() {
        cuenta(1, "Ana");
        cuenta(2, "Oculta");
        cuenta(3, null);
        cuenta(4, "Baja");
        cuenta(5, "Borrada");

        for (long id = 1; id <= 5; id++) {
            puntos(id, "PENALTIS", (int) (10 + id), LUNES.plusDays(1));
        }

        dao.actualizarOculto(2, true, AHORA);
        jdbc.update("UPDATE USUARIOS_APP SET ACTIVO = 0 WHERE ID = 4");
        jdbc.update("UPDATE USUARIOS_APP SET FECHA_ELIMINACION = ? WHERE ID = 5", java.sql.Timestamp.valueOf(AHORA));

        assertThat(aliasDelRanking("PENALTIS", null, null)).containsExactly("Ana");

        // Una vez visible otra vez, vuelve a salir.
        dao.actualizarOculto(2, false, AHORA);
        assertThat(aliasDelRanking("PENALTIS", null, null)).containsExactly("Oculta", "Ana");
    }

    @Test
    void cuentasPorDelanteDaLaPosicionTambienFueraDelTopYDesempataPorFecha() {
        for (int i = 1; i <= 60; i++) {
            cuenta(i, "J" + i);
            puntos(i, "TOQUES", 100 - i, LUNES.plusDays(1));
        }

        // La cuenta 60 tiene 40 puntos: hay 59 por delante; su posición es la 60, fuera del top 50.
        Marca marca60 = dao.mejorMarca(60, "TOQUES", null, null).orElseThrow();
        assertThat(dao.cuentasPorDelante("TOQUES", null, null, 60, marca60) + 1).isEqualTo(60);
        assertThat(dao.ranking("TOQUES", null, null, 50)).hasSize(50);

        Marca marca1 = dao.mejorMarca(1, "TOQUES", null, null).orElseThrow();
        assertThat(dao.cuentasPorDelante("TOQUES", null, null, 1, marca1)).isZero();

        // Empate a 99 puntos con la cuenta 1 pero más tarde: queda detrás.
        cuenta(100, "Tarde");
        puntos(100, "TOQUES", 99, LUNES.plusDays(2));
        Marca tarde = dao.mejorMarca(100, "TOQUES", null, null).orElseThrow();
        assertThat(dao.cuentasPorDelante("TOQUES", null, null, 100, tarde) + 1).isEqualTo(2);
    }

    @Test
    void elAliasEsUnicoSinDistinguirLaClaveNormalizadaYSeComprueba() {
        cuenta(1, "Ana");

        assertThat(dao.existeAlias("ANA", 2)).isTrue();
        assertThat(dao.existeAlias("ANA", 1)).isFalse(); // es el suyo
        assertThat(dao.existeAlias("OTRO", 2)).isFalse();

        org.junit.jupiter.api.Assertions.assertThrows(DataIntegrityViolationException.class,
                () -> dao.crearPerfil(2, "ana", "ANA", "AZUL", AHORA));
    }

    @Test
    void actualizarPerfilCambiaAliasYEquipacionPorSeparado() {
        cuenta(1, "Ana");

        dao.actualizarPerfil(1, null, null, "ROSA", AHORA);
        assertThat(dao.obtenerPerfil(1)).hasValueSatisfying(p -> {
            assertThat(p.alias()).isEqualTo("Ana");
            assertThat(p.equipacion()).isEqualTo("ROSA");
        });

        dao.actualizarPerfil(1, "Anita", "ANITA", null, AHORA);
        assertThat(dao.obtenerPerfil(1)).hasValueSatisfying(p -> {
            assertThat(p.alias()).isEqualTo("Anita");
            assertThat(p.equipacion()).isEqualTo("ROSA");
        });
        assertThat(dao.obtenerPerfil(99)).isEmpty();
    }

    @Test
    void limiteDeEnviosCuentaYUltimaPartida() {
        cuenta(1, "Ana");
        puntos(1, "PENALTIS", 1, AHORA.minusDays(1));
        puntos(1, "PENALTIS", 1, AHORA.minusHours(2));
        puntos(1, "TOQUES", 1, AHORA.minusMinutes(1));

        assertThat(dao.contarPuntuacionesDesde(1, AHORA.toLocalDate().atStartOfDay())).isEqualTo(2);
        assertThat(dao.ultimaPuntuacion(1)).contains(AHORA.minusMinutes(1));
        assertThat(dao.ultimaPuntuacion(9)).isEmpty();
    }

    @Test
    void moderacionListaFiltraPorAliasYBorraPuntuaciones() {
        cuenta(1, "Ana");
        cuenta(2, "Antonio");
        cuenta(3, "Beto");
        puntos(1, "PENALTIS", 4, LUNES.plusDays(1));
        puntos(1, "PENALTIS", 6, LUNES.plusDays(2));
        puntos(1, "ATRAPA", 12, LUNES.plusDays(2));

        assertThat(dao.listarPerfilesAdmin("", 500)).hasSize(3);
        assertThat(dao.listarPerfilesAdmin("AN", 500)).extracting(p -> p.alias()).containsExactlyInAnyOrder("Ana",
                "Antonio");
        assertThat(dao.listarPerfilesAdmin("%", 500)).hasSize(3); // el comodín no se interpreta

        var ana = dao.obtenerPerfilAdmin(1).orElseThrow();
        assertThat(ana.nombre()).isEqualTo("Nombre1 Apellido1");
        assertThat(ana.email()).isEqualTo("u1@b.es");
        assertThat(ana.partidas()).isEqualTo(3);
        assertThat(ana.mejorPenaltis()).isEqualTo(6);
        assertThat(ana.mejorToques()).isZero();
        assertThat(ana.mejorAtrapa()).isEqualTo(12);

        var ultimas = dao.ultimasPuntuaciones(1, 100);
        assertThat(ultimas).hasSize(3);

        assertThat(dao.borrarPuntuacion(ultimas.get(0).id())).isEqualTo(1);
        assertThat(dao.borrarPuntuacion(ultimas.get(0).id())).isZero();
        assertThat(dao.borrarPuntuacionesDeUsuario(1)).isEqualTo(2);
        assertThat(dao.obtenerPerfil(1)).isPresent(); // el perfil sigue
    }

    @Test
    void eliminarTodoDeUsuarioBorraPerfilYPuntuacionesSoloDeEsaCuenta() {
        cuenta(1, "Ana");
        cuenta(2, "Beto");
        puntos(1, "PENALTIS", 4, LUNES.plusDays(1));
        puntos(2, "PENALTIS", 5, LUNES.plusDays(1));

        dao.eliminarTodoDeUsuario(1);

        assertThat(dao.obtenerPerfil(1)).isEmpty();
        assertThat(dao.mejorMarca(1, "PENALTIS", null, null)).isEmpty();
        assertThat(dao.obtenerPerfil(2)).isPresent();
        assertThat(aliasDelRanking("PENALTIS", null, null)).containsExactly("Beto");
    }
}
