package com.mikedev.mutxamelcf.dao.impl;

import static org.assertj.core.api.Assertions.assertThat;

import java.util.UUID;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import com.mikedev.mutxamelcf.dao.EsquemaH2;
import com.mikedev.mutxamelcf.model.Equipo;

/** EQUIPO.MODALIDAD con el esquema real (H2 modo Oracle): guardado, edición y regla de estadísticas. */
class EquipoModalidadH2Test {

    private JdbcTemplate jdbc;
    private EquipoDaoImpl equipoDao;
    private EquipoGestionDaoImpl gestionDao;

    @BeforeEach
    void setUp() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(
                "jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=Oracle;DB_CLOSE_DELAY=-1", "sa", ""));
        jdbc.execute("""
                CREATE TABLE EQUIPO (
                    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, CATEGORIA VARCHAR2(50), GRUPO VARCHAR2(10),
                    ORDEN VARCHAR2(5), NOMBRE VARCHAR2(50), DEPORTE VARCHAR2(5))""");
        EsquemaH2.crear(jdbc);
        // Editar un equipo propaga nombre, categoría y deporte a las copias de JUGADORES (enlazados por EQUIPO_ID)
        jdbc.execute("CREATE TABLE JUGADORES (ID NUMBER PRIMARY KEY, EQUIPO_ID NUMBER, EQUIPO VARCHAR2(50),"
                + " CATEGORIA VARCHAR2(50), DEPORTE VARCHAR2(5))");

        equipoDao = new EquipoDaoImpl(jdbc);
        gestionDao = new EquipoGestionDaoImpl(jdbc);
    }

    private Equipo equipo(Long id, String grupo, String modalidad) {
        Equipo equipo = new Equipo();
        equipo.setId(id);
        equipo.setCategoria("Benjamín");
        equipo.setGrupo(grupo);
        equipo.setOrden("5");
        equipo.setNombre("Benjamín " + grupo);
        equipo.setDeporte("F");
        equipo.setModalidad(modalidad);
        return equipo;
    }

    @Test
    void guardaYLeeLaModalidad() {
        assertThat(equipoDao.guardar(equipo(null, "A", "F8"))).isTrue();

        Equipo leido = equipoDao.obtenerEquipoPorNombre("Benjamín A");

        assertThat(leido.getModalidad()).isEqualTo("F8");
        assertThat(equipoDao.obtenerTodos()).extracting(Equipo::getModalidad).containsExactly("F8");
    }

    @Test
    void editarUnEquipoCambiaOConservaLaModalidad() {
        equipoDao.guardar(equipo(null, "A", "F8"));
        Long id = equipoDao.obtenerEquipoPorNombre("Benjamín A").getId();

        equipoDao.guardar(equipo(id, "A", "F8"));
        assertThat(equipoDao.obtenerEquipoPorId(id).getModalidad()).isEqualTo("F8");

        equipoDao.guardar(equipo(id, "A", "F11"));
        assertThat(equipoDao.obtenerEquipoPorId(id).getModalidad()).isEqualTo("F11");

        equipoDao.guardar(equipo(id, "A", null));
        assertThat(equipoDao.obtenerEquipoPorId(id).getModalidad()).isNull();
    }

    @Test
    void renombrarUnEquipoLlevaSusCopiasEnJugadores() {
        equipoDao.guardar(equipo(null, "A", "F8"));
        Long id = equipoDao.obtenerEquipoPorNombre("Benjamín A").getId();
        jdbc.update("INSERT INTO JUGADORES VALUES (1, ?, 'Benjamín A', 'Benjamín', 'F')", id);
        jdbc.update("INSERT INTO JUGADORES VALUES (2, NULL, 'Benjamín A', 'Benjamín', 'F')");

        Equipo renombrado = equipo(id, "A", "F8");
        renombrado.setNombre("Benjamín Estrella");
        assertThat(equipoDao.guardar(renombrado)).isTrue();

        // El jugador enlazado por EQUIPO_ID sigue al equipo; el que no tenía enlace no se toca.
        assertThat(jdbc.queryForObject("SELECT EQUIPO FROM JUGADORES WHERE ID = 1", String.class))
                .isEqualTo("Benjamín Estrella");
        assertThat(jdbc.queryForObject("SELECT EQUIPO FROM JUGADORES WHERE ID = 2", String.class))
                .isEqualTo("Benjamín A");
    }

    @Test
    void soloElF11AdmiteEstadisticas() {
        equipoDao.guardar(equipo(null, "A", "F11"));
        equipoDao.guardar(equipo(null, "B", "F8"));
        equipoDao.guardar(equipo(null, "C", "F5"));
        equipoDao.guardar(equipo(null, "D", null));

        assertThat(admite("Benjamín A")).isTrue();
        assertThat(admite("Benjamín B")).isFalse();
        assertThat(admite("Benjamín C")).isFalse();
        assertThat(admite("Benjamín D")).isFalse();
        assertThat(gestionDao.equipoAdmiteEstadisticas(9999L)).isFalse();
    }

    @Test
    void elEsquemaH2RechazaUnaModalidadFueraDeF11F8F5() {
        org.assertj.core.api.Assertions.assertThatThrownBy(
                () -> jdbc.update("INSERT INTO EQUIPO (CATEGORIA, GRUPO, NOMBRE, MODALIDAD) VALUES ('X', 'A', 'X A', 'F7')"))
                .isInstanceOf(Exception.class);
    }

    private boolean admite(String nombre) {
        Equipo equipo = equipoDao.obtenerEquipoPorNombre(nombre);
        assertThat(equipo.admiteEstadisticas()).isEqualTo(gestionDao.equipoAdmiteEstadisticas(equipo.getId()));
        return equipo.admiteEstadisticas();
    }
}
