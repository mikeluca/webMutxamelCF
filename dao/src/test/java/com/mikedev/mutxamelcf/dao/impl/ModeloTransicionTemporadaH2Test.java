package com.mikedev.mutxamelcf.dao.impl;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.sql.Date;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.List;
import java.util.UUID;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import com.mikedev.mutxamelcf.dao.EsquemaH2;
import com.mikedev.mutxamelcf.model.Clasificacion;
import com.mikedev.mutxamelcf.model.EquipoFfcv;
import com.mikedev.mutxamelcf.model.HorarioEntrenamiento;
import com.mikedev.mutxamelcf.model.JugadorTemporada;

/**
 * sql/2026-10-29_modelo_transicion_temporada.sql sobre H2: TEMPORADA_ID en los INSERT, clasificación por temporada,
 * UNIQUE de EQUIPOS_FFCV, estado INCOBRABLE y coherencia BAJA/ESTADO. Las tablas se crean con el esquema de antes
 * del script y {@code EsquemaH2.crearTransicion} aplica el cambio.
 */
class ModeloTransicionTemporadaH2Test {

    private static final long ANTERIOR = 1;
    private static final long ACTIVA = 2;
    private static final long EQUIPO = 5;

    private JdbcTemplate jdbc;

    @BeforeEach
    void setUp() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(
                "jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=Oracle;DB_CLOSE_DELAY=-1", "sa", ""));

        jdbc.execute("""
                CREATE TABLE TEMPORADAS (ID NUMBER PRIMARY KEY, NOMBRE VARCHAR2(50), FECHA_INICIO DATE,
                    FECHA_FIN DATE, ACTIVA NUMBER(1))""");
        jdbc.execute("""
                CREATE TABLE EQUIPO (ID NUMBER PRIMARY KEY, NOMBRE VARCHAR2(100), CATEGORIA VARCHAR2(100),
                    DEPORTE VARCHAR2(10), GRUPO VARCHAR2(10), ORDEN VARCHAR2(5), MODALIDAD VARCHAR2(5))""");
        jdbc.execute("""
                CREATE TABLE CLASIFICACIONES (
                    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, EQUIPO_ID NUMBER NOT NULL,
                    COMPETICION VARCHAR2(200) NOT NULL, JORNADA NUMBER, POSICION NUMBER NOT NULL,
                    NOMBRE_EQUIPO VARCHAR2(150) NOT NULL, LETRA VARCHAR2(2), ES_NUESTRO NUMBER(1) DEFAULT 0 NOT NULL,
                    PUNTOS NUMBER NOT NULL, PJ NUMBER NOT NULL, PG NUMBER NOT NULL, PE NUMBER NOT NULL,
                    PP NUMBER NOT NULL, GF NUMBER NOT NULL, GC NUMBER NOT NULL, FECHA_ULT_PARTIDO DATE,
                    FECHA_IMPORTACION TIMESTAMP NOT NULL)""");
        jdbc.execute("""
                CREATE TABLE EQUIPOS_FFCV (
                    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, EQUIPO_ID NUMBER NOT NULL,
                    COMPETICION VARCHAR2(200) NOT NULL, LETRA VARCHAR2(2),
                    CONSTRAINT UQ_EQUIPOS_FFCV UNIQUE (COMPETICION, LETRA))""");
        jdbc.execute("""
                CREATE TABLE HORARIOS_ENTRENAMIENTO (
                    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, EQUIPO_ID NUMBER NOT NULL,
                    DIA_SEMANA NUMBER(1) NOT NULL, HORA VARCHAR2(10) NOT NULL, LUGAR VARCHAR2(150),
                    ACTIVO NUMBER(1) DEFAULT 1 NOT NULL, USUARIO_ACTUALIZO_ID NUMBER, FECHA_ACTUALIZACION TIMESTAMP)""");
        jdbc.execute("""
                CREATE TABLE CUOTAS_JUGADOR (
                    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, JUGADOR_ID NUMBER, IMPORTE NUMBER,
                    ESTADO VARCHAR2(20) NOT NULL,
                    CONSTRAINT CK_CUOTA_ESTADO CHECK (ESTADO IN ('PENDIENTE', 'PARCIAL', 'PAGADO')))""");
        jdbc.execute("CREATE TABLE PAGOS (ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                + " CUOTA_JUGADOR_ID NUMBER, IMPORTE NUMBER)");

        EsquemaH2.crearPersonal(jdbc);
        EsquemaH2.crearPlantillas(jdbc);
        EsquemaH2.crearTransicion(jdbc);

        jdbc.update("INSERT INTO TEMPORADAS VALUES (?, '2025/2026', ?, ?, 0)", ANTERIOR,
                Date.valueOf("2025-07-01"), Date.valueOf("2026-06-30"));
        jdbc.update("INSERT INTO TEMPORADAS VALUES (?, '2026/2027', ?, ?, 1)", ACTIVA,
                Date.valueOf("2026-07-01"), Date.valueOf("2027-06-30"));
        jdbc.update("INSERT INTO EQUIPO (ID, NOMBRE) VALUES (?, 'Cadete A')", EQUIPO);
    }

    // ---- TEMPORADA_ID en los INSERT -------------------------------------------------------------

    private Clasificacion fila(int posicion) {
        Clasificacion c = new Clasificacion();
        c.setEquipoId(EQUIPO);
        c.setCompeticion("Primera Cadet, Grup 10");
        c.setPosicion(posicion);
        c.setNombreEquipo("Rival " + posicion);
        c.setPuntos(10);
        c.setFechaImportacion(LocalDateTime.of(2026, 10, 21, 10, 0));
        return c;
    }

    private int clasificacionesDe(long temporada) {
        return jdbc.queryForObject("SELECT COUNT(*) FROM CLASIFICACIONES WHERE EQUIPO_ID = ? AND TEMPORADA_ID = ?",
                Integer.class, EQUIPO, temporada);
    }

    @Test
    void reimportarLaClasificacionDeUnEquipoNoBorraLaDeLaTemporadaAnterior() {
        ClasificacionDaoImpl dao = new ClasificacionDaoImpl(jdbc);
        jdbc.update("INSERT INTO CLASIFICACIONES (EQUIPO_ID, COMPETICION, POSICION, NOMBRE_EQUIPO, PUNTOS, PJ, PG,"
                + " PE, PP, GF, GC, FECHA_IMPORTACION, TEMPORADA_ID) VALUES (?, 'Antigua', 1, 'Final', 60, 30, 20,"
                + " 0, 10, 50, 20, CURRENT_TIMESTAMP, ?)", EQUIPO, ANTERIOR);

        dao.insertarTodas(List.of(fila(1), fila(2)));
        assertThat(clasificacionesDe(ACTIVA)).isEqualTo(2);

        // Segunda importación: borra y vuelve a insertar solo la de la temporada activa.
        dao.eliminarPorEquipo(EQUIPO);
        dao.insertarTodas(List.of(fila(1)));

        assertThat(clasificacionesDe(ACTIVA)).isEqualTo(1);
        assertThat(clasificacionesDe(ANTERIOR)).isEqualTo(1);
    }

    @Test
    void losInsertDeClasificacionEnlaceFfcvYHorarioGuardanLaTemporadaActiva() {
        new ClasificacionDaoImpl(jdbc).insertarTodas(List.of(fila(1)));

        EquipoFfcv enlace = new EquipoFfcv();
        enlace.setEquipoId(EQUIPO);
        enlace.setCompeticion("Primera Cadet, Grup 10");
        enlace.setLetra("A");
        new EquipoFfcvDaoImpl(jdbc).crear(enlace);

        HorarioEntrenamiento horario = new HorarioEntrenamiento();
        horario.setEquipoId(EQUIPO);
        horario.setDiaSemana(2);
        horario.setHora("18:00");
        horario.setActivo(true);
        new HorarioEntrenamientoDaoImpl(jdbc).crear(horario);

        for (String tabla : List.of("CLASIFICACIONES", "EQUIPOS_FFCV", "HORARIOS_ENTRENAMIENTO")) {
            assertThat(jdbc.queryForList("SELECT TEMPORADA_ID FROM " + tabla, Long.class))
                    .as(tabla).containsExactly(ACTIVA);
        }
    }

    @Test
    void sinTemporadaActivaLosInsertFallanConUnMensajeClaro() {
        jdbc.update("UPDATE TEMPORADAS SET ACTIVA = 0");

        HorarioEntrenamiento horario = new HorarioEntrenamiento();
        horario.setEquipoId(EQUIPO);
        horario.setDiaSemana(2);
        horario.setHora("18:00");
        EquipoFfcv enlace = new EquipoFfcv();
        enlace.setEquipoId(EQUIPO);
        enlace.setCompeticion("X");

        assertThatThrownBy(() -> new ClasificacionDaoImpl(jdbc).insertarTodas(List.of(fila(1))))
                .isInstanceOf(IllegalStateException.class).hasMessageContaining("temporada activa");
        assertThatThrownBy(() -> new EquipoFfcvDaoImpl(jdbc).crear(enlace))
                .isInstanceOf(IllegalStateException.class).hasMessageContaining("temporada activa");
        assertThatThrownBy(() -> new HorarioEntrenamientoDaoImpl(jdbc).crear(horario))
                .isInstanceOf(IllegalStateException.class).hasMessageContaining("temporada activa");
    }

    // ---- UNIQUE de EQUIPOS_FFCV -------------------------------------------------------------------

    private void enlaceFfcv(long temporada, String competicion, String letra) {
        jdbc.update("INSERT INTO EQUIPOS_FFCV (EQUIPO_ID, COMPETICION, LETRA, TEMPORADA_ID) VALUES (?, ?, ?, ?)",
                EQUIPO, competicion, letra, temporada);
    }

    @Test
    void elMismoGrupoYLetraSePuedeTenerEnDosTemporadasPeroNoDosVecesEnLaMisma() {
        enlaceFfcv(ANTERIOR, "Primera Cadet, Grup 10", "A");
        enlaceFfcv(ACTIVA, "Primera Cadet, Grup 10", "A");

        assertThatThrownBy(() -> enlaceFfcv(ACTIVA, "Primera Cadet, Grup 10", "A"))
                .isInstanceOf(DataIntegrityViolationException.class);
    }

    // ---- CUOTAS_JUGADOR: INCOBRABLE ---------------------------------------------------------------

    private long cuota(String estado) {
        jdbc.update("INSERT INTO CUOTAS_JUGADOR (JUGADOR_ID, IMPORTE, ESTADO) VALUES (1, 30, ?)", estado);
        return jdbc.queryForObject("SELECT MAX(ID) FROM CUOTAS_JUGADOR", Long.class);
    }

    private void pago(long cuota, int importe) {
        jdbc.update("INSERT INTO PAGOS (CUOTA_JUGADOR_ID, IMPORTE) VALUES (?, ?)", cuota, importe);
    }

    private String estado(long cuota) {
        return jdbc.queryForObject("SELECT ESTADO FROM CUOTAS_JUGADOR WHERE ID = ?", String.class, cuota);
    }

    @Test
    void unaCuotaIncobrableNoVuelveAPendienteYPasaAPagadoSiSePagaEntera() {
        CuotaJugadorDaoImpl dao = new CuotaJugadorDaoImpl(jdbc);
        long incobrable = cuota("INCOBRABLE");

        dao.actualizarEstado(incobrable);
        assertThat(estado(incobrable)).isEqualTo("INCOBRABLE");

        // Un pago parcial tampoco la saca de INCOBRABLE...
        pago(incobrable, 10);
        dao.actualizarEstado(incobrable);
        assertThat(estado(incobrable)).isEqualTo("INCOBRABLE");

        // ...pero si los pagos cubren el importe completo, queda PAGADO.
        pago(incobrable, 20);
        dao.actualizarEstado(incobrable);
        assertThat(estado(incobrable)).isEqualTo("PAGADO");
    }

    @Test
    void elRecalculoDeLasDemasCuotasNoCambia() {
        CuotaJugadorDaoImpl dao = new CuotaJugadorDaoImpl(jdbc);
        long pendiente = cuota("PAGADO");
        long parcial = cuota("PENDIENTE");
        pago(parcial, 10);

        dao.actualizarEstado(pendiente);
        dao.actualizarEstado(parcial);

        assertThat(estado(pendiente)).isEqualTo("PENDIENTE");
        assertThat(estado(parcial)).isEqualTo("PARCIAL");
    }

    @Test
    void elCheckAdmiteIncobrableYRechazaOtrosEstados() {
        cuota("INCOBRABLE");

        assertThatThrownBy(() -> cuota("COBRADA")).isInstanceOf(DataIntegrityViolationException.class);
    }

    // ---- JUGADOR_TEMPORADA: BAJA y ESTADO coherentes -----------------------------------------------

    private JugadorTemporadaDaoImpl jugadorTemporada() {
        jdbc.update("INSERT INTO JUGADORES (ID, NOMBRE, APELLIDOS, CATEGORIA, DEPORTE, DORSAL, EQUIPO, EQUIPO_ID)"
                + " VALUES (10, 'Pablo', 'Prueba', 'Cat', 'F', 9, 'Cadete A', ?)", EQUIPO);
        return new JugadorTemporadaDaoImpl(jdbc);
    }

    private JugadorTemporada fila(boolean baja) {
        JugadorTemporada f = new JugadorTemporada();
        f.setJugadorId(10L);
        f.setTemporadaId(ACTIVA);
        f.setEquipoId(EQUIPO);
        f.setEquipoNombre("Cadete A");
        f.setBaja(baja);
        return f;
    }

    private String estadoDeLaFila() {
        return jdbc.queryForObject("SELECT ESTADO FROM JUGADOR_TEMPORADA WHERE JUGADOR_ID = 10", String.class);
    }

    @Test
    void darDeBajaYReactivarMantienenBajaYEstadoCoherentes() {
        JugadorTemporadaDaoImpl dao = jugadorTemporada();

        dao.guardar(fila(false));
        assertThat(estadoDeLaFila()).isEqualTo("CONFIRMADO");

        dao.guardar(fila(true));
        assertThat(estadoDeLaFila()).isEqualTo("BAJA");
        assertThat(dao.obtener(10L, ACTIVA).isBaja()).isTrue();
        assertThat(dao.obtener(10L, ACTIVA).getEstado()).isEqualTo("BAJA");

        dao.guardar(fila(false));
        assertThat(estadoDeLaFila()).isEqualTo("CONFIRMADO");
        assertThat(dao.obtener(10L, ACTIVA).isBaja()).isFalse();
    }

    @Test
    void unaFilaNuevaDeBajaSeInsertaConEstadoBaja() {
        jugadorTemporada().guardar(fila(true));

        assertThat(estadoDeLaFila()).isEqualTo("BAJA");
    }

    @Test
    void guardarSinBajaConservaUnEstadoQueNoEsBaja() {
        JugadorTemporadaDaoImpl dao = jugadorTemporada();
        dao.guardar(fila(false));
        jdbc.update("UPDATE JUGADOR_TEMPORADA SET ESTADO = 'PRUEBA' WHERE JUGADOR_ID = 10");

        dao.guardar(fila(false));

        assertThat(estadoDeLaFila()).isEqualTo("PRUEBA");
    }

    @Test
    void elMapperLeeLosCamposNuevosConSusValoresPorDefecto() {
        JugadorTemporadaDaoImpl dao = jugadorTemporada();
        dao.guardar(fila(false));

        JugadorTemporada leida = dao.obtener(10L, ACTIVA);

        assertThat(leida.getEstado()).isEqualTo("CONFIRMADO");
        assertThat(leida.getContinuidad()).isEqualTo("PENDIENTE");
        assertThat(leida.getFechaContinuidad()).isNull();
        assertThat(leida.getUsuarioAppContinuidadId()).isNull();
        assertThat(leida.isEquipoDefinitivo()).isTrue();

        jdbc.update("UPDATE JUGADOR_TEMPORADA SET CONTINUIDAD = 'SIGUE', FECHA_CONTINUIDAD = ?,"
                + " USUARIO_APP_CONTINUIDAD_ID = 7, EQUIPO_DEFINITIVO = 0 WHERE JUGADOR_ID = 10",
                java.sql.Timestamp.valueOf(LocalDate.of(2027, 5, 3).atTime(9, 30)));

        leida = dao.obtener(10L, ACTIVA);

        assertThat(leida.getContinuidad()).isEqualTo("SIGUE");
        assertThat(leida.getFechaContinuidad()).isEqualTo(LocalDate.of(2027, 5, 3).atTime(9, 30));
        assertThat(leida.getUsuarioAppContinuidadId()).isEqualTo(7L);
        assertThat(leida.isEquipoDefinitivo()).isFalse();
    }

    @Test
    void laBaseRechazaUnaFilaConBajaYEstadoIncoherentes() {
        jugadorTemporada();

        assertThatThrownBy(() -> jdbc.update("INSERT INTO JUGADOR_TEMPORADA (JUGADOR_ID, TEMPORADA_ID, BAJA, ESTADO)"
                + " VALUES (10, ?, 1, 'CONFIRMADO')", ACTIVA)).isInstanceOf(DataIntegrityViolationException.class);
        assertThatThrownBy(() -> jdbc.update("INSERT INTO JUGADOR_TEMPORADA (JUGADOR_ID, TEMPORADA_ID, BAJA, ESTADO)"
                + " VALUES (10, ?, 0, 'BAJA')", ACTIVA)).isInstanceOf(DataIntegrityViolationException.class);
    }
}
