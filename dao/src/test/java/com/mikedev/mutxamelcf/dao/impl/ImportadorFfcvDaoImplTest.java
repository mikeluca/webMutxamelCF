package com.mikedev.mutxamelcf.dao.impl;

import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.verify;

import java.time.LocalDate;

import org.junit.jupiter.api.Test;
import org.mockito.ArgumentCaptor;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.RowMapper;

import com.mikedev.mutxamelcf.model.DescansoEquipo;
import com.mikedev.mutxamelcf.model.Partido;

class ImportadorFfcvDaoImplTest {

    @Test
    void actualizarDatosFfcvNuncaEscribeResultadoGolesNiCancelacion() {
        JdbcTemplate jdbcTemplate = mock(JdbcTemplate.class);
        PartidoDaoImpl dao = new PartidoDaoImpl(jdbcTemplate, RELOJ);

        Partido partido = new Partido();
        partido.setId(5L);
        partido.setRival("Rival");
        partido.setHora("10:00");
        partido.setCampo("Campo");
        partido.setJornada(3);

        dao.actualizarDatosFfcv(partido);

        ArgumentCaptor<String> sql = ArgumentCaptor.forClass(String.class);
        verify(jdbcTemplate).update(sql.capture(), eq("Rival"), eq("10:00"), eq("Campo"), eq(3), eq(1), eq(5L));
        assertThat(sql.getValue())
                .contains("RIVAL", "HORA", "CAMPO", "JORNADA", "ORIGEN = 'FFCV'")
                // FECHA_ACTUALIZACION significa solo "editado a mano".
                .doesNotContain("RESULTADO", "GOLES", "CANCELADO", "DIA =", "TIPO", "FECHA_ACTUALIZACION");
    }

    private static final java.time.LocalDateTime AHORA = java.time.LocalDateTime.of(2026, 10, 21, 8, 30);
    private static final java.time.Clock RELOJ = java.time.Clock.fixed(
            AHORA.atZone(java.time.ZoneId.of("Europe/Madrid")).toInstant(), java.time.ZoneId.of("Europe/Madrid"));

    @Test
    void elImportadorNoTocaFechaActualizacionYMarcaFechaImportacion() {
        JdbcTemplate jdbc = new JdbcTemplate(new org.springframework.jdbc.datasource.DriverManagerDataSource(
                "jdbc:h2:mem:" + java.util.UUID.randomUUID() + ";MODE=Oracle;DB_CLOSE_DELAY=-1", "sa", ""));

        jdbc.execute("""
                CREATE TABLE PARTIDOS (
                    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, EQUIPO_ID NUMBER, RIVAL VARCHAR2(50),
                    DIA DATE, HORA VARCHAR2(20), CAMPO VARCHAR2(50), RESULTADO VARCHAR2(20), TIPO VARCHAR2(20),
                    ORIGEN VARCHAR2(10), JORNADA NUMBER, ES_LOCAL NUMBER(1), FECHA_ACTUALIZACION TIMESTAMP,
                    FECHA_IMPORTACION TIMESTAMP, USUARIO_ACTUALIZO_ID NUMBER, CANCELADO NUMBER(1) DEFAULT 0,
                    GOLES_FAVOR NUMBER, GOLES_CONTRA NUMBER, AVISO_RESULTADO_ENVIADO NUMBER(1) DEFAULT 0)""");

        PartidoDaoImpl dao = new PartidoDaoImpl(jdbc, RELOJ);

        Partido ffcv = new Partido();
        ffcv.setEquipoId(5L);
        ffcv.setRival("Rival FFCV");
        ffcv.setOrigen(Partido.ORIGEN_FFCV);

        Partido manual = new Partido();
        manual.setEquipoId(5L);
        manual.setRival("Rival manual");

        long idFfcv = dao.crear(ffcv).getId();
        long idManual = dao.crear(manual).getId();

        // Crear o actualizar datos no escribe ninguna de las dos fechas.
        ffcv.setId(idFfcv);
        ffcv.setRival("Otro rival");
        dao.actualizarDatosFfcv(ffcv);

        assertThat(fecha(jdbc, "FECHA_ACTUALIZACION", idFfcv)).isNull();
        assertThat(fecha(jdbc, "FECHA_IMPORTACION", idFfcv)).isNull();

        // La edición manual escribe FECHA_ACTUALIZACION y no FECHA_IMPORTACION.
        jdbc.update("UPDATE PARTIDOS SET FECHA_ACTUALIZACION = ? WHERE ID = ?",
                java.sql.Timestamp.valueOf(AHORA.minusDays(1)), idFfcv);

        dao.marcarFechaImportacion(java.util.List.of(idFfcv, idManual));

        // Marcar importación: solo FFCV, y FECHA_ACTUALIZACION queda como estaba.
        assertThat(fecha(jdbc, "FECHA_IMPORTACION", idFfcv)).isEqualTo(AHORA);
        assertThat(fecha(jdbc, "FECHA_ACTUALIZACION", idFfcv)).isEqualTo(AHORA.minusDays(1));
        assertThat(fecha(jdbc, "FECHA_IMPORTACION", idManual)).isNull();

        // Guardar un resultado (PartidoDaoImpl.actualizar) escribe FECHA_ACTUALIZACION y deja
        // FECHA_IMPORTACION como estaba.
        Partido conResultado = dao.obtenerPorId(idFfcv);
        conResultado.setGolesFavor(2);
        conResultado.setGolesContra(1);
        conResultado.setResultado("2-1");
        conResultado.setFechaActualizacion(java.sql.Timestamp.valueOf(AHORA.plusHours(5)));
        dao.actualizar(conResultado);

        assertThat(fecha(jdbc, "FECHA_IMPORTACION", idFfcv)).isEqualTo(AHORA);
        assertThat(fecha(jdbc, "FECHA_ACTUALIZACION", idFfcv)).isEqualTo(AHORA.plusHours(5));

        // Una lista vacía o nula no hace nada.
        dao.marcarFechaImportacion(java.util.List.of());
        dao.marcarFechaImportacion(null);
    }

    private static java.time.LocalDateTime fecha(JdbcTemplate jdbc, String columna, long id) {
        java.sql.Timestamp valor = jdbc.queryForObject(
                "SELECT " + columna + " FROM PARTIDOS WHERE ID = ?", java.sql.Timestamp.class, id);

        return valor == null ? null : valor.toLocalDateTime();
    }

    @Test
    @SuppressWarnings("unchecked")
    void obtenerPorCompeticionYLetraSinLetraBuscaLetraNula() {
        JdbcTemplate jdbcTemplate = mock(JdbcTemplate.class);
        EquipoFfcvDaoImpl dao = new EquipoFfcvDaoImpl(jdbcTemplate);

        dao.obtenerPorCompeticionYLetra("Primera FFCV, Grup 4", null);

        ArgumentCaptor<String> sql = ArgumentCaptor.forClass(String.class);
        verify(jdbcTemplate).query(sql.capture(), any(RowMapper.class), eq("Primera FFCV, Grup 4"));
        assertThat(sql.getValue()).contains("LETRA IS NULL");
    }

    @Test
    @SuppressWarnings("unchecked")
    void obtenerPorCompeticionYLetraConLetraLaCompara() {
        JdbcTemplate jdbcTemplate = mock(JdbcTemplate.class);
        EquipoFfcvDaoImpl dao = new EquipoFfcvDaoImpl(jdbcTemplate);

        dao.obtenerPorCompeticionYLetra("Segona FFCV, Grup 7", "B");

        ArgumentCaptor<String> sql = ArgumentCaptor.forClass(String.class);
        verify(jdbcTemplate).query(sql.capture(), any(RowMapper.class), eq("Segona FFCV, Grup 7"), eq("B"));
        assertThat(sql.getValue()).contains("LETRA = ?");
    }

    @Test
    @SuppressWarnings("unchecked")
    void descansosSeBuscanPorRangoDeFechas() {
        JdbcTemplate jdbcTemplate = mock(JdbcTemplate.class);
        DescansoEquipoDaoImpl dao = new DescansoEquipoDaoImpl(jdbcTemplate);

        dao.obtenerPorRangoFechas(LocalDate.of(2026, 10, 17), LocalDate.of(2026, 10, 18));

        ArgumentCaptor<String> sql = ArgumentCaptor.forClass(String.class);
        verify(jdbcTemplate).query(sql.capture(), any(RowMapper.class),
                eq(java.sql.Date.valueOf("2026-10-17")), eq(java.sql.Date.valueOf("2026-10-18")));
        assertThat(sql.getValue()).contains("DESCANSOS_EQUIPO").contains("BETWEEN");
    }

    @Test
    void crearDescansoInsertaEquipoFechaYJornada() {
        JdbcTemplate jdbcTemplate = mock(JdbcTemplate.class);
        DescansoEquipoDaoImpl dao = new DescansoEquipoDaoImpl(jdbcTemplate);

        dao.crear(new DescansoEquipo(null, 3L, LocalDate.of(2026, 10, 17), null));

        verify(jdbcTemplate).update(anyString(), eq(3L), eq(java.sql.Date.valueOf("2026-10-17")), eq((Object) null));
    }

}
