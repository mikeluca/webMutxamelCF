package com.mikedev.mutxamelcf.dao.impl;

import static org.assertj.core.api.Assertions.assertThat;

import java.util.List;
import java.util.UUID;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import com.mikedev.mutxamelcf.dao.EsquemaH2;
import com.mikedev.mutxamelcf.model.Equipo;

/**
 * Qué equipos juegan cada temporada (EQUIPO_TEMPORADA) sobre H2 en modo Oracle: selectores (activos, también los de
 * pretemporada), web pública (activos NORMAL), modalidad de la temporada y alta/edición desde el panel.
 */
class EquiposTemporadaH2Test {

    private static final long PASADA = 1;
    private static final long ACTIVA = 2;

    private static final long CADETE_A = 1;       // juega, NORMAL, F11
    private static final long CADETE_B = 2;       // ACTIVO = 0
    private static final long ALEVIN_PRE = 3;     // juega, PRETEMPORADA, F8 en la temporada (F11 en EQUIPO)
    private static final long INFANTIL_A = 4;     // sin fila en la temporada: F11 en EQUIPO

    private JdbcTemplate jdbc;
    private EquipoDaoImpl dao;

    @BeforeEach
    void setUp() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(
                "jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=Oracle;DB_CLOSE_DELAY=-1", "sa", ""));
        jdbc.execute("""
                CREATE TABLE TEMPORADAS (ID NUMBER PRIMARY KEY, NOMBRE VARCHAR2(50), FECHA_INICIO DATE,
                    FECHA_FIN DATE, ACTIVA NUMBER(1))""");
        jdbc.execute("""
                CREATE TABLE EQUIPO (
                    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, CATEGORIA VARCHAR2(50), GRUPO VARCHAR2(10),
                    ORDEN VARCHAR2(5), NOMBRE VARCHAR2(50), DEPORTE VARCHAR2(5), MODALIDAD VARCHAR2(3))""");
        EsquemaH2.crearPersonal(jdbc);
        EsquemaH2.crearTransicion(jdbc);
        jdbc.execute("CREATE TABLE USUARIOS_APP_CUERPO_TECNICO (USUARIO_APP_ID NUMBER, CUERPO_TECNICO_ID NUMBER)");

        jdbc.update("INSERT INTO TEMPORADAS VALUES (?, '2025/2026', DATE '2025-07-01', DATE '2026-06-30', 0)", PASADA);
        jdbc.update("INSERT INTO TEMPORADAS VALUES (?, '2026/2027', DATE '2026-07-01', DATE '2027-06-30', 1)", ACTIVA);

        jdbc.execute("CREATE TABLE PARTIDOS (ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, DIA DATE,"
                + " CANCELADO NUMBER(1) DEFAULT 0)");
        // Por defecto la temporada activa ya ha empezado a jugar: no es verano
        partido("2026-09-20", 0);

        equipo(CADETE_A, "Cadete", "A", "F", "F11");
        equipo(CADETE_B, "Cadete", "B", "F", "F11");
        equipo(ALEVIN_PRE, "Alevín", "P", "H", "F11");
        equipo(INFANTIL_A, "Infantil", "A", "G", "F11");

        enTemporada(CADETE_A, ACTIVA, 1, "F11", "NORMAL");
        enTemporada(CADETE_B, ACTIVA, 0, "F11", "NORMAL");
        enTemporada(ALEVIN_PRE, ACTIVA, 1, "F8", "PRETEMPORADA");
        // Una temporada pasada no cuenta: ahí el Cadete B sí jugaba y el A no.
        enTemporada(CADETE_A, PASADA, 0, "F11", "NORMAL");
        enTemporada(CADETE_B, PASADA, 1, "F11", "NORMAL");

        // Los IDs de arriba son explícitos: los equipos que cree el DAO siguen desde 100
        jdbc.execute("ALTER TABLE EQUIPO ALTER COLUMN ID RESTART WITH 100");

        dao = new EquipoDaoImpl(jdbc);
    }

    private void partido(String dia, int cancelado) {
        jdbc.update("INSERT INTO PARTIDOS (DIA, CANCELADO) VALUES (DATE '" + dia + "', ?)", cancelado);
    }

    private void equipo(long id, String categoria, String grupo, String orden, String modalidad) {
        jdbc.update("INSERT INTO EQUIPO (ID, CATEGORIA, GRUPO, ORDEN, NOMBRE, DEPORTE, MODALIDAD)"
                + " VALUES (?, ?, ?, ?, ?, 'F', ?)", id, categoria, grupo, orden, categoria + " " + grupo, modalidad);
    }

    private void enTemporada(long equipo, long temporada, int activo, String modalidad, String tipo) {
        jdbc.update("INSERT INTO EQUIPO_TEMPORADA (EQUIPO_ID, TEMPORADA_ID, ACTIVO, MODALIDAD, TIPO)"
                + " VALUES (?, ?, ?, ?, ?)", equipo, temporada, activo, modalidad, tipo);
    }

    private static List<Long> ids(List<Equipo> equipos) {
        return equipos.stream().map(Equipo::getId).toList();
    }

    // ---- selectores y web pública ------------------------------------------------------------------

    @Test
    void losSelectoresSoloTienenLosActivosYLosDePretemporadaTambien() {
        assertThat(ids(dao.obtenerActivos())).containsExactlyInAnyOrder(CADETE_A, ALEVIN_PRE);
        assertThat(ids(dao.obtenerActivosPorCategoria("Alevín"))).containsExactly(ALEVIN_PRE);
        assertThat(dao.obtenerActivosPorCategoria("Cadete")).extracting(Equipo::getNombre).containsExactly("Cadete A");
    }

    @Test
    void enVeranoLaWebPublicaMuestraLosEquiposDeLaTemporadaAnterior() {
        jdbc.update("DELETE FROM PARTIDOS");
        partido("2026-09-20", 1); // un partido cancelado no cuenta como temporada empezada

        // Cadete B jugaba en la anterior; Cadete A (activo ahora) sigue visible; la pretemporada, nunca
        assertThat(ids(dao.obtenerActivosPublicos())).containsExactlyInAnyOrder(CADETE_A, CADETE_B);
        assertThat(ids(dao.obtenerActivosPublicosPorDeporte("F"))).containsExactlyInAnyOrder(CADETE_A, CADETE_B);
    }

    @Test
    void conPartidosEnLaTemporadaActivaLaWebPublicaDejaDeMirarLaAnterior() {
        partido("2026-09-27", 0);

        assertThat(ids(dao.obtenerActivosPublicos())).containsExactly(CADETE_A);
    }

    @Test
    void laWebPublicaSoloTieneLosActivosNormalesYNoLosDePretemporada() {
        assertThat(ids(dao.obtenerActivosPublicos())).containsExactly(CADETE_A);
        assertThat(ids(dao.obtenerActivosPublicosPorDeporte("F"))).containsExactly(CADETE_A);
        assertThat(dao.obtenerEquiposAgrupadosPorCategoria("F")).containsOnlyKeys("F")
                .extractingByKey("F").asList().hasSize(1);
    }

    @Test
    void unEquipoSinFilaEnLaTemporadaActivaNoSalePeroElPanelLoVe() {
        assertThat(ids(dao.obtenerActivos())).doesNotContain(INFANTIL_A);
        assertThat(ids(dao.obtenerActivosPublicos())).doesNotContain(INFANTIL_A);

        // El panel de Equipos ve todos, con su estado en la temporada activa.
        List<Equipo> todos = dao.obtenerTodos();
        assertThat(ids(todos)).containsExactlyInAnyOrder(CADETE_A, CADETE_B, ALEVIN_PRE, INFANTIL_A);
        assertThat(todos).filteredOn(e -> e.getId() == CADETE_B).extracting(Equipo::getActivoTemporada)
                .containsExactly(false);
        assertThat(todos).filteredOn(e -> e.getId() == ALEVIN_PRE).extracting(Equipo::getTipoTemporada)
                .containsExactly("PRETEMPORADA");
        assertThat(todos).filteredOn(e -> e.getId() == INFANTIL_A).extracting(Equipo::getActivoTemporada)
                .containsExactly((Boolean) null);
    }

    @Test
    void sinTemporadaActivaNoSeFiltraNada() {
        jdbc.update("UPDATE TEMPORADAS SET ACTIVA = 0");

        assertThat(ids(dao.obtenerActivos())).hasSize(4);
        assertThat(ids(dao.obtenerActivosPublicos())).hasSize(4);
    }

    // ---- modalidad ---------------------------------------------------------------------------------

    @Test
    void laModalidadEsLaDeLaTemporadaConLaDeEquipoDeRespaldo() {
        assertThat(dao.obtenerEquipoPorId(ALEVIN_PRE).getModalidad()).isEqualTo("F8");
        assertThat(dao.obtenerEquipoPorNombre("Alevín P").getModalidad()).isEqualTo("F8");
        // Sin fila en la temporada: la de EQUIPO
        assertThat(dao.obtenerEquipoPorId(INFANTIL_A).getModalidad()).isEqualTo("F11");
        // Fila sin modalidad: también la de EQUIPO
        jdbc.update("UPDATE EQUIPO_TEMPORADA SET MODALIDAD = NULL WHERE EQUIPO_ID = ? AND TEMPORADA_ID = ?",
                CADETE_A, ACTIVA);
        assertThat(dao.obtenerEquipoPorId(CADETE_A).getModalidad()).isEqualTo("F11");
    }

    @Test
    void admiteEstadisticasSigueALaModalidadDeLaTemporada() {
        EquipoGestionDaoImpl gestion = new EquipoGestionDaoImpl(jdbc);

        assertThat(gestion.equipoAdmiteEstadisticas(CADETE_A)).isTrue();
        // F8 en la temporada aunque EQUIPO diga F11
        assertThat(gestion.equipoAdmiteEstadisticas(ALEVIN_PRE)).isFalse();
        // Sin fila: la de EQUIPO
        assertThat(gestion.equipoAdmiteEstadisticas(INFANTIL_A)).isTrue();
        assertThat(gestion.equipoAdmiteEstadisticas(999L)).isFalse();
    }

    // ---- mis equipos (perfil de la app) ------------------------------------------------------------

    @Test
    void misEquiposDelPerfilSonLosActivosConLaModalidadDeLaTemporada() {
        jdbc.update("INSERT INTO CUERPO_TECNICO (ID, NOMBRE, APELLIDOS) VALUES (1, 'Ana', 'Ruiz')");
        for (long equipo : new long[] { CADETE_A, CADETE_B, ALEVIN_PRE }) {
            jdbc.update("INSERT INTO CUERPO_TECNICO_EQUIPO (CUERPO_TECNICO_ID, EQUIPO_ID) VALUES (1, ?)", equipo);
        }
        jdbc.update("INSERT INTO USUARIOS_APP_CUERPO_TECNICO VALUES (100, 1)");

        List<Equipo> equipos = new PerfilAppDaoImpl(jdbc).obtenerEquiposPorUsuario(100);

        // El Cadete B (ACTIVO = 0) no sale; el de pretemporada sí, con su modalidad F8.
        assertThat(ids(equipos)).containsExactlyInAnyOrder(CADETE_A, ALEVIN_PRE);
        assertThat(equipos).filteredOn(e -> e.getId() == ALEVIN_PRE).extracting(Equipo::getModalidad)
                .containsExactly("F8");
    }

    // ---- panel de Equipos: alta y edición ----------------------------------------------------------

    private Equipo nuevo(String grupo, String modalidad, Boolean juega) {
        Equipo e = new Equipo();
        e.setCategoria("Benjamín");
        e.setGrupo(grupo);
        e.setOrden("5");
        e.setNombre("Benjamín " + grupo);
        e.setDeporte("F");
        e.setModalidad(modalidad);
        e.setActivoTemporada(juega);
        return e;
    }

    private java.util.Map<String, Object> filaDeTemporada(String nombre) {
        return jdbc.queryForMap("SELECT ET.ACTIVO, ET.MODALIDAD, ET.TIPO, E.MODALIDAD AS MODALIDAD_EQUIPO"
                + " FROM EQUIPO_TEMPORADA ET JOIN EQUIPO E ON E.ID = ET.EQUIPO_ID"
                + " WHERE E.NOMBRE = ? AND ET.TEMPORADA_ID = ?", nombre, ACTIVA);
    }

    @Test
    void unEquipoNuevoSeCreaYaActivoEnLaTemporadaActivaConSuModalidad() {
        assertThat(dao.guardar(nuevo("A", "F8", null))).isTrue();

        java.util.Map<String, Object> fila = filaDeTemporada("Benjamín A");
        assertThat(((Number) fila.get("ACTIVO")).intValue()).isEqualTo(1);
        assertThat(fila.get("MODALIDAD")).isEqualTo("F8");
        assertThat(fila.get("TIPO")).isEqualTo("NORMAL");
        // EQUIPO.MODALIDAD sincronizada
        assertThat(fila.get("MODALIDAD_EQUIPO")).isEqualTo("F8");
        assertThat(ids(dao.obtenerActivos())).contains(dao.obtenerEquipoPorNombre("Benjamín A").getId());
    }

    @Test
    void editarUnEquipoMarcaSiJuegaYCambiaSuModalidadEnLaTemporada() {
        dao.guardar(nuevo("A", "F8", null));
        long id = dao.obtenerEquipoPorNombre("Benjamín A").getId();

        Equipo editado = nuevo("A", "F11", false);
        editado.setId(id);
        assertThat(dao.guardar(editado)).isTrue();

        java.util.Map<String, Object> fila = filaDeTemporada("Benjamín A");
        assertThat(((Number) fila.get("ACTIVO")).intValue()).isZero();
        assertThat(fila.get("MODALIDAD")).isEqualTo("F11");
        assertThat(fila.get("MODALIDAD_EQUIPO")).isEqualTo("F11");
        assertThat(ids(dao.obtenerActivos())).doesNotContain(id);

        // Sin indicar si juega (null) se conserva: sigue sin jugar
        Equipo sinTocar = nuevo("A", "F5", null);
        sinTocar.setId(id);
        dao.guardar(sinTocar);
        assertThat(((Number) filaDeTemporada("Benjamín A").get("ACTIVO")).intValue()).isZero();
        assertThat(filaDeTemporada("Benjamín A").get("MODALIDAD")).isEqualTo("F5");
    }

    @Test
    void editarUnEquipoSinFilaLaCreaYNoTocaLasDeOtrasTemporadas() {
        Equipo editado = nuevo("A", "F8", null);
        editado.setId(INFANTIL_A);
        editado.setCategoria("Infantil");
        editado.setNombre("Infantil A");
        assertThat(dao.guardar(editado)).isTrue();

        assertThat(((Number) filaDeTemporada("Infantil A").get("ACTIVO")).intValue()).isEqualTo(1);
        // La fila de la temporada pasada del Cadete B sigue igual
        assertThat(jdbc.queryForObject("SELECT ACTIVO FROM EQUIPO_TEMPORADA WHERE EQUIPO_ID = ? AND TEMPORADA_ID = ?",
                Integer.class, CADETE_B, PASADA)).isEqualTo(1);
    }

    @Test
    void sinTemporadaActivaGuardarUnEquipoNoCreaFilaDeTemporada() {
        jdbc.update("UPDATE TEMPORADAS SET ACTIVA = 0");

        assertThat(dao.guardar(nuevo("A", "F8", null))).isTrue();

        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM EQUIPO_TEMPORADA", Integer.class)).isEqualTo(5);
    }

    @Test
    void borrarUnEquipoBorraTambienSusFilasDeTemporada() {
        dao.eliminarEquipo(CADETE_B);

        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM EQUIPO_TEMPORADA WHERE EQUIPO_ID = ?", Integer.class,
                CADETE_B)).isZero();
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM EQUIPO WHERE ID = ?", Integer.class, CADETE_B)).isZero();
    }
}
