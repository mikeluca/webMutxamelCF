package com.mikedev.mutxamelcf.dao.impl;

import static org.assertj.core.api.Assertions.assertThat;

import java.time.LocalDateTime;
import java.util.List;
import java.util.UUID;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import com.mikedev.mutxamelcf.model.JugadorBasico;
import com.mikedev.mutxamelcf.model.PartidoLiveEvento;

class PartidoLiveEventoDaoH2Test {

    private static final LocalDateTime T0 = LocalDateTime.of(2026, 10, 24, 11, 0, 0, 123_456_000);

    private JdbcTemplate jdbc;
    private PartidoLiveEventoDaoImpl dao;

    @BeforeEach
    void setUp() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(
                "jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=Oracle;DB_CLOSE_DELAY=-1", "sa", ""));

        jdbc.execute("""
                CREATE TABLE PARTIDO_LIVE_EVENTOS (
                    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    PARTIDO_ID NUMBER NOT NULL,
                    TIPO VARCHAR2(20) NOT NULL,
                    JUGADOR_ID NUMBER NULL,
                    AUTOR_TEXTO VARCHAR2(60) NULL,
                    USUARIO_APP_ID NUMBER NOT NULL,
                    FECHA TIMESTAMP NOT NULL,
                    ANULADO NUMBER(1) DEFAULT 0 NOT NULL,
                    FECHA_ANULACION TIMESTAMP NULL,
                    RESULTADO_ANTERIOR VARCHAR2(20) NULL,
                    GOLES_FAVOR_ANTERIOR NUMBER NULL,
                    GOLES_CONTRA_ANTERIOR NUMBER NULL,
                    AVISO_ANTERIOR NUMBER(1) NULL,
                    ESTADISTICAS_GUARDADAS NUMBER(1) DEFAULT 0 NOT NULL)""");
        jdbc.execute("""
                CREATE TABLE JUGADORES (
                    ID NUMBER PRIMARY KEY, DORSAL NUMBER, NOMBRE VARCHAR2(50), APELLIDOS VARCHAR2(50))""");

        dao = new PartidoLiveEventoDaoImpl(jdbc);
    }

    private PartidoLiveEvento evento(long partido, String tipo, LocalDateTime fecha) {
        PartidoLiveEvento e = new PartidoLiveEvento();
        e.setPartidoId(partido);
        e.setTipo(tipo);
        e.setUsuarioAppId(7L);
        e.setFecha(fecha);
        return dao.crear(e);
    }

    @Test
    void creaYLeeUnEventoConTodosSusCampos() {
        PartidoLiveEvento e = new PartidoLiveEvento();
        e.setPartidoId(30L);
        e.setTipo(PartidoLiveEvento.GOL_FAVOR);
        e.setJugadorId(10L);
        e.setUsuarioAppId(7L);
        e.setFecha(T0);

        dao.crear(e);

        PartidoLiveEvento leido = dao.obtenerPorId(e.getId());

        assertThat(e.getId()).isNotNull();
        assertThat(leido.getTipo()).isEqualTo("GOL_FAVOR");
        assertThat(leido.getJugadorId()).isEqualTo(10L);
        assertThat(leido.getAutorTexto()).isNull();
        // La fecha vuelve exactamente igual (microsegundos): el deshacer del final depende de ello.
        assertThat(leido.getFecha()).isEqualTo(T0);
        assertThat(leido.isAnulado()).isFalse();
        assertThat(leido.isEstadisticasGuardadas()).isFalse();
        assertThat(leido.getAvisoAnterior()).isNull();
    }

    @Test
    void guardaLaInstantaneaDelFinal() {
        PartidoLiveEvento e = new PartidoLiveEvento();
        e.setPartidoId(30L);
        e.setTipo(PartidoLiveEvento.FINAL);
        e.setUsuarioAppId(7L);
        e.setFecha(T0);
        e.setResultadoAnterior("1-1");
        e.setGolesFavorAnterior(1);
        e.setGolesContraAnterior(1);
        e.setAvisoAnterior(true);
        e.setEstadisticasGuardadas(true);

        dao.crear(e);

        PartidoLiveEvento leido = dao.obtenerPorId(e.getId());

        assertThat(leido.getResultadoAnterior()).isEqualTo("1-1");
        assertThat(leido.getGolesFavorAnterior()).isEqualTo(1);
        assertThat(leido.getGolesContraAnterior()).isEqualTo(1);
        assertThat(leido.getAvisoAnterior()).isTrue();
        assertThat(leido.isEstadisticasGuardadas()).isTrue();
    }

    @Test
    void elAutorEnTextoSeGuarda() {
        PartidoLiveEvento e = new PartidoLiveEvento();
        e.setPartidoId(30L);
        e.setTipo(PartidoLiveEvento.GOL_FAVOR);
        e.setAutorTexto("p.p.");
        e.setUsuarioAppId(7L);
        e.setFecha(T0);

        dao.crear(e);

        PartidoLiveEvento leido = dao.obtenerPorId(e.getId());

        assertThat(leido.getAutorTexto()).isEqualTo("p.p.");
        assertThat(leido.getJugadorId()).isNull();
    }

    @Test
    void losNoAnuladosVanEnOrdenYSoloDeSuPartido() {
        evento(30, "INICIO", T0);
        evento(31, "INICIO", T0);
        PartidoLiveEvento gol = evento(30, "GOL_CONTRA", T0.plusMinutes(5));
        evento(30, "DESCANSO", T0.plusMinutes(45));

        dao.anular(gol.getId(), T0.plusMinutes(6));

        assertThat(dao.obtenerNoAnuladosPorPartido(30L)).extracting(PartidoLiveEvento::getTipo)
                .containsExactly("INICIO", "DESCANSO");
        assertThat(dao.obtenerNoAnuladosPorPartido(31L)).hasSize(1);
    }

    @Test
    void anularMarcaLaFilaSinBorrarlaYSoloUnaVez() {
        PartidoLiveEvento e = evento(30, "GOL_CONTRA", T0);

        assertThat(dao.anular(e.getId(), T0.plusSeconds(30))).isEqualTo(1);
        assertThat(dao.anular(e.getId(), T0.plusSeconds(40))).isZero();

        PartidoLiveEvento leido = dao.obtenerPorId(e.getId());
        assertThat(leido.isAnulado()).isTrue();
        assertThat(leido.getFechaAnulacion()).isEqualTo(T0.plusSeconds(30));
    }

    @Test
    void losEventosConLaMismaFechaSeOrdenanPorId() {
        PartidoLiveEvento primero = evento(30, "INICIO", T0);
        PartidoLiveEvento segundo = evento(30, "GOL_CONTRA", T0);

        assertThat(dao.obtenerNoAnuladosPorPartido(30L)).extracting(PartidoLiveEvento::getId)
                .containsExactly(primero.getId(), segundo.getId());
    }

    @Test
    void losJugadoresBasicosTraenDorsalNuloComoNulo() {
        jdbc.update("INSERT INTO JUGADORES VALUES (10, 9, 'Pablo', 'Garcia')");
        jdbc.update("INSERT INTO JUGADORES VALUES (12, NULL, 'Sin', 'Dorsal')");
        jdbc.update("INSERT INTO JUGADORES VALUES (13, 4, 'Otro', 'Jugador')");

        List<JugadorBasico> jugadores = dao.obtenerJugadoresBasicos(List.of(10L, 12L));

        assertThat(jugadores).extracting(j -> j.id() + ":" + j.dorsal() + ":" + j.nombreCompleto())
                .containsExactlyInAnyOrder("10:9:Pablo Garcia", "12:null:Sin Dorsal");
        assertThat(dao.obtenerJugadoresBasicos(List.of())).isEmpty();
    }

}
