-- JUGADORES y CUERPO_TECNICO tal como están en producción: SIN fecha_nacimiento, poblacion ni
-- nacionalidad (no se guardan; minimización de datos). Un INSERT que las use tiene que fallar.
-- JUGADORES lleva además lo de sql/2026-10-29_plantillas_temporada.sql: EQUIPO_ID (el enlace con EQUIPO; la FK no se
-- crea aquí porque cada test define su propia EQUIPO), ANIO_NACIMIENTO (solo el año, nunca la fecha completa) y
-- FECHA_BAJA (nula mientras el jugador forma parte de la plantilla actual).
CREATE TABLE JUGADORES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(100),
    APELLIDOS VARCHAR2(100),
    CATEGORIA VARCHAR2(100),
    DEPORTE VARCHAR2(50),
    DORSAL NUMBER,
    POSICION VARCHAR2(50),
    EQUIPO VARCHAR2(100),
    FOTO BLOB,
    EQUIPO_ID NUMBER,
    ANIO_NACIMIENTO NUMBER(4),
    FECHA_BAJA DATE
);

CREATE TABLE CUERPO_TECNICO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(100),
    APELLIDOS VARCHAR2(100),
    CATEGORIA VARCHAR2(100),
    DEPORTE VARCHAR2(50),
    EQUIPO VARCHAR2(100),
    PUESTO VARCHAR2(100),
    FOTO BLOB
);

-- sql/2026-10-30_cuerpo_tecnico_equipo_id.sql: un técnico puede llevar varios equipos. PUESTO es el puesto en ESE
-- equipo (NULL = el puesto general de la ficha). La FK a EQUIPO no se crea aquí porque cada test define su propia EQUIPO.
CREATE TABLE CUERPO_TECNICO_EQUIPO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUERPO_TECNICO_ID NUMBER NOT NULL,
    EQUIPO_ID NUMBER NOT NULL,
    PUESTO VARCHAR2(100 CHAR),
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_CTE_CUERPO_TECNICO FOREIGN KEY (CUERPO_TECNICO_ID) REFERENCES CUERPO_TECNICO(ID),
    CONSTRAINT UQ_CTE_FICHA_EQUIPO UNIQUE (CUERPO_TECNICO_ID, EQUIPO_ID)
);
