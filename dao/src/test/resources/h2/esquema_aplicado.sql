-- Esquema que hay aplicado en DEV y PRO de las tablas de la respuesta a la
-- convocatoria y de la retransmisión por partido, ANTES de
-- sql/2026-10-21_ajustes_post_revision.sql (que se aplica encima en
-- h2/ajustes_post_revision.sql). Sin claves ajenas: los tests no crean las
-- tablas a las que apuntan (PARTIDOS, JUGADORES, USUARIOS_APP...) completas.

CREATE TABLE CONVOCATORIA_JUGADOR (
    ID                        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CONVOCATORIA_ID           NUMBER NOT NULL,
    JUGADOR_ID                NUMBER NOT NULL,
    RESPUESTA                 VARCHAR2(10) NULL,
    MOTIVO                    VARCHAR2(500) NULL,
    FECHA_RESPUESTA           TIMESTAMP NULL,
    USUARIO_APP_RESPUESTA_ID  NUMBER NULL,
    CONSTRAINT CK_CONV_JUG_RESPUESTA CHECK (RESPUESTA IN ('VA', 'NO_PUEDE'))
);

CREATE TABLE PARTIDO_LIVE_EVENTOS (
    ID                        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PARTIDO_ID                NUMBER NOT NULL,
    TIPO                      VARCHAR2(20) NOT NULL,
    JUGADOR_ID                NUMBER NULL,
    AUTOR_TEXTO               VARCHAR2(60) NULL,
    USUARIO_APP_ID            NUMBER NOT NULL,
    FECHA                     TIMESTAMP NOT NULL,
    ANULADO                   NUMBER(1) DEFAULT 0 NOT NULL,
    FECHA_ANULACION           TIMESTAMP NULL,
    CONSTRAINT CK_LIVE_EVENTOS_TIPO CHECK (TIPO IN
        ('INICIO', 'GOL_FAVOR', 'GOL_CONTRA', 'DESCANSO', 'SEGUNDA_PARTE', 'FINAL')),
    CONSTRAINT CK_LIVE_EVENTOS_ANULADO CHECK (ANULADO IN (0, 1)),
    CONSTRAINT CK_LIVE_EVENTOS_AUTOR CHECK (JUGADOR_ID IS NULL OR AUTOR_TEXTO IS NULL)
);

CREATE INDEX IDX_LIVE_EVENTOS_PARTIDO_FECHA ON PARTIDO_LIVE_EVENTOS (PARTIDO_ID, FECHA);

-- ENTRENAMIENTOS tal como estaba antes de sql/2026-10-23_entrenador_coordinador_admin.sql
-- (con la sesión de calendario de sql/2026-09-28_entrenamiento_desde_sesion.sql).
CREATE TABLE ENTRENAMIENTOS (
    ID                        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EQUIPO_ID                 NUMBER NOT NULL,
    FECHA                     DATE NOT NULL,
    USUARIO_ENTRENADOR_ID     NUMBER NOT NULL,
    SESION_ENTRENAMIENTO_ID   NUMBER NULL,
    FECHA_CREACION            TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT UQ_ENTRENAMIENTOS_SESION UNIQUE (SESION_ENTRENAMIENTO_ID)
);
