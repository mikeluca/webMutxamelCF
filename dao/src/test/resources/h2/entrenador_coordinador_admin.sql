-- 2) Cola de moderación
CREATE TABLE REPORTES_COMUNICACION (
    ID                     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COMUNICACION_ID        NUMBER               NOT NULL,
    AUTOR_ID               NUMBER               NULL,
    REPORTADOR_ID          NUMBER               NOT NULL,
    MOTIVO                 VARCHAR2(500 CHAR)   NULL,
    TITULO_COPIA           VARCHAR2(300 CHAR)   NULL,
    CONTENIDO_COPIA        CLOB                 NULL,
    FECHA_MENSAJE          TIMESTAMP            NULL,
    FECHA_REPORTE          TIMESTAMP            NOT NULL,
    ESTADO                 VARCHAR2(20)         DEFAULT 'PENDIENTE' NOT NULL,
    RESUELTO_POR_ID        NUMBER               NULL,
    FECHA_RESOLUCION       TIMESTAMP            NULL,
    NOTA_RESOLUCION        VARCHAR2(500 CHAR)   NULL,
    CONSTRAINT CK_REPORTE_ESTADO CHECK (ESTADO IN ('PENDIENTE','DESCARTADO','MENSAJE_BORRADO','AUTOR_DESACTIVADO')),
    CONSTRAINT UQ_REPORTE_COM_REPORTADOR UNIQUE (COMUNICACION_ID, REPORTADOR_ID)
);
CREATE INDEX IDX_REPORTE_ESTADO_FECHA ON REPORTES_COMUNICACION (ESTADO, FECHA_REPORTE);
