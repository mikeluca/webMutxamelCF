-- ajenas a USUARIOS_APP y JUGADORES (los tests no las crean completas), sin permisos ni sinónimos ni el bloque de deshacer.
CREATE TABLE SOLICITUDES_FAMILIA (
    ID                          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USUARIO_APP_ID              NUMBER NOT NULL,
    NOMBRE                      VARCHAR2(100 CHAR) NOT NULL,
    APELLIDOS                   VARCHAR2(150 CHAR) NOT NULL,
    EMAIL                       VARCHAR2(150 CHAR) NOT NULL,
    TELEFONO                    VARCHAR2(20 CHAR) NULL,
    PARENTESCO                  VARCHAR2(10) NOT NULL,
    ESTADO                      VARCHAR2(15) DEFAULT 'PENDIENTE_EMAIL' NOT NULL,
    MOTIVO_RECHAZO              VARCHAR2(500 CHAR) NULL,
    ACEPTA_PRIVACIDAD           NUMBER(1) NOT NULL,
    DECLARA_REPRESENTANTE       NUMBER(1) NOT NULL,
    IP_ORIGEN                   VARCHAR2(45) NULL,
    FECHA_SOLICITUD             TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_REVISION              TIMESTAMP NULL,
    REVISADA_POR_USUARIO_APP_ID NUMBER NULL,
    REVISADA_POR_PANEL          VARCHAR2(100 CHAR) NULL,
    CONSTRAINT CK_SOLFAM_PARENTESCO CHECK (PARENTESCO IN ('MADRE', 'PADRE', 'TUTOR', 'OTRO')),
    CONSTRAINT CK_SOLFAM_ESTADO CHECK (ESTADO IN ('PENDIENTE_EMAIL', 'PENDIENTE', 'APROBADA', 'RECHAZADA', 'CADUCADA')),
    CONSTRAINT CK_SOLFAM_PRIVACIDAD CHECK (ACEPTA_PRIVACIDAD = 1),
    CONSTRAINT CK_SOLFAM_REPRESENTANTE CHECK (DECLARA_REPRESENTANTE = 1)
);

CREATE INDEX IDX_SOLFAM_USUARIO ON SOLICITUDES_FAMILIA (USUARIO_APP_ID);
CREATE INDEX IDX_SOLFAM_ESTADO ON SOLICITUDES_FAMILIA (ESTADO, FECHA_SOLICITUD);

CREATE TABLE SOLICITUDES_FAMILIA_JUGADOR (
    ID                 NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SOLICITUD_ID       NUMBER NOT NULL,
    NOMBRE_JUGADOR     VARCHAR2(100 CHAR) NOT NULL,
    APELLIDOS_JUGADOR  VARCHAR2(150 CHAR) NOT NULL,
    EQUIPO_TEXTO       VARCHAR2(100 CHAR) NULL,
    JUGADOR_ID         NUMBER NULL,
    ESTADO             VARCHAR2(10) DEFAULT 'PENDIENTE' NOT NULL,
    CONSTRAINT FK_SOLFAMJUG_SOLICITUD FOREIGN KEY (SOLICITUD_ID) REFERENCES SOLICITUDES_FAMILIA(ID) ON DELETE CASCADE,
    CONSTRAINT CK_SOLFAMJUG_ESTADO CHECK (ESTADO IN ('PENDIENTE', 'APROBADO', 'RECHAZADO')),
    CONSTRAINT CK_SOLFAMJUG_APROBADO CHECK (ESTADO <> 'APROBADO' OR JUGADOR_ID IS NOT NULL)
);

CREATE INDEX IDX_SOLFAMJUG_SOLICITUD ON SOLICITUDES_FAMILIA_JUGADOR (SOLICITUD_ID);
CREATE INDEX IDX_SOLFAMJUG_JUGADOR ON SOLICITUDES_FAMILIA_JUGADOR (JUGADOR_ID);
