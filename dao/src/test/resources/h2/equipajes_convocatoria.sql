-- Versión para H2 de sql/2026-11-03_equipajes_convocatoria.sql: la tabla EQUIPACIONES y las mismas restricciones
-- CHECK, sin GRANT, sinónimo, comprobaciones ni bloque de deshacer (solo existen en Oracle).
-- La tabla CONVOCATORIAS no forma parte del esquema compartido: cada test que la necesita crea la suya, así que las
-- columnas se añaden solo si existe (y si no las tenía ya) y la clave ajena y los CHECK solo si las dos columnas
-- están. Los tests que crean CONVOCATORIAS después de EsquemaH2.crear declaran las columnas ellos.

CREATE TABLE EQUIPACIONES (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE      VARCHAR2(50 CHAR) NOT NULL,
    CAMISETA    VARCHAR2(50 CHAR) NULL,
    PANTALON    VARCHAR2(50 CHAR) NULL,
    MEDIAS      VARCHAR2(50 CHAR) NULL,
    COLOR_HEX   VARCHAR2(7) NULL,
    ORDEN       NUMBER DEFAULT 0 NOT NULL,
    ACTIVA      NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT UQ_EQUIPACIONES_NOMBRE UNIQUE (NOMBRE),
    CONSTRAINT CK_EQUIPACIONES_COLOR_HEX CHECK (REGEXP_LIKE(COLOR_HEX, '^#[0-9A-Fa-f]{6}$')),
    CONSTRAINT CK_EQUIPACIONES_ACTIVA CHECK (ACTIVA IN (0, 1))
);

ALTER TABLE IF EXISTS CONVOCATORIAS ADD COLUMN IF NOT EXISTS EQUIPACION_ID NUMBER NULL;
ALTER TABLE IF EXISTS CONVOCATORIAS ADD COLUMN IF NOT EXISTS EQUIPACION_MOCHILA_ID NUMBER NULL;
ALTER TABLE IF EXISTS CONVOCATORIAS ADD CONSTRAINT IF NOT EXISTS FK_CONVOCATORIAS_EQUIPACION
    FOREIGN KEY (EQUIPACION_ID) REFERENCES EQUIPACIONES(ID);
ALTER TABLE IF EXISTS CONVOCATORIAS ADD CONSTRAINT IF NOT EXISTS FK_CONVOCATORIAS_EQUIP_MOCHILA
    FOREIGN KEY (EQUIPACION_MOCHILA_ID) REFERENCES EQUIPACIONES(ID);
ALTER TABLE IF EXISTS CONVOCATORIAS ADD CONSTRAINT IF NOT EXISTS CK_CONVOCATORIAS_EQUIPAJE CHECK (
    EQUIPACION_MOCHILA_ID IS NULL
    OR (EQUIPACION_ID IS NOT NULL AND EQUIPACION_ID <> EQUIPACION_MOCHILA_ID));
