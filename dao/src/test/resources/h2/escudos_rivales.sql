CREATE TABLE CLUBES_RIVALES (
    ID                   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE               VARCHAR2(150 CHAR) NOT NULL,
    ESCUDO               BLOB NULL,
    ESCUDO_VERSION       NUMBER DEFAULT 0 NOT NULL,
    FECHA_ACTUALIZACION  TIMESTAMP NULL,
    FECHA_CREACION       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CODIGO_FFCV          NUMBER NULL,
    CONSTRAINT UQ_CLUBES_RIVALES_NOMBRE UNIQUE (NOMBRE),
    CONSTRAINT UQ_CLUBES_RIVALES_CODIGO UNIQUE (CODIGO_FFCV)
);

CREATE TABLE CLUBES_RIVALES_ALIAS (
    ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CLUB_RIVAL_ID       NUMBER NOT NULL,
    NOMBRE_NORMALIZADO  VARCHAR2(150 CHAR) NOT NULL,
    CONSTRAINT FK_ALIAS_CLUB_RIVAL FOREIGN KEY (CLUB_RIVAL_ID) REFERENCES CLUBES_RIVALES(ID),
    CONSTRAINT UQ_ALIAS_NOMBRE UNIQUE (NOMBRE_NORMALIZADO)
);

ALTER TABLE IF EXISTS PARTIDOS ADD COLUMN IF NOT EXISTS CLUB_RIVAL_ID NUMBER NULL;

ALTER TABLE IF EXISTS CLASIFICACIONES ADD COLUMN IF NOT EXISTS CODIGO_CLUB NUMBER NULL;
