-- Versión para H2 de sql/2026-11-12_ficha_partido.sql (ya aplicado en DEV y PRO). La tabla PARTIDOS no forma parte
-- del esquema compartido: cada test que la necesita crea la suya, así que FORMACION se añade solo si la tabla existe.
-- Sin claves ajenas (los tests no crean PARTIDOS ni JUGADORES completas en todos los casos).

ALTER TABLE IF EXISTS PARTIDOS ADD COLUMN IF NOT EXISTS FORMACION VARCHAR2(10 CHAR) NULL;

ALTER TABLE PARTIDO_LIVE_EVENTOS ADD COLUMN JUGADOR_ENTRA_ID NUMBER NULL;

ALTER TABLE PARTIDO_LIVE_EVENTOS ADD CONSTRAINT CK_LIVE_EVENTOS_ENTRA
    CHECK (JUGADOR_ENTRA_ID IS NULL OR TIPO = 'CAMBIO');

ALTER TABLE PARTIDO_LIVE_EVENTOS DROP CONSTRAINT CK_LIVE_EVENTOS_TIPO;

ALTER TABLE PARTIDO_LIVE_EVENTOS ADD CONSTRAINT CK_LIVE_EVENTOS_TIPO CHECK (TIPO IN
    ('INICIO', 'GOL_FAVOR', 'GOL_CONTRA', 'DESCANSO', 'SEGUNDA_PARTE', 'FINAL',
     'CAMBIO', 'TARJETA_AMARILLA', 'TARJETA_ROJA'));

CREATE TABLE PARTIDO_ALINEACION (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PARTIDO_ID  NUMBER NOT NULL,
    JUGADOR_ID  NUMBER NOT NULL,
    TITULAR     NUMBER(1) NOT NULL,
    ORDEN       NUMBER(3) NOT NULL,
    CONSTRAINT CK_ALINEACION_TITULAR CHECK (TITULAR IN (0, 1)),
    CONSTRAINT UQ_ALINEACION_JUGADOR UNIQUE (PARTIDO_ID, JUGADOR_ID)
);

CREATE INDEX IDX_ALINEACION_JUGADOR ON PARTIDO_ALINEACION (JUGADOR_ID);
