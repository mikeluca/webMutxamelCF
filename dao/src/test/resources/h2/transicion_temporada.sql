-- nuevas de JUGADOR_TEMPORADA van en plantillas_temporada.sql. EQUIPO_TEMPORADA y CUERPO_TECNICO_TEMPORADA se crean
-- aquí sin FK (cada test define sus tablas de referencia); CLASIFICACIONES, EQUIPOS_FFCV, HORARIOS_ENTRENAMIENTO y
-- CUOTAS_JUGADOR no forman parte del esquema compartido: cada test que las necesita crea la suya, así que los cambios
-- se aplican solo si la tabla existe (y vacía: TEMPORADA_ID se añade ya obligatorio).
CREATE TABLE EQUIPO_TEMPORADA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EQUIPO_ID NUMBER NOT NULL,
    TEMPORADA_ID NUMBER NOT NULL,
    ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
    MODALIDAD VARCHAR2(3) NULL,
    TIPO VARCHAR2(12) DEFAULT 'NORMAL' NOT NULL,
    CONSTRAINT CK_EQUIPO_TEMPORADA_ACTIVO CHECK (ACTIVO IN (0, 1)),
    CONSTRAINT CK_EQUIPO_TEMPORADA_MODALIDAD CHECK (MODALIDAD IN ('F11', 'F8', 'F5')),
    CONSTRAINT CK_EQUIPO_TEMPORADA_TIPO CHECK (TIPO IN ('NORMAL', 'PRETEMPORADA')),
    CONSTRAINT UQ_EQUIPO_TEMPORADA UNIQUE (EQUIPO_ID, TEMPORADA_ID)
);

CREATE TABLE CUERPO_TECNICO_TEMPORADA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUERPO_TECNICO_ID NUMBER NOT NULL,
    TEMPORADA_ID NUMBER NOT NULL,
    EQUIPO_ID NUMBER NOT NULL,
    PUESTO VARCHAR2(100 CHAR) NULL,
    CONSTRAINT UQ_CTT_FICHA_TEMPORADA_EQUIPO UNIQUE (CUERPO_TECNICO_ID, TEMPORADA_ID, EQUIPO_ID)
);

ALTER TABLE IF EXISTS CLASIFICACIONES ADD COLUMN IF NOT EXISTS TEMPORADA_ID NUMBER NOT NULL;
ALTER TABLE IF EXISTS EQUIPOS_FFCV ADD COLUMN IF NOT EXISTS TEMPORADA_ID NUMBER NOT NULL;
ALTER TABLE IF EXISTS HORARIOS_ENTRENAMIENTO ADD COLUMN IF NOT EXISTS TEMPORADA_ID NUMBER NOT NULL;

ALTER TABLE IF EXISTS EQUIPOS_FFCV DROP CONSTRAINT IF EXISTS UQ_EQUIPOS_FFCV;
ALTER TABLE IF EXISTS EQUIPOS_FFCV ADD CONSTRAINT UQ_EQUIPOS_FFCV UNIQUE (TEMPORADA_ID, COMPETICION, LETRA);

ALTER TABLE IF EXISTS CUOTAS_JUGADOR DROP CONSTRAINT IF EXISTS CK_CUOTA_ESTADO;
ALTER TABLE IF EXISTS CUOTAS_JUGADOR ADD CONSTRAINT CK_CUOTA_ESTADO
    CHECK (ESTADO IN ('PENDIENTE', 'PARCIAL', 'PAGADO', 'INCOBRABLE'));
