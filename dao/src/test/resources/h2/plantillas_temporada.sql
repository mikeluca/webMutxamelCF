-- cada test define las suyas.
CREATE TABLE CATEGORIAS_EDAD (
    CATEGORIA VARCHAR2(100) PRIMARY KEY,
    EDAD_MIN NUMBER(3) NOT NULL,
    EDAD_MAX NUMBER(3) NOT NULL,
    ORDEN NUMBER(3) NOT NULL
);

CREATE TABLE JUGADOR_TEMPORADA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    JUGADOR_ID NUMBER NOT NULL,
    TEMPORADA_ID NUMBER NOT NULL,
    EQUIPO_ID NUMBER,
    EQUIPO_NOMBRE VARCHAR2(100),
    CATEGORIA VARCHAR2(100),
    DORSAL NUMBER,
    PENDIENTE_REVISION NUMBER(1) DEFAULT 0 NOT NULL,
    NOTA VARCHAR2(500),
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    -- sql/2026-10-29_modelo_transicion_temporada.sql y sql/2026-10-30_jugador_temporada_sin_baja.sql (ESTADO es la baja; la FK a USUARIOS_APP no se crea: cada test define la suya)
    ESTADO VARCHAR2(12) DEFAULT 'CONFIRMADO' NOT NULL,
    CONTINUIDAD VARCHAR2(10) DEFAULT 'PENDIENTE' NOT NULL,
    FECHA_CONTINUIDAD TIMESTAMP,
    USUARIO_APP_CONTINUIDAD_ID NUMBER,
    EQUIPO_DEFINITIVO NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT CK_JT_ESTADO CHECK (ESTADO IN ('CONFIRMADO', 'PRUEBA', 'BAJA')),
    CONSTRAINT CK_JT_CONTINUIDAD CHECK (CONTINUIDAD IN ('PENDIENTE', 'SIGUE', 'NO_SIGUE', 'DUDA')),
    CONSTRAINT CK_JT_EQUIPO_DEFINITIVO CHECK (EQUIPO_DEFINITIVO IN (0, 1)),
    CONSTRAINT FK_JT_JUGADOR FOREIGN KEY (JUGADOR_ID) REFERENCES JUGADORES(ID),
    CONSTRAINT UQ_JT_JUGADOR_TEMPORADA UNIQUE (JUGADOR_ID, TEMPORADA_ID)
);
