import com.mikedev.mutxamelcf.model.Comunicacion;
import com.mikedev.mutxamelcf.model.ConvocatoriaGuardarRequest;
import com.mikedev.mutxamelcf.model.ConvocatoriaJugadorResponse;
import com.mikedev.mutxamelcf.model.ConvocatoriaResponse;
import com.mikedev.mutxamelcf.model.Partido;
import com.mikedev.mutxamelcf.model.OpcionesPushComunicacion;
import com.mikedev.mutxamelcf.service.ComunicacionService;

/**
 * Editar una convocatoria (PUT) no debe borrar las respuestas de los jugadores
 * que siguen convocados. Se prueba con los DAO reales sobre H2 en modo Oracle.
 */
class ConvocatoriaEditarConservaRespuestasH2Test {

    private static final Long ENTRENADOR = 1L;
    private static final Long EQUIPO = 10L;

    private ConvocatoriaJugadorDaoImpl convocatoriaJugadorDao;
    private ConvocatoriaServiceImpl service;
    private JdbcTemplate jdbc;
    private EquipoGestionDao equipoGestionDao;
    private ComunicacionService comunicacionService;
    private PartidoDao partidoDao;

    @BeforeEach
    void setUp() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(
                "jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=Oracle;DB_CLOSE_DELAY=-1", "sa", ""));

        jdbc.execute("""
                CREATE TABLE PARTIDOS (
                    ID NUMBER PRIMARY KEY, DIA DATE, RIVAL VARCHAR2(150), CAMPO VARCHAR2(150), HORA VARCHAR2(10))""");
        jdbc.execute("""
                CREATE TABLE CONVOCATORIAS (
                    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    EQUIPO_ID NUMBER NOT NULL,
                    PARTIDO_ID NUMBER NOT NULL,
                    HORA_CONVOCATORIA VARCHAR2(10),
                    LUGAR_CONVOCATORIA VARCHAR2(150),
                    USUARIO_ENTRENADOR_ID NUMBER,
                    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP)""");
        EsquemaH2.crear(jdbc);

        jdbc.update("INSERT INTO PARTIDOS VALUES (30, ?, 'Pego', 'Municipal', '11:00')",
                Date.valueOf(LocalDate.of(2026, 10, 24)));
        jdbc.update("INSERT INTO PARTIDOS VALUES (31, ?, 'Elx', 'Municipal', '12:00')",
                Date.valueOf(LocalDate.of(2026, 10, 25)));

        equipoGestionDao = mock(EquipoGestionDao.class);
        comunicacionService = mock(ComunicacionService.class);
        when(equipoGestionDao.existeEquipo(EQUIPO)).thenReturn(true);
        when(equipoGestionDao.puedeGestionarEquipo(ENTRENADOR, EQUIPO)).thenReturn(true);
        when(equipoGestionDao.obtenerJugadoresPorEquipo(EQUIPO)).thenReturn(List.of(100L, 101L, 102L));
        when(equipoGestionDao.obtenerNombreJugador(anyLong())).thenReturn("Jugador");
        when(equipoGestionDao.obtenerUsuariosPorJugador(anyLong())).thenReturn(List.of());
        when(equipoGestionDao.obtenerUsuariosFamiliaresPorJugador(anyLong())).thenReturn(List.of());

        partidoDao = mock(PartidoDao.class);
        when(partidoDao.obtenerPorId(30L)).thenReturn(partido(30L, LocalDate.of(2026, 10, 24), "Pego"));
        when(partidoDao.obtenerPorId(31L)).thenReturn(partido(31L, LocalDate.of(2026, 10, 25), "Elx"));

        convocatoriaJugadorDao = new ConvocatoriaJugadorDaoImpl(jdbc);

        service = new ConvocatoriaServiceImpl(
                new ConvocatoriaDaoImpl(jdbc),
                convocatoriaJugadorDao,
                equipoGestionDao,
                partidoDao,
                comunicacionService);
    }

    private static Partido partido(Long id, LocalDate dia, String rival) {
        Partido partido = new Partido();
        partido.setId(id);
        partido.setEquipoId(EQUIPO);
        partido.setRival(rival);
        partido.setDia(Date.valueOf(dia));
        partido.setHora("11:00");
        return partido;
    }

    private static ConvocatoriaGuardarRequest request(Long partidoId, String hora, List<Long> jugadores) {
        ConvocatoriaGuardarRequest request = new ConvocatoriaGuardarRequest();
        request.setPartidoId(partidoId);
        request.setHoraConvocatoria(hora);
        request.setLugarConvocatoria("Vestuarios");
        request.setJugadoresIds(jugadores);
        return request;
    }

    @Test
    void editarLaHoraOElLugarConservaLasRespuestas() {
        ConvocatoriaResponse creada = service.crear(ENTRENADOR, request(30L, "09:30", List.of(100L, 101L, 102L)));

        convocatoriaJugadorDao.guardarRespuesta(creada.getId(), 100L, "VA", null, LocalDateTime.now(), 7L);
        convocatoriaJugadorDao.guardarRespuesta(creada.getId(), 101L, "NO_PUEDE", "Enfermo", LocalDateTime.now(), 7L);

        // Se cambia la hora (mismo partido); la lista de jugadores del request no
        // se usa al editar (los convocados se mantienen).
        ConvocatoriaResponse editada = service.actualizar(
                ENTRENADOR, creada.getId(), request(30L, "10:00", List.of(100L)));

        assertThat(editada.getRival()).isEqualTo("Pego");
        assertThat(editada.getHoraConvocatoria()).isEqualTo("10:00");

        assertThat(editada.getJugadores())
                .extracting(ConvocatoriaJugadorResponse::getJugadorId,
                        ConvocatoriaJugadorResponse::getRespuesta,
                        ConvocatoriaJugadorResponse::getMotivo)
                .containsExactly(
                        org.assertj.core.groups.Tuple.tuple(100L, "VA", null),
                        org.assertj.core.groups.Tuple.tuple(101L, "NO_PUEDE", "Enfermo"),
                        org.assertj.core.groups.Tuple.tuple(102L, null, null));

        assertThat(editada.getResumen().va()).isEqualTo(1);
        assertThat(editada.getResumen().noPuede()).isEqualTo(1);
        assertThat(editada.getResumen().sinResponder()).isEqualTo(1);

        // Y siguen guardadas en la base de datos, no solo en la respuesta.
        assertThat(convocatoriaJugadorDao.obtenerPorConvocatoriaYJugador(creada.getId(), 101L).getMotivo())
                .isEqualTo("Enfermo");
    }

    @Test
    void cambiarElPartidoDejaATodosSinResponder() {
        ConvocatoriaResponse creada = service.crear(ENTRENADOR, request(30L, "09:30", List.of(100L, 101L, 102L)));

        convocatoriaJugadorDao.guardarRespuesta(creada.getId(), 100L, "VA", null, LocalDateTime.now(), 7L);
        convocatoriaJugadorDao.guardarRespuesta(creada.getId(), 101L, "NO_PUEDE", "Enfermo", LocalDateTime.now(), 7L);

        ConvocatoriaResponse editada = service.actualizar(
                ENTRENADOR, creada.getId(), request(31L, "10:00", List.of(100L)));

        assertThat(editada.getRival()).isEqualTo("Elx");
        assertThat(editada.getJugadores())
                .extracting(ConvocatoriaJugadorResponse::getJugadorId,
                        ConvocatoriaJugadorResponse::getRespuesta,
                        ConvocatoriaJugadorResponse::getMotivo,
                        ConvocatoriaJugadorResponse::getFechaRespuesta)
                .containsExactly(
                        org.assertj.core.groups.Tuple.tuple(100L, null, null, null),
                        org.assertj.core.groups.Tuple.tuple(101L, null, null, null),
                        org.assertj.core.groups.Tuple.tuple(102L, null, null, null));

        assertThat(editada.getResumen().sinResponder()).isEqualTo(3);

        // También en la base de datos (las cuatro columnas de la respuesta).
        assertThat(jdbc.queryForObject(
                "SELECT COUNT(*) FROM CONVOCATORIA_JUGADOR WHERE CONVOCATORIA_ID = ? AND (RESPUESTA IS NOT NULL"
                        + " OR MOTIVO IS NOT NULL OR FECHA_RESPUESTA IS NOT NULL OR USUARIO_APP_RESPUESTA_ID IS NOT NULL)",
                Integer.class, creada.getId())).isZero();
    }

    @Test
    void cambiarElPartidoNoTocaLasRespuestasDeOtraConvocatoria() {
        ConvocatoriaResponse uno = service.crear(ENTRENADOR, request(30L, "09:30", List.of(100L)));
        ConvocatoriaResponse otra = service.crear(ENTRENADOR, request(31L, "09:30", List.of(100L)));

        convocatoriaJugadorDao.guardarRespuesta(otra.getId(), 100L, "VA", null, LocalDateTime.now(), 7L);
        convocatoriaJugadorDao.guardarRespuesta(uno.getId(), 100L, "VA", null, LocalDateTime.now(), 7L);

        jdbc.update("INSERT INTO PARTIDOS VALUES (32, ?, 'Alcoy', 'Municipal', '12:00')",
                Date.valueOf(LocalDate.of(2026, 10, 26)));
        when(partidoDao.obtenerPorId(32L)).thenReturn(partido(32L, LocalDate.of(2026, 10, 26), "Alcoy"));

        service.actualizar(ENTRENADOR, uno.getId(), request(32L, "10:00", List.of(100L)));

        assertThat(convocatoriaJugadorDao.obtenerPorConvocatoriaYJugador(uno.getId(), 100L).getRespuesta()).isNull();
        assertThat(convocatoriaJugadorDao.obtenerPorConvocatoriaYJugador(otra.getId(), 100L).getRespuesta())
                .isEqualTo("VA");
    }

    @Test
    void elPushDeConvocatoriaLlevaElTipoYElId() {
        when(equipoGestionDao.obtenerUsuariosPorJugador(100L)).thenReturn(List.of(55L));

        ConvocatoriaResponse creada = service.crear(ENTRENADOR, request(30L, "09:30", List.of(100L)));

        ArgumentCaptor<OpcionesPushComunicacion> opciones = ArgumentCaptor.forClass(OpcionesPushComunicacion.class);
        verify(comunicacionService).crearPrivada(any(Comunicacion.class), eq(List.of(55L)), eq(ENTRENADOR),
                opciones.capture());

        assertThat(opciones.getValue().contenidoPush()).isNull();
        assertThat(opciones.getValue().datos())
                .containsEntry("tipo", "CONVOCATORIA")
                .containsEntry("convocatoriaId", String.valueOf(creada.getId()));
    }

    @Test
    void laVistaDelEntrenadorTraeElResumenYLaRespuestaDeCadaJugador() {
        ConvocatoriaResponse creada = service.crear(ENTRENADOR, request(30L, "09:30", List.of(100L, 101L)));

        convocatoriaJugadorDao.guardarRespuesta(creada.getId(), 100L, "NO_PUEDE", "Examen", LocalDateTime.now(), 7L);

        ConvocatoriaResponse vista = service.obtenerPorId(ENTRENADOR, creada.getId());

        assertThat(vista.getResumen().va()).isZero();
        assertThat(vista.getResumen().noPuede()).isEqualTo(1);
        assertThat(vista.getResumen().sinResponder()).isEqualTo(1);
        assertThat(vista.getJugadores().get(0).getFechaRespuesta()).isNotNull();
    }

}
