package com.mikedev.mutxamelcf.serviceimpl;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

import java.util.List;
import java.util.UUID;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import com.mikedev.mutxamelcf.dao.ConvocatoriaJugadorDao;
import com.mikedev.mutxamelcf.dao.EntrenamientoAsistenciaDao;
import com.mikedev.mutxamelcf.dao.EsquemaH2;
import com.mikedev.mutxamelcf.dao.UsuarioAppVinculoDao;
import com.mikedev.mutxamelcf.dao.impl.JugadorDaoImpl;
import com.mikedev.mutxamelcf.dao.impl.JustificacionFaltaEntrenamientoDaoImpl;
import com.mikedev.mutxamelcf.dao.impl.JustificacionFaltaPartidoDaoImpl;
import com.mikedev.mutxamelcf.dao.impl.PartidoEstadisticaJugadorDaoImpl;
import com.mikedev.mutxamelcf.dao.impl.PartidoLiveEventoDaoImpl;
import com.mikedev.mutxamelcf.service.CuotaJugadorService;
import com.mikedev.mutxamelcf.service.FamiliarJugadorService;

/**
 * Borrado de jugadores con los DAO de estadísticas, goles en directo y justificaciones reales sobre H2:
 * estadísticas y goles bloquean; las justificaciones se borran con el jugador.
 */
class JugadorServiceImplH2Test {

    private static final long JUGADOR = 10L;
    private static final long OTRO = 11L;

    private JdbcTemplate jdbc;
    private JugadorServiceImpl service;

    @BeforeEach
    void setUp() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(
                "jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=Oracle;DB_CLOSE_DELAY=-1", "sa", ""));
        EsquemaH2.crear(jdbc);

        // Estas dos tablas no están en EsquemaH2; JUGADORES es la mínima que usa JugadorDaoImpl.eliminar.
        jdbc.execute("CREATE TABLE JUGADORES (ID NUMBER PRIMARY KEY, NOMBRE VARCHAR2(50))");
        // JugadorDaoImpl.eliminar borra antes su fila de JUGADOR_TEMPORADA
        EsquemaH2.crearPlantillas(jdbc);
        jdbc.execute("""
                CREATE TABLE PARTIDO_ESTADISTICAS_JUGADOR (
                    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, PARTIDO_ID NUMBER NOT NULL,
                    JUGADOR_ID NUMBER NOT NULL, GOLES NUMBER DEFAULT 0, ASISTENCIAS NUMBER DEFAULT 0,
                    TARJETAS_AMARILLAS NUMBER DEFAULT 0, TARJETA_ROJA NUMBER(1) DEFAULT 0)""");
        jdbc.execute("""
                CREATE TABLE JUSTIFICACIONES_FALTA_ENTRENAMIENTO (
                    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, SESION_ID NUMBER NOT NULL,
                    JUGADOR_ID NUMBER NOT NULL, USUARIO_APP_ID NUMBER NOT NULL, MOTIVO VARCHAR2(500),
                    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL)""");

        jdbc.update("INSERT INTO JUGADORES (ID, NOMBRE) VALUES (?, 'Pablo')", JUGADOR);
        jdbc.update("INSERT INTO JUGADORES (ID, NOMBRE) VALUES (?, 'Luis')", OTRO);

        FamiliarJugadorService familiares = mock(FamiliarJugadorService.class);
        when(familiares.obtenerFamiliaresDeJugador(JUGADOR)).thenReturn(List.of());
        CuotaJugadorService cuotas = mock(CuotaJugadorService.class);
        when(cuotas.obtenerPorJugador(JUGADOR)).thenReturn(List.of());

        service = new JugadorServiceImpl(new JugadorDaoImpl(jdbc), familiares, mock(UsuarioAppVinculoDao.class),
                cuotas, mock(ConvocatoriaJugadorDao.class), mock(EntrenamientoAsistenciaDao.class),
                new PartidoEstadisticaJugadorDaoImpl(jdbc), new PartidoLiveEventoDaoImpl(jdbc),
                new JustificacionFaltaEntrenamientoDaoImpl(jdbc), new JustificacionFaltaPartidoDaoImpl(jdbc),
                mock(com.mikedev.mutxamelcf.dao.EquipoDao.class), mock(com.mikedev.mutxamelcf.dao.TemporadaDao.class),
                new com.mikedev.mutxamelcf.dao.impl.JugadorTemporadaDaoImpl(jdbc), java.time.Clock.systemDefaultZone());
    }

    private int jugadores(long id) {
        return jdbc.queryForObject("SELECT COUNT(*) FROM JUGADORES WHERE ID = ?", Integer.class, id);
    }

    private void estadistica(long jugador) {
        jdbc.update("INSERT INTO PARTIDO_ESTADISTICAS_JUGADOR (PARTIDO_ID, JUGADOR_ID, GOLES) VALUES (1, ?, 2)", jugador);
    }

    private void gol(long jugador, int anulado) {
        jdbc.update("""
                INSERT INTO PARTIDO_LIVE_EVENTOS (PARTIDO_ID, TIPO, JUGADOR_ID, USUARIO_APP_ID, FECHA, ANULADO)
                VALUES (1, 'GOL_FAVOR', ?, 7, CURRENT_TIMESTAMP, ?)""", jugador, anulado);
    }

    private void justificaciones(long jugador) {
        jdbc.update("INSERT INTO JUSTIFICACIONES_FALTA_ENTRENAMIENTO (SESION_ID, JUGADOR_ID, USUARIO_APP_ID, MOTIVO)"
                + " VALUES (1, ?, 7, 'Enfermo')", jugador);
        jdbc.update("INSERT INTO JUSTIFICACIONES_FALTA_ENTRENAMIENTO (SESION_ID, JUGADOR_ID, USUARIO_APP_ID, MOTIVO)"
                + " VALUES (2, ?, 7, 'Examen')", jugador);
        jdbc.update("INSERT INTO JUSTIFICACIONES_FALTA_PARTIDO (PARTIDO_ID, JUGADOR_ID, USUARIO_APP_ID, MOTIVO,"
                + " FECHA_CREACION) VALUES (1, ?, 7, 'Viaje', CURRENT_TIMESTAMP)", jugador);
    }

    private int totalJustificaciones(long jugador) {
        return jdbc.queryForObject("SELECT COUNT(*) FROM JUSTIFICACIONES_FALTA_ENTRENAMIENTO WHERE JUGADOR_ID = ?",
                Integer.class, jugador)
                + jdbc.queryForObject("SELECT COUNT(*) FROM JUSTIFICACIONES_FALTA_PARTIDO WHERE JUGADOR_ID = ?",
                        Integer.class, jugador);
    }

    @Test
    void conEstadisticasDePartidoSeBloquea() {
        estadistica(JUGADOR);

        assertThatThrownBy(() -> service.eliminarJugador(JUGADOR))
                .isInstanceOf(IllegalStateException.class)
                .hasMessageContaining("tiene estadísticas de partidos registradas");

        assertThat(jugadores(JUGADOR)).isEqualTo(1);
    }

    @Test
    void conGolesEnElDirectoSeBloquea() {
        gol(JUGADOR, 0);

        assertThatThrownBy(() -> service.eliminarJugador(JUGADOR))
                .isInstanceOf(IllegalStateException.class)
                .hasMessageContaining("tiene goles en retransmisiones");

        assertThat(jugadores(JUGADOR)).isEqualTo(1);
    }

    @Test
    void unGolAnuladoTambienBloquea() {
        gol(JUGADOR, 1);

        assertThatThrownBy(() -> service.eliminarJugador(JUGADOR))
                .isInstanceOf(IllegalStateException.class)
                .hasMessageContaining("tiene goles en retransmisiones");
    }

    @Test
    void siBloqueaOtroMotivoLasJustificacionesNoSeTocan() {
        estadistica(JUGADOR);
        justificaciones(JUGADOR);

        assertThatThrownBy(() -> service.eliminarJugador(JUGADOR)).isInstanceOf(IllegalStateException.class);

        assertThat(totalJustificaciones(JUGADOR)).isEqualTo(3);
    }

    @Test
    void soloConJustificacionesSeBorraElJugadorYSusJustificaciones() {
        justificaciones(JUGADOR);
        justificaciones(OTRO);

        service.eliminarJugador(JUGADOR);

        assertThat(jugadores(JUGADOR)).isZero();
        assertThat(totalJustificaciones(JUGADOR)).isZero();
        // Las de otro jugador siguen ahí.
        assertThat(jugadores(OTRO)).isEqualTo(1);
        assertThat(totalJustificaciones(OTRO)).isEqualTo(3);
    }

    @Test
    void conSuFilaDeTemporadaSeBorraJuntoAlJugador() {
        // Un alta por error ya tiene su fila de la temporada activa (FK a JUGADORES): se va con el jugador.
        jdbc.update("INSERT INTO JUGADOR_TEMPORADA (JUGADOR_ID, TEMPORADA_ID, DORSAL) VALUES (?, 1, 7)", JUGADOR);
        jdbc.update("INSERT INTO JUGADOR_TEMPORADA (JUGADOR_ID, TEMPORADA_ID, DORSAL) VALUES (?, 1, 8)", OTRO);

        service.eliminarJugador(JUGADOR);

        assertThat(jugadores(JUGADOR)).isZero();
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM JUGADOR_TEMPORADA", Integer.class)).isEqualTo(1);
    }

    @Test
    void sinNadaSeBorra() {
        service.eliminarJugador(JUGADOR);

        assertThat(jugadores(JUGADOR)).isZero();
        assertThat(jugadores(OTRO)).isEqualTo(1);
    }

    @Test
    void siElDeleteViolaUnaConstraintDevuelveUnMensajeClaro() {
        // Una tabla no comprobada por el servicio con FK al jugador: ORA-02292 en el DELETE.
        jdbc.execute("CREATE TABLE HISTORIAL (ID NUMBER PRIMARY KEY, JUGADOR_ID NUMBER,"
                + " CONSTRAINT FK_HISTORIAL_JUGADOR FOREIGN KEY (JUGADOR_ID) REFERENCES JUGADORES(ID))");
        jdbc.update("INSERT INTO HISTORIAL (ID, JUGADOR_ID) VALUES (1, ?)", JUGADOR);

        assertThatThrownBy(() -> service.eliminarJugador(JUGADOR))
                .isInstanceOf(IllegalStateException.class)
                .hasMessage("No se puede eliminar el jugador porque tiene datos relacionados en el club (historial). "
                        + "Revisa sus relaciones.");
    }
}
