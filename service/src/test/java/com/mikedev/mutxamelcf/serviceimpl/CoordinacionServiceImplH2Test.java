    @Test
    void elFinDeSemanaDeReferenciaPorCadaDiaDeLaSemana() {
        // Semana del 19 al 25 de octubre de 2026 (lunes a domingo).
        LocalDate proximo = LocalDate.of(2026, 10, 23);
        LocalDate siguiente = LocalDate.of(2026, 10, 30);

        for (int dia = 19; dia <= 22; dia++) {
            assertThat(CoordinacionServiceImpl.viernesDeReferencia(LocalDate.of(2026, 10, dia)))
                    .as("lunes a jueves: el próximo viernes (%d)", dia).isEqualTo(proximo);
        }

        for (int dia = 23; dia <= 25; dia++) {
            assertThat(CoordinacionServiceImpl.viernesDeReferencia(LocalDate.of(2026, 10, dia)))
                    .as("viernes a domingo: el actual (%d)", dia).isEqualTo(proximo);
        }

        // El lunes siguiente ya mira al fin de semana posterior.
        assertThat(CoordinacionServiceImpl.viernesDeReferencia(LocalDate.of(2026, 10, 26))).isEqualTo(siguiente);
    }

    @Test
    void laFechaDeLaPeticionManda_ySinFechaSeUsaHoy() {
        assertThat(service.obtenerFinDeSemana(COORDINADOR, null).desde()).isEqualTo(VIERNES);
        assertThat(service.obtenerFinDeSemana(COORDINADOR, null).hasta()).isEqualTo(VIERNES.plusDays(2));

        FinDeSemanaResponse otro = service.obtenerFinDeSemana(COORDINADOR, LocalDate.of(2026, 10, 31));

        assertThat(otro.desde()).isEqualTo(LocalDate.of(2026, 10, 30));
        assertThat(otro.hasta()).isEqualTo(LocalDate.of(2026, 11, 1));
    }

