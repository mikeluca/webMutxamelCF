    @Test
    void elSeguimientoAplicaLosUmbralesYOrdenaPorIncidencias() {
        jugador(1, "Pablo", "Cadete A");   // 3 faltas -> FALTAS
        jugador(2, "Luis", "Cadete A");    // 2 mal comportamiento -> COMPORTAMIENTO
        jugador(3, "Ana", "Infantil A");   // 4 faltas + 2 mal -> AMBOS
        jugador(4, "Eva", "Cadete A");     // 2 faltas, 1 mal: no llega
        jugador(5, "Raul", "Cadete A");    // solo justificadas y retrasos: no llega

        LocalDate d = HOY.minusDays(2);

        entrenamiento(d, 1, "FALTA", 2, "MAL_COMPORTAMIENTO", 3, "FALTA", 4, "FALTA", 5, "FALTA_JUSTIFICADA");
        entrenamiento(d.minusDays(2), 1, "FALTA", 2, "MAL_COMPORTAMIENTO", 3, "FALTA", 4, "FALTA", 5, "FALTA_JUSTIFICADA");
        entrenamiento(d.minusDays(4), 1, "FALTA", 3, "FALTA", 3, "MAL_COMPORTAMIENTO", 4, "MAL_COMPORTAMIENTO",
                5, "FALTA_JUSTIFICADA");
        entrenamiento(d.minusDays(6), 3, "FALTA", 3, "MAL_COMPORTAMIENTO", 1, "RETRASO", 5, "FALTA_JUSTIFICADA");
        entrenamiento(d.minusDays(8), 5, "FALTA_JUSTIFICADA", 5, "RETRASO");

        SeguimientoJugadoresResponse r = service.obtenerSeguimientoJugadores(COORDINADOR, null);

        assertThat(r.periodo()).isEqualTo("30d");
        assertThat(r.dias()).isEqualTo(30);
        assertThat(r.jugadores()).extracting(SeguimientoJugadoresResponse.Jugador::nombre,
                SeguimientoJugadoresResponse.Jugador::motivo)
                .containsExactly(
                        org.assertj.core.groups.Tuple.tuple("Ana Lopez", "AMBOS"),
                        org.assertj.core.groups.Tuple.tuple("Pablo Lopez", "FALTAS"),
                        org.assertj.core.groups.Tuple.tuple("Luis Lopez", "COMPORTAMIENTO"));

        SeguimientoJugadoresResponse.Jugador ana = r.jugadores().get(0);

        assertThat(ana.faltas()).isEqualTo(4);
        assertThat(ana.malComportamiento()).isEqualTo(2);
        assertThat(ana.equipo()).isEqualTo("Infantil A");
        assertThat(ana.ultimaIncidencia()).isEqualTo(d);

        SeguimientoJugadoresResponse.Jugador pablo = r.jugadores().get(1);

        assertThat(pablo.retrasos()).isEqualTo(1);
    }

    @Test
    void lasFaltasJustificadasNoCuentanComoFaltas() {
        jugador(1, "Pablo", "Cadete A");

        for (int i = 1; i <= 5; i++) {
            entrenamiento(HOY.minusDays(i), 1, "FALTA_JUSTIFICADA");
        }

        entrenamiento(HOY.minusDays(7), 1, "FALTA");
        entrenamiento(HOY.minusDays(8), 1, "FALTA");

        // 2 faltas + 5 justificadas: por debajo del umbral de 3.
        assertThat(service.obtenerSeguimientoJugadores(COORDINADOR, "30d").jugadores()).isEmpty();

        entrenamiento(HOY.minusDays(9), 1, "FALTA");

        SeguimientoJugadoresResponse.Jugador jugador =
                service.obtenerSeguimientoJugadores(COORDINADOR, "30d").jugadores().get(0);

        assertThat(jugador.faltas()).isEqualTo(3);
        assertThat(jugador.faltasJustificadas()).isEqualTo(5);
    }

    @Test
    void elPeriodoDeDiasYElDeTemporadaAcotanLasFechas() {
        jugador(1, "Pablo", "Cadete A");

        // 2 faltas recientes y 1 de hace 40 días (dentro de la temporada, fuera de los 30 días).
        entrenamiento(HOY.minusDays(1), 1, "FALTA");
        entrenamiento(HOY.minusDays(5), 1, "FALTA");
        entrenamiento(HOY.minusDays(40), 1, "FALTA");
        // De la temporada anterior: no cuenta en ninguno.
        entrenamiento(LocalDate.of(2026, 5, 1), 1, "FALTA");

        assertThat(service.obtenerSeguimientoJugadores(COORDINADOR, "30d").jugadores()).isEmpty();

        SeguimientoJugadoresResponse temporada = service.obtenerSeguimientoJugadores(COORDINADOR, "temporada");

        assertThat(temporada.periodo()).isEqualTo("temporada");
        assertThat(temporada.desde()).isEqualTo(LocalDate.of(2026, 9, 1));
        assertThat(temporada.jugadores()).hasSize(1);
        assertThat(temporada.jugadores().get(0).faltas()).isEqualTo(3);
    }

