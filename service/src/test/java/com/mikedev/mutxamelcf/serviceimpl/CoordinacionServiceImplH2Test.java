    @Test
    void elDetalleListaLasIncidenciasDelJugadorEnElPeriodo() {
        jugador(1, "Pablo", "Cadete A");

        entrenamiento(HOY.minusDays(2), 1, "FALTA");
        entrenamiento(HOY.minusDays(4), 1, "PRESENTE");
        entrenamiento(HOY.minusDays(6), 1, "FALTA_JUSTIFICADA");
        entrenamiento(HOY.minusDays(8), 1, "RETRASO");
        entrenamiento(HOY.minusDays(60), 1, "FALTA");

        SeguimientoJugadoresResponse.Detalle detalle = service.obtenerDetalleSeguimiento(COORDINADOR, 1L, "30d");

        assertThat(detalle.jugador().nombre()).isEqualTo("Pablo Lopez");
        assertThat(detalle.incidencias()).extracting(
                SeguimientoJugadoresResponse.Incidencia::fecha, SeguimientoJugadoresResponse.Incidencia::estado)
                .containsExactly(
                        org.assertj.core.groups.Tuple.tuple(HOY.minusDays(2), "FALTA"),
                        org.assertj.core.groups.Tuple.tuple(HOY.minusDays(6), "FALTA_JUSTIFICADA"),
                        org.assertj.core.groups.Tuple.tuple(HOY.minusDays(8), "RETRASO"));

        // Un jugador sin entrenamientos en el periodo existe con todo a cero; uno inexistente es un error.
        jugador(2, "Eva", "Cadete A");

        assertThat(service.obtenerDetalleSeguimiento(COORDINADOR, 2L, null).incidencias()).isEmpty();
        assertThatThrownBy(() -> service.obtenerDetalleSeguimiento(COORDINADOR, 99L, null))
                .isInstanceOf(IllegalArgumentException.class);
    }

