    @Test
    void elResultadoPendienteUsaElMismoCriterioQueElRecordatorio() {
        // Mismo helper: mismas decisiones para resultado y para "terminado".
        assertThat(RecordatorioResultadoPartidoScheduler.HORAS_HASTA_EL_AVISO)
                .isEqualTo(CriterioResultadoPartido.HORAS_HASTA_EL_FINAL);

        assertThat(CriterioResultadoPartido.tieneResultado(null, null)).isFalse();
        assertThat(CriterioResultadoPartido.tieneResultado(null, " - ")).isFalse();
        assertThat(CriterioResultadoPartido.tieneResultado(null, "-")).isFalse();
        assertThat(CriterioResultadoPartido.tieneResultado(null, "2-1")).isTrue();
        assertThat(CriterioResultadoPartido.tieneResultado(0, null)).isTrue();

        LocalDateTime ahora = LocalDateTime.of(2026, 10, 21, 12, 0);

        assertThat(CriterioResultadoPartido.haTerminado(HOY, "10:00", ahora)).isTrue();   // justo 2 h
        assertThat(CriterioResultadoPartido.haTerminado(HOY, "10:01", ahora)).isFalse();
        // Sin hora legible, medianoche (igual que la consulta del DAO).
        assertThat(CriterioResultadoPartido.haTerminado(HOY, "tarde", ahora)).isTrue();
        assertThat(CriterioResultadoPartido.haTerminado(HOY, " 9:30 ", ahora)).isTrue();
    }

