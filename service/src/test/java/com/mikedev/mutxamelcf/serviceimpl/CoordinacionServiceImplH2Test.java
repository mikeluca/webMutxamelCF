    // ---- datos ----------------------------------------------------------------------------

    private void equipo(long id, String nombre, String orden) {
        jdbc.update("INSERT INTO EQUIPO (ID, NOMBRE, ORDEN) VALUES (?, ?, ?)", id, nombre, orden);
    }

    private long partido(long equipo, LocalDate dia, String hora, boolean cancelado, Integer goles, String resultado) {
        long id = siguienteId++;
        jdbc.update("INSERT INTO PARTIDOS (ID, EQUIPO_ID, RIVAL, DIA, HORA, CANCELADO, GOLES_FAVOR, RESULTADO)"
                + " VALUES (?, ?, 'Rival', ?, ?, ?, ?, ?)",
                id, equipo, Date.valueOf(dia), hora, cancelado ? 1 : 0, goles, resultado);
        return id;
    }

    private void convocar(long partido) {
        jdbc.update("INSERT INTO CONVOCATORIAS VALUES (?, ?)", siguienteId++, partido);
    }

    private void descanso(long equipo, LocalDate fecha, Integer jornada) {
        jdbc.update("INSERT INTO DESCANSOS_EQUIPO (EQUIPO_ID, FECHA, JORNADA) VALUES (?, ?, ?)",
                equipo, Date.valueOf(fecha), jornada);
    }

    private void relacionFfcv(long equipo) {
        jdbc.update("INSERT INTO EQUIPOS_FFCV (EQUIPO_ID, COMPETICION, LETRA) VALUES (?, ?, 'A')",
                equipo, "Competicion " + equipo);
    }

    private void jugador(long id, String nombre, String equipo) {
        // El enlace con el equipo es EQUIPO_ID; la columna EQUIPO es solo una copia
        jdbc.update("INSERT INTO JUGADORES (ID, NOMBRE, APELLIDOS, DORSAL, EQUIPO, EQUIPO_ID)"
                + " VALUES (?, ?, 'Lopez', 5, ?, (SELECT ID FROM EQUIPO WHERE NOMBRE = ?))", id, nombre, equipo, equipo);
    }

    private void entrenamiento(LocalDate fecha, Object... jugadorYEstado) {
        long id = siguienteId++;
        jdbc.update("INSERT INTO ENTRENAMIENTOS (ID, EQUIPO_ID, FECHA, USUARIO_ENTRENADOR_ID) VALUES (?, 2, ?, 1)",
                id, Date.valueOf(fecha));

        for (int i = 0; i < jugadorYEstado.length; i += 2) {
            jdbc.update("INSERT INTO ENTRENAMIENTO_ASISTENCIA VALUES (?, ?, ?)",
                    id, jugadorYEstado[i], jugadorYEstado[i + 1]);
        }
    }

