    @Test
    void losCuatroBloquesConDatosMezclados() {
        for (long equipo = 1; equipo <= 5; equipo++) {
            relacionFfcv(equipo);
        }

        // Sin convocatoria: el equipo 2 (sábado) y el 1 (domingo); el 3 ya tiene convocatoria; el cancelado no cuenta.
        partido(2, VIERNES.plusDays(1), "11:00", false, null, null);
        partido(1, VIERNES.plusDays(2), "12:00", false, null, null);
        convocar(partido(3, VIERNES.plusDays(1), "10:00", false, null, null));
        partido(5, VIERNES.plusDays(1), "10:00", true, null, null);

        // Descansa el equipo 4. El 5 tiene un partido cancelado: ni sin partido ni sin importar.
        descanso(4, VIERNES.plusDays(1), 8);
        descanso(4, VIERNES.plusDays(8), 9); // otro fin de semana: no cuenta

        // Resultados pendientes (hoy es miércoles 21 a las 12:00).
        partido(1, HOY.minusDays(3), "11:00", false, null, null);        // pendiente, 3 días
        partido(2, HOY.minusDays(1), "10:00", false, null, " - ");       // pendiente (resultado vacío), 1 día
        partido(3, HOY, "09:00", false, null, null);                     // hoy a las 9: ya terminó (11:00 <= 12:00)
        partido(3, HOY, "11:00", false, null, null);                     // hoy a las 11: aún no (13:00 > 12:00)
        partido(4, HOY.minusDays(2), "10:00", false, 2, null);           // con goles
        partido(4, HOY.minusDays(2), "12:00", false, null, "1-1");       // con resultado en texto
        partido(5, HOY.minusDays(2), "10:00", true, null, null);         // cancelado
        partido(1, HOY.minusDays(11), "10:00", false, null, null);       // más de 10 días

        FinDeSemanaResponse r = service.obtenerFinDeSemana(COORDINADOR, null);

        assertThat(r.sinConvocatoria()).extracting(FinDeSemanaResponse.PartidoSinConvocatoria::equipo)
                .containsExactly("Primer Equipo", "Cadete A");
        assertThat(r.sinConvocatoria().get(1).hora()).isEqualTo("11:00");
        assertThat(r.sinConvocatoria().get(1).local()).isTrue();

        assertThat(r.resultadosPendientes()).extracting(
                FinDeSemanaResponse.ResultadoPendiente::equipo, FinDeSemanaResponse.ResultadoPendiente::diasDeRetraso)
                .containsExactly(
                        org.assertj.core.groups.Tuple.tuple("Primer Equipo", 3),
                        org.assertj.core.groups.Tuple.tuple("Cadete A", 1),
                        org.assertj.core.groups.Tuple.tuple("Infantil A", 0));

        assertThat(r.descansan()).extracting(FinDeSemanaResponse.Descanso::equipo, FinDeSemanaResponse.Descanso::jornada)
                .containsExactly(org.assertj.core.groups.Tuple.tuple("Alevín A", 8));

        // Los 5 equipos tienen partido (aunque sea cancelado) o descanso: nadie sin importar.
        assertThat(r.sinPartido()).isEmpty();

        assertThat(r.resumen().sinConvocatoria()).isEqualTo(2);
        assertThat(r.resumen().resultadosPendientes()).isEqualTo(3);
        assertThat(r.resumen().descansan()).isEqualTo(1);
        assertThat(r.resumen().sinPartido()).isZero();
        assertThat(r.resumen().ultimaImportacionFfcv()).isNull();
    }

    @Test
    void losEquiposConRelacionSinPartidoNiDescansoVanAPosibleImportacionPendiente() {
        relacionFfcv(1);
        relacionFfcv(2);
        relacionFfcv(3); // sin partido ni descanso
        // El equipo 4 no tiene relación FFCV: no se reclama.

        partido(1, VIERNES.plusDays(1), "11:00", false, null, null);
        descanso(2, VIERNES.plusDays(1), 3);

        FinDeSemanaResponse r = service.obtenerFinDeSemana(COORDINADOR, null);

        assertThat(r.sinPartido()).extracting(FinDeSemanaResponse.SinPartido::equipo).containsExactly("Infantil A");
        assertThat(r.resumen().sinPartido()).isEqualTo(1);
    }

    @Test
    void laUltimaImportacionEsLaMasRecienteDeUnPartidoFfcv() {
        long ffcv = partido(1, VIERNES, "10:00", false, null, null);
        long otro = partido(1, VIERNES, "12:00", false, null, null);
        long manual = partido(1, VIERNES, "14:00", false, null, null);

        jdbc.update("UPDATE PARTIDOS SET ORIGEN = 'FFCV', FECHA_IMPORTACION = ? WHERE ID = ?",
                java.sql.Timestamp.valueOf(LocalDateTime.of(2026, 10, 14, 9, 0)), ffcv);
        jdbc.update("UPDATE PARTIDOS SET ORIGEN = 'FFCV', FECHA_IMPORTACION = ? WHERE ID = ?",
                java.sql.Timestamp.valueOf(LocalDateTime.of(2026, 10, 21, 8, 30)), otro);
        // Un partido manual con una fecha más reciente no cuenta como importación.
        jdbc.update("UPDATE PARTIDOS SET ORIGEN = 'MANUAL', FECHA_IMPORTACION = ? WHERE ID = ?",
                java.sql.Timestamp.valueOf(LocalDateTime.of(2026, 10, 22, 8, 30)), manual);

        assertThat(service.obtenerFinDeSemana(COORDINADOR, null).resumen().ultimaImportacionFfcv())
                .isEqualTo(LocalDateTime.of(2026, 10, 21, 8, 30));
    }

    @Test
    void editarAManoUnPartidoFfcvNoCambiaLaUltimaImportacion() {
        long antiguo = partido(1, VIERNES, "10:00", false, null, null);

        jdbc.update("UPDATE PARTIDOS SET ORIGEN = 'FFCV', FECHA_IMPORTACION = ?, FECHA_ACTUALIZACION = ? WHERE ID = ?",
                java.sql.Timestamp.valueOf(LocalDateTime.of(2026, 10, 14, 9, 0)),
                java.sql.Timestamp.valueOf(LocalDateTime.of(2026, 10, 21, 11, 0)), antiguo);

        // FECHA_ACTUALIZACION (edición manual) más reciente: la importación sigue siendo la del 14.
        assertThat(service.obtenerFinDeSemana(COORDINADOR, null).resumen().ultimaImportacionFfcv())
                .isEqualTo(LocalDateTime.of(2026, 10, 14, 9, 0));
    }

