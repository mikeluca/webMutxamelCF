import com.mikedev.mutxamelcf.model.Partido;
import com.mikedev.mutxamelcf.service.ComunicacionService;

/**
 * Crear y editar una convocatoria con los DAO reales sobre H2 en modo Oracle
 * (esquema de {@link EsquemaH2}): las ausencias justificadas no se pueden
 * convocar, el PUT añade y quita jugadores conservando los demás.
 */
class ConvocatoriaEditarH2Test {

    private static final Long ENTRENADOR = 1L;
    private static final Long EQUIPO = 10L;

    private ConvocatoriaJugadorDaoImpl convocatoriaJugadorDao;
    private JustificacionFaltaPartidoDaoImpl justificacionDao;
    private ConvocatoriaServiceImpl service;
    private JdbcTemplate jdbc;
    private EquipoGestionDao equipoGestionDao;
    private ComunicacionService comunicacionService;
    private PartidoDao partidoDao;

    @BeforeEach
    void setUp() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(
                "jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=Oracle;DB_CLOSE_DELAY=-1", "sa", ""));

        jdbc.execute("""
                CREATE TABLE PARTIDOS (
                    ID NUMBER PRIMARY KEY, DIA DATE, RIVAL VARCHAR2(150), CAMPO VARCHAR2(150), HORA VARCHAR2(10))""");
        jdbc.execute("""
                CREATE TABLE CONVOCATORIAS (
                    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    EQUIPO_ID NUMBER NOT NULL,
                    PARTIDO_ID NUMBER NOT NULL,
                    HORA_CONVOCATORIA VARCHAR2(10),
                    LUGAR_CONVOCATORIA VARCHAR2(150),
                    USUARIO_ENTRENADOR_ID NUMBER,
                    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP)""");
        EsquemaH2.crear(jdbc);

        jdbc.update("INSERT INTO PARTIDOS VALUES (30, ?, 'Pego', 'Municipal', '11:00')",
                Date.valueOf(LocalDate.of(2026, 10, 24)));
        jdbc.update("INSERT INTO PARTIDOS VALUES (31, ?, 'Elx', 'Municipal', '12:00')",
                Date.valueOf(LocalDate.of(2026, 10, 25)));

        equipoGestionDao = mock(EquipoGestionDao.class);
        comunicacionService = mock(ComunicacionService.class);
        when(equipoGestionDao.existeEquipo(EQUIPO)).thenReturn(true);
        when(equipoGestionDao.puedeGestionarEquipo(ENTRENADOR, EQUIPO)).thenReturn(true);
        when(equipoGestionDao.obtenerJugadoresPorEquipo(EQUIPO)).thenReturn(List.of(100L, 101L, 102L, 103L));
        when(equipoGestionDao.obtenerNombreJugador(anyLong())).thenAnswer(i -> "Jugador " + i.getArgument(0));
        when(equipoGestionDao.obtenerUsuariosPorJugador(anyLong())).thenReturn(List.of());
        when(equipoGestionDao.obtenerUsuariosFamiliaresPorJugador(anyLong())).thenReturn(List.of());

        partidoDao = mock(PartidoDao.class);
        when(partidoDao.obtenerPorId(30L)).thenReturn(partido(30L, LocalDate.of(2026, 10, 24), "Pego"));
        when(partidoDao.obtenerPorId(31L)).thenReturn(partido(31L, LocalDate.of(2026, 10, 25), "Elx"));

        convocatoriaJugadorDao = new ConvocatoriaJugadorDaoImpl(jdbc);
        justificacionDao = new JustificacionFaltaPartidoDaoImpl(jdbc);

        service = new ConvocatoriaServiceImpl(
                new ConvocatoriaDaoImpl(jdbc),
                convocatoriaJugadorDao,
                equipoGestionDao,
                partidoDao,
                comunicacionService,
                justificacionDao);
    }

    private static Partido partido(Long id, LocalDate dia, String rival) {
        Partido partido = new Partido();
        partido.setId(id);
        partido.setEquipoId(EQUIPO);
        partido.setRival(rival);
        partido.setDia(Date.valueOf(dia));
        partido.setHora("11:00");
        return partido;
    }

    private static ConvocatoriaGuardarRequest request(Long partidoId, String hora, List<Long> jugadores) {
        ConvocatoriaGuardarRequest request = new ConvocatoriaGuardarRequest();
        request.setPartidoId(partidoId);
        request.setHoraConvocatoria(hora);
        request.setLugarConvocatoria("Vestuarios");
        request.setJugadoresIds(jugadores);
        return request;
    }

    private void justificar(long partidoId, long jugadorId, String motivo) {
        JustificacionFaltaPartido j = new JustificacionFaltaPartido();
        j.setPartidoId(partidoId);
        j.setJugadorId(jugadorId);
        j.setUsuarioAppId(7L);
        j.setMotivo(motivo);
        j.setFechaCreacion(LocalDateTime.of(2026, 10, 21, 10, 0));
        justificacionDao.crear(j);
    }

    private List<Long> convocados(Long convocatoriaId) {
        return convocatoriaJugadorDao.obtenerPorConvocatoria(convocatoriaId).stream()
                .map(ConvocatoriaJugador::getJugadorId).toList();
    }

    // ---- crear -------------------------------------------------------------------------

    @Test
    void crearRechazaAUnJugadorConAusenciaJustificadaConSuNombre() {
        justificar(30, 101, "Examen");

        assertThatThrownBy(() -> service.crear(ENTRENADOR, request(30L, "09:30", List.of(100L, 101L))))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("Jugador 101")
                .hasMessageContaining("ausencia");

        // No se ha creado nada.
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM CONVOCATORIAS", Integer.class)).isZero();
    }

    @Test
    void laAusenciaDeOtroPartidoNoImpideConvocar() {
        justificar(31, 101, "Examen");

        ConvocatoriaResponse creada = service.crear(ENTRENADOR, request(30L, "09:30", List.of(100L, 101L)));

        assertThat(convocados(creada.getId())).containsExactly(100L, 101L);
    }

    @Test
    void crearBloqueaElPartidoParaSerializarConLasJustificaciones() {
        service.crear(ENTRENADOR, request(30L, "09:30", List.of(100L)));

        verify(partidoDao).bloquearPorId(30L);
    }

    // ---- editar ------------------------------------------------------------------------

    @Test
    void elPutAnadeYQuitaJugadoresConservandoLosDemas() {
        ConvocatoriaResponse creada = service.crear(ENTRENADOR, request(30L, "09:30", List.of(100L, 101L, 102L)));

        Long idDe101 = convocatoriaJugadorDao.obtenerPorConvocatoriaYJugador(creada.getId(), 101L).getId();

        // Sale el 100; el 101 y el 102 se quedan; entra el 103.
        ConvocatoriaResponse editada = service.actualizar(
                ENTRENADOR, creada.getId(), request(30L, "10:00", List.of(101L, 102L, 103L)));

        assertThat(convocados(creada.getId())).containsExactly(101L, 102L, 103L);
        assertThat(editada.getJugadores()).extracting(ConvocatoriaJugadorResponse::getJugadorId)
                .containsExactly(101L, 102L, 103L);
        assertThat(editada.getHoraConvocatoria()).isEqualTo("10:00");

        // Los que se quedan conservan su fila (no se borra y se vuelve a insertar).
        assertThat(convocatoriaJugadorDao.obtenerPorConvocatoriaYJugador(creada.getId(), 101L).getId())
                .isEqualTo(idDe101);
    }

    @Test
    void elPutSinListaDeJugadoresNoTocaALosConvocados() {
        ConvocatoriaResponse creada = service.crear(ENTRENADOR, request(30L, "09:30", List.of(100L, 101L)));

        service.actualizar(ENTRENADOR, creada.getId(), request(30L, "10:00", null));

        assertThat(convocados(creada.getId())).containsExactly(100L, 101L);
    }

    @Test
    void elPutNoPermiteVaciarLaConvocatoria() {
        ConvocatoriaResponse creada = service.crear(ENTRENADOR, request(30L, "09:30", List.of(100L)));

        assertThatThrownBy(() -> service.actualizar(
                ENTRENADOR, creada.getId(), request(30L, "10:00", List.of())))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("al menos un jugador");

        assertThat(convocados(creada.getId())).containsExactly(100L);
    }

    @Test
    void elPutRechazaAnadirAUnJugadorConAusenciaJustificada() {
        ConvocatoriaResponse creada = service.crear(ENTRENADOR, request(30L, "09:30", List.of(100L)));
        justificar(30, 103, "Viaje");

        assertThatThrownBy(() -> service.actualizar(
                ENTRENADOR, creada.getId(), request(30L, "09:30", List.of(100L, 103L))))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("Jugador 103");

        assertThat(convocados(creada.getId())).containsExactly(100L);
    }

    @Test
    void elPutPermiteMantenerAUnoQueYaEstabaAunqueHayaJustificado() {
        ConvocatoriaResponse creada = service.crear(ENTRENADOR, request(30L, "09:30", List.of(100L, 101L)));
        justificar(30, 101, "Examen");

        ConvocatoriaResponse editada = service.actualizar(
                ENTRENADOR, creada.getId(), request(30L, "09:45", List.of(100L, 101L, 102L)));

        assertThat(convocados(creada.getId())).containsExactly(100L, 101L, 102L);
        assertThat(editada.getJugadores())
                .extracting(ConvocatoriaJugadorResponse::getJugadorId,
                        ConvocatoriaJugadorResponse::isAusenciaJustificada,
                        ConvocatoriaJugadorResponse::getMotivoAusencia)
                .containsExactly(
                        org.assertj.core.groups.Tuple.tuple(100L, false, null),
                        org.assertj.core.groups.Tuple.tuple(101L, true, "Examen"),
                        org.assertj.core.groups.Tuple.tuple(102L, false, null));
    }

    @Test
    void elPutRechazaJugadoresQueNoSonDelEquipo() {
        ConvocatoriaResponse creada = service.crear(ENTRENADOR, request(30L, "09:30", List.of(100L)));

        assertThatThrownBy(() -> service.actualizar(
                ENTRENADOR, creada.getId(), request(30L, "09:30", List.of(100L, 999L))))
                .isInstanceOf(SecurityException.class);
        assertThatThrownBy(() -> service.actualizar(
                ENTRENADOR, creada.getId(), request(30L, "09:30", List.of(100L, 100L))))
                .isInstanceOf(IllegalArgumentException.class);

        assertThat(convocados(creada.getId())).containsExactly(100L);
    }

    @Test
    void alCambiarDePartidoSeCompruebanLasAusenciasDelPartidoNuevo() {
        ConvocatoriaResponse creada = service.crear(ENTRENADOR, request(30L, "09:30", List.of(100L)));
        justificar(31, 102, "Viaje");

        assertThatThrownBy(() -> service.actualizar(
                ENTRENADOR, creada.getId(), request(31L, "09:30", List.of(100L, 102L))))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("Jugador 102");

        ConvocatoriaResponse editada = service.actualizar(
                ENTRENADOR, creada.getId(), request(31L, "09:30", List.of(100L, 101L)));

        assertThat(editada.getRival()).isEqualTo("Elx");
        assertThat(convocados(creada.getId())).containsExactly(100L, 101L);
    }

    // ---- detalle y push ---------------------------------------------------------------

    @Test
    void elDetalleMarcaALosConvocadosQueHanJustificado() {
        ConvocatoriaResponse creada = service.crear(ENTRENADOR, request(30L, "09:30", List.of(100L, 101L)));
        justificar(30, 101, "Examen");

        ConvocatoriaResponse detalle = service.obtenerPorId(ENTRENADOR, creada.getId());

        assertThat(detalle.getJugadores())
                .extracting(ConvocatoriaJugadorResponse::getJugadorId,
                        ConvocatoriaJugadorResponse::isAusenciaJustificada,
                        ConvocatoriaJugadorResponse::getMotivoAusencia)
                .containsExactly(
                        org.assertj.core.groups.Tuple.tuple(100L, false, null),
                        org.assertj.core.groups.Tuple.tuple(101L, true, "Examen"));
    }

    @Test
    void elPushDeConvocatoriaLlevaElTipoYElId() {
        when(equipoGestionDao.obtenerUsuariosPorJugador(100L)).thenReturn(List.of(55L));

        ConvocatoriaResponse creada = service.crear(ENTRENADOR, request(30L, "09:30", List.of(100L)));

        ArgumentCaptor<OpcionesPushComunicacion> opciones = ArgumentCaptor.forClass(OpcionesPushComunicacion.class);
        verify(comunicacionService).crearPrivada(any(Comunicacion.class), eq(List.of(55L)), eq(ENTRENADOR),
                opciones.capture());

        assertThat(opciones.getValue().contenidoPush()).isNull();
        assertThat(opciones.getValue().datos())
                .containsEntry("tipo", "CONVOCATORIA")
                .containsEntry("convocatoriaId", String.valueOf(creada.getId()))
                // El día del partido (sábado 24/10/2026) para abrir el calendario en él.
                .containsEntry("fechaPartido", "2026-10-24");
    }

    @Test
    void sinPermisoElPutNoToca() {
        ConvocatoriaResponse creada = service.crear(ENTRENADOR, request(30L, "09:30", List.of(100L)));
        when(equipoGestionDao.puedeGestionarEquipo(2L, EQUIPO)).thenReturn(false);

        assertThatThrownBy(() -> service.actualizar(
                2L, creada.getId(), request(30L, "10:00", List.of(101L))))
                .isInstanceOf(SecurityException.class);

        assertThat(convocados(creada.getId())).containsExactly(100L);
    }
}
