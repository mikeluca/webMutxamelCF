    @Test
    void elPutAnadeYQuitaJugadoresConservandoLosDemas() {
        ConvocatoriaResponse creada = service.crear(ENTRENADOR, request(30L, "09:30", List.of(100L, 101L, 102L)));

        Long idDe101 = convocatoriaJugadorDao.obtenerPorConvocatoriaYJugador(creada.getId(), 101L).getId();

        // Sale el 100; el 101 y el 102 se quedan; entra el 103.
        ConvocatoriaResponse editada = service.actualizar(
                ENTRENADOR, creada.getId(), request(30L, "10:00", List.of(101L, 102L, 103L)));

        assertThat(convocados(creada.getId())).containsExactly(101L, 102L, 103L);
        assertThat(editada.getJugadores()).extracting(ConvocatoriaJugadorResponse::getJugadorId)
                .containsExactly(101L, 102L, 103L);
        assertThat(editada.getHoraConvocatoria()).isEqualTo("10:00");

        // Los que se quedan conservan su fila (no se borra y se vuelve a insertar).
        assertThat(convocatoriaJugadorDao.obtenerPorConvocatoriaYJugador(creada.getId(), 101L).getId())
                .isEqualTo(idDe101);
    }

