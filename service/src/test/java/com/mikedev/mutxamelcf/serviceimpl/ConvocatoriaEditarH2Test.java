    private ComunicacionService comunicacionService;
    private PartidoDao partidoDao;
    private ConvocatoriaDaoImpl convocatoriaDao;

    @BeforeEach
    void setUp() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(
                "jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=Oracle;DB_CLOSE_DELAY=-1", "sa", ""));

        jdbc.execute("""
                CREATE TABLE PARTIDOS (
                    ID NUMBER PRIMARY KEY, DIA DATE, RIVAL VARCHAR2(150), CAMPO VARCHAR2(150), HORA VARCHAR2(10))""");
        jdbc.execute("""
                CREATE TABLE CONVOCATORIAS (
                    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    EQUIPO_ID NUMBER NOT NULL,
                    PARTIDO_ID NUMBER NOT NULL,
                    HORA_CONVOCATORIA VARCHAR2(10),
                    LUGAR_CONVOCATORIA VARCHAR2(150),
                    USUARIO_ENTRENADOR_ID NUMBER,
                    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP)""");
        EsquemaH2.crear(jdbc);

        jdbc.update("INSERT INTO PARTIDOS (ID, DIA, RIVAL, CAMPO, HORA) VALUES (30, ?, 'Pego', 'Municipal', '11:00')",
                Date.valueOf(LocalDate.of(2026, 10, 24)));
        jdbc.update("INSERT INTO PARTIDOS (ID, DIA, RIVAL, CAMPO, HORA) VALUES (31, ?, 'Elx', 'Municipal', '12:00')",
                Date.valueOf(LocalDate.of(2026, 10, 25)));

        equipoGestionDao = mock(EquipoGestionDao.class);
        comunicacionService = mock(ComunicacionService.class);
        when(equipoGestionDao.existeEquipo(EQUIPO)).thenReturn(true);
        when(equipoGestionDao.puedeGestionarEquipo(ENTRENADOR, EQUIPO)).thenReturn(true);
        when(equipoGestionDao.obtenerJugadoresPorEquipo(EQUIPO)).thenReturn(List.of(100L, 101L, 102L, 103L));
        when(equipoGestionDao.obtenerNombreJugador(anyLong())).thenAnswer(i -> "Jugador " + i.getArgument(0));
        when(equipoGestionDao.obtenerUsuariosPorJugador(anyLong())).thenReturn(List.of());
        when(equipoGestionDao.obtenerUsuariosFamiliaresPorJugador(anyLong())).thenReturn(List.of());

        partidoDao = mock(PartidoDao.class);
        when(partidoDao.obtenerPorId(30L)).thenReturn(partido(30L, LocalDate.of(2026, 10, 24), "Pego"));
        when(partidoDao.obtenerPorId(31L)).thenReturn(partido(31L, LocalDate.of(2026, 10, 25), "Elx"));

        convocatoriaDao = org.mockito.Mockito.spy(new ConvocatoriaDaoImpl(jdbc));
        convocatoriaJugadorDao = new ConvocatoriaJugadorDaoImpl(jdbc);
        justificacionDao = new JustificacionFaltaPartidoDaoImpl(jdbc);

        service = new ConvocatoriaServiceImpl(
                convocatoriaDao,
                convocatoriaJugadorDao,
                equipoGestionDao,
                partidoDao,
                comunicacionService,
                justificacionDao,
                java.time.Clock.fixed(
                        LocalDate.of(2026, 10, 21).atTime(12, 0).atZone(java.time.ZoneId.of("Europe/Madrid")).toInstant(),
                        java.time.ZoneId.of("Europe/Madrid")));
    }

    private static Partido partido(Long id, LocalDate dia, String rival) {
        Partido partido = new Partido();
        partido.setId(id);
        partido.setEquipoId(EQUIPO);
        partido.setRival(rival);
        partido.setDia(Date.valueOf(dia));
        partido.setHora("11:00");
        return partido;
    }

    private static ConvocatoriaGuardarRequest request(Long partidoId, String hora, List<Long> jugadores) {
        ConvocatoriaGuardarRequest request = new ConvocatoriaGuardarRequest();
        request.setPartidoId(partidoId);
        request.setHoraConvocatoria(hora);
        request.setLugarConvocatoria("Vestuarios");
        request.setJugadoresIds(jugadores);
        return request;
    }

    private void justificar(long partidoId, long jugadorId, String motivo) {
        JustificacionFaltaPartido j = new JustificacionFaltaPartido();
        j.setPartidoId(partidoId);
        j.setJugadorId(jugadorId);
        j.setUsuarioAppId(7L);
        j.setMotivo(motivo);
        j.setFechaCreacion(LocalDateTime.of(2026, 10, 21, 10, 0));
        justificacionDao.crear(j);
    }

    private List<Long> convocados(Long convocatoriaId) {
        return convocatoriaJugadorDao.obtenerPorConvocatoria(convocatoriaId).stream()
                .map(ConvocatoriaJugador::getJugadorId).toList();
    }

    // ---- crear -------------------------------------------------------------------------

    @Test
    void crearRechazaAUnJugadorConAusenciaJustificadaConSuNombre() {
        justificar(30, 101, "Examen");

        assertThatThrownBy(() -> service.crear(ENTRENADOR, request(30L, "09:30", List.of(100L, 101L))))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("Jugador 101")
                .hasMessageContaining("ausencia");

        // No se ha creado nada.
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM CONVOCATORIAS", Integer.class)).isZero();
    }

    @Test
    void laAusenciaDeOtroPartidoNoImpideConvocar() {
        justificar(31, 101, "Examen");

        ConvocatoriaResponse creada = service.crear(ENTRENADOR, request(30L, "09:30", List.of(100L, 101L)));

        assertThat(convocados(creada.getId())).containsExactly(100L, 101L);
    }

