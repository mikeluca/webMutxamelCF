        partido(44L, PRIMER_EQUIPO, "R5", DIA.minusDays(2), "LIGA", 3, false, 1, 2, false);         // P
        partido(45L, PRIMER_EQUIPO, "R6", DIA.minusDays(40), "LIGA", 0, true, 5, 0, false);         // el sexto: fuera
        partido(46L, PRIMER_EQUIPO, "Cancelado", DIA.minusDays(1), "LIGA", 4, true, 1, 0, true);    // cancelado: fuera
        partido(47L, PRIMER_EQUIPO, "SinResultado", DIA.minusDays(3), "LIGA", 5, true, null, null, false);
        partido(48L, PRIMER_EQUIPO, "Futuro", DIA.plusDays(7), "LIGA", 10, true, 3, 3, false);      // posterior: fuera
        partido(49L, OTRO_EQUIPO, "Otro equipo", DIA.minusDays(4), "LIGA", 6, true, 9, 0, false);   // otro equipo: fuera

        List<FichaPartidoDTO.FormaFicha> forma = ficha().forma();

        assertThat(forma).extracting(FichaPartidoDTO.FormaFicha::partidoId).containsExactly(44L, 43L, 42L, 41L, 40L);
        assertThat(forma).extracting(FichaPartidoDTO.FormaFicha::resultado).containsExactly("P", "G", "P", "E", "G");
        assertThat(forma.get(0).rival()).isEqualTo("R5");
        assertThat(forma.get(0).local()).isFalse();
        assertThat(forma.get(0).golesFavor()).isEqualTo(1);
        assertThat(forma.get(0).golesContra()).isEqualTo(2);
        assertThat(forma.get(0).dia()).isEqualTo(DIA.minusDays(2));

        // Con resultado guardado, el propio partido encabeza la forma (día igual al suyo).
