        partido(40L, PRIMER_EQUIPO, "R1", DIA.minusDays(30), "LIGA", 1, true, 2, 0, false);        // G
        partido(41L, PRIMER_EQUIPO, "R2", DIA.minusDays(23), "AMISTOSO", null, false, 1, 1, false); // E
