    private void partido(Long id, Long equipo, String rival, LocalDate dia, String tipo, Integer jornada,
            boolean local, Integer golesFavor, Integer golesContra, boolean cancelado) {
        jdbc.update("INSERT INTO PARTIDOS (ID, EQUIPO_ID, RIVAL, DIA, HORA, TIPO, JORNADA, ES_LOCAL, GOLES_FAVOR,"
                + " GOLES_CONTRA, CANCELADO) VALUES (?, ?, ?, ?, '18:00', ?, ?, ?, ?, ?, ?)",
                id, equipo, rival, Date.valueOf(dia), tipo, jornada, local ? 1 : 0, golesFavor, golesContra,
                cancelado ? 1 : 0);
    }

    private void jugador(long id, int dorsal, String nombre, String apellidos, String retransmision, Integer anio,
            Long equipoId, byte[] foto) {
        jdbc.update("INSERT INTO JUGADORES (ID, DORSAL, NOMBRE, APELLIDOS, NOMBRE_RETRANSMISION, ANIO_NACIMIENTO,"
                + " EQUIPO_ID, FOTO) VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
                id, dorsal, nombre, apellidos, retransmision, anio, equipoId, foto);
    }

    private void evento(String tipo, Long jugador, Long entra, String autorTexto, Integer minuto, boolean anulado) {
        reloj = reloj.plusMinutes(1);
        jdbc.update("INSERT INTO PARTIDO_LIVE_EVENTOS (PARTIDO_ID, TIPO, JUGADOR_ID, JUGADOR_ENTRA_ID, AUTOR_TEXTO,"
                + " USUARIO_APP_ID, FECHA, ANULADO, MINUTO) VALUES (?, ?, ?, ?, ?, 7, ?, ?, ?)",
                PARTIDO, tipo, jugador, entra, autorTexto, java.sql.Timestamp.valueOf(reloj), anulado ? 1 : 0, minuto);
    }

    private static byte[] foto() throws Exception {
        BufferedImage imagen = new BufferedImage(40, 40, BufferedImage.TYPE_INT_RGB);
        ByteArrayOutputStream salida = new ByteArrayOutputStream();
        ImageIO.write(imagen, "png", salida);
        return salida.toByteArray();
    }

