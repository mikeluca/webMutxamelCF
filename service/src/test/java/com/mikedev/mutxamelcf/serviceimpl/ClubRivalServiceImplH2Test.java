    private static byte[] png(int ancho, int alto, boolean transparenteEnLaEsquina) {
        BufferedImage imagen = new BufferedImage(ancho, alto, BufferedImage.TYPE_INT_ARGB);

        for (int x = 0; x < ancho; x++) {
            for (int y = 0; y < alto; y++) {
                boolean fuera = transparenteEnLaEsquina && x < ancho / 4 && y < alto / 4;
                imagen.setRGB(x, y, fuera ? 0x00000000 : 0xFFCC1122);
            }
        }

        return escribir(imagen, "png");
    }

    private static byte[] jpg(int ancho, int alto) {
        BufferedImage imagen = new BufferedImage(ancho, alto, BufferedImage.TYPE_INT_RGB);

        for (int x = 0; x < ancho; x++) {
            for (int y = 0; y < alto; y++) {
                imagen.setRGB(x, y, 0x2255AA);
            }
        }

        return escribir(imagen, "jpg");
    }

    private static byte[] escribir(BufferedImage imagen, String formato) {
        try {
            ByteArrayOutputStream salida = new ByteArrayOutputStream();
            ImageIO.write(imagen, formato, salida);
            return salida.toByteArray();
        } catch (java.io.IOException e) {
            throw new IllegalStateException(e);
        }
    }

    private static BufferedImage leer(byte[] png) throws Exception {
        return ImageIO.read(new ByteArrayInputStream(png));
    }

    @Test
    void subirUnPngLoReducePorElLadoLargoConservaLaTransparenciaYLoGuardaComoPng() throws Exception {
        Long id = clubDao.crear("Pego C.F.", null);

        service.subirEscudo(id, png(800, 400, true));

        byte[] guardado = service.obtenerEscudo(id);
        assertThat(guardado).startsWith((byte) 0x89, 'P', 'N', 'G');

        BufferedImage imagen = leer(guardado);
        assertThat(imagen.getWidth()).isEqualTo(256);
        assertThat(imagen.getHeight()).isEqualTo(128);
        // La esquina transparente sigue transparente; el resto, opaco.
        assertThat(imagen.getRGB(2, 2) >>> 24).isZero();
        assertThat(imagen.getRGB(200, 100) >>> 24).isEqualTo(255);

        ClubRival club = clubDao.obtenerPorId(id);
        assertThat(club.isTieneEscudo()).isTrue();
        assertThat(club.getEscudoVersion()).isEqualTo(1);
        assertThat(club.getFechaActualizacion()).isNotNull();
    }

