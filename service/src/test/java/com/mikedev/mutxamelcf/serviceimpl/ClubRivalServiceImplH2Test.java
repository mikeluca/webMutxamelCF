    @Test
    void cadaCambioDeEscudoSubeLaVersionYNoSeAdmiteLoQueNoEsUnaImagenOPesaMasDe2Mb() {
        Long id = clubDao.crear("Pego C.F.", null);

        service.subirEscudo(id, png(300, 300, false));
        service.subirEscudo(id, jpg(300, 300));
        assertThat(clubDao.obtenerPorId(id).getEscudoVersion()).isEqualTo(2);

        // Texto, imagen rota y un archivo de más de 2 MB: errores claros y no se toca nada.
        assertThatThrownBy(() -> service.subirEscudo(id, "esto no es una imagen".getBytes()))
                .isInstanceOf(IllegalArgumentException.class).hasMessageContaining("no es una imagen");
        assertThatThrownBy(() -> service.subirEscudo(id, new byte[] { (byte) 0x89, 'P', 'N', 'G', 1, 2 }))
                .isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> service.subirEscudo(id, new byte[2 * 1024 * 1024 + 1]))
                .isInstanceOf(IllegalArgumentException.class).hasMessageContaining("2 MB");
        assertThatThrownBy(() -> service.subirEscudo(id, new byte[0])).isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> service.subirEscudo(999L, png(10, 10, false)))
                .isInstanceOf(IllegalArgumentException.class).hasMessageContaining("no existe");

        assertThat(clubDao.obtenerPorId(id).getEscudoVersion()).isEqualTo(2);
    }

